#!/usr/bin/env python3
"""Write build/shared.mk: how to compile the shared client code into OUR build dir.

The PokeSprite client is its own build. It still needs the game's app, net,
world, UI and embedded-server code, compiled exactly as the main client
compiles it -- same defines, so `struct App` has the same layout on both sides
of every call. src/makefile is the only place that knows those 553 objects,
their per-object flags (unity builds, NEON asm, the Objective-C webview, ...)
and their order, and restating them here would drift.

So src/makefile is READ, never run for real and never edited:
  1. `print-OBJS` / `print-CFLAGS` / `print-LDFLAGS` give the lists and flags.
  2. One `make -n -B` dry run prints the exact compile command of every object.
  3. Each command is replayed from src/ with its output moved into our dir.

    gen_shared_mk.py <out.mk> <objdir> [make VAR=value ...]
"""

import os
import re
import shlex
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src")


def make_print(var, extra):
    probe = os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), "print_var.mk")
    with open(probe, "w") as f:
        f.write("print-%: ; @echo $($*)\n")
    r = subprocess.run(["make", "-s", "-C", SRC, "-f", "makefile", "-f", probe] + extra +
                       ["print-" + var], capture_output=True, text=True, check=True)
    return r.stdout.strip()


def main():
    out_mk, objdir = sys.argv[1], os.path.abspath(sys.argv[2])
    extra = sys.argv[3:]
    src_objdir = make_print("OBJ_DIR", extra)
    objs = make_print("OBJS", extra).split()
    objs = [o for o in objs if os.path.basename(o) != "main.o"]
    cflags = make_print("CFLAGS", extra)
    ldflags = make_print("LDFLAGS", extra)

    dry = subprocess.run(["make", "-n", "-B", "-C", SRC] + extra + objs,
                         capture_output=True, text=True)
    if dry.returncode != 0:
        sys.exit("dry run failed:\n" + dry.stderr[-2000:])
    # Join backslash continuations, then keep each command that writes an object.
    lines, cur = [], ""
    for line in dry.stdout.splitlines():
        if line.endswith("\\"):
            cur += line[:-1] + " "
            continue
        lines.append(cur + line)
        cur = ""
    by_obj = {}
    for line in lines:
        m = re.search(r"\s-o\s+(\S+\.o)(\s|$)", line)
        if not m:
            continue
        target = m.group(1)
        name = os.path.basename(target)
        if os.path.normpath(os.path.join(SRC, target)) not in {
                os.path.normpath(os.path.join(SRC, o)) for o in objs}:
            continue
        by_obj[name] = line.replace(m.group(1), os.path.join(objdir, name), 1)

    missing = [os.path.basename(o) for o in objs if os.path.basename(o) not in by_obj]
    if missing:
        sys.exit("no compile command found for: " + " ".join(missing))

    with open(out_mk, "w") as f:
        f.write("# GENERATED by gen_shared_mk.py from src/makefile (read-only). Do not edit.\n")
        f.write("# src objdir it mirrors: %s; make args: %s\n\n" % (src_objdir, " ".join(extra)))
        f.write("SHARED_CFLAGS := %s\n" % cflags)
        f.write("SHARED_LDFLAGS := %s\n" % ldflags)
        f.write("SHARED_OBJS := %s\n\n" % " ".join(os.path.join(objdir, os.path.basename(o))
                                                  for o in objs))
        f.write("%s:\n\tmkdir -p %s\n\n" % (objdir, objdir))
        for name in sorted(by_obj):
            target = os.path.join(objdir, name)
            f.write("%s: | %s\n\tcd %s && %s\n\n" % (target, objdir, shlex.quote(SRC), by_obj[name]))
    print("%s: %d shared objects (mirroring %s)" % (out_mk, len(by_obj), src_objdir))


if __name__ == "__main__":
    main()
