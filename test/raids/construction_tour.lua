-- construction_tour: the house's whole-house flows on one account. Content:
-- OSRS-Content/osrs239-content/server/scripts/skill_construction/
-- (poh_estate_agent, poh_enter_leave, poh_options).
--
--   1. buy      Varrock estate agent sells the starter house (1,000 coins).
--   2. portals  for each of the nine locations: the estate agent moves the
--               house there (relocate, its fee), the town portal's menu
--               enters it ("Go to your house"), the exit portal leaves; the
--               portal's Build-mode op enters in Building Mode.
--   3. options  House Options (Settings side) turns Building Mode off and on.
--
-- Rooms and furniture are not here: test/raids/construction/<room>.lua
-- (generated by tools/poh_test_gen.py) builds, upgrades, uses and removes
-- every tier of every hotspot in every room; construction_vertical.lua covers
-- stairs and the oubliette; construction_board.lua the advertisement board.
--
--   TORIRS_STDERR_UNBUFFERED=1 ./src/build_<you>_opt/torirsserver --scriptrun \
--       test/raids/construction_tour.lua --bots 1 --name poh --ticks 20000 \
--       --session $S/poh --fixture test/raids/fixtures/fresh_lumbridge.ini
--   python3 tools/raid_gate/run.py construction_tour --no-publish     (live)

-- Location ordinal (construction.constant ^poh_loc_*), its town portal, the
-- tile beside it, and the estate agent's menu rows that pick it
-- (~poh_location_select pages five rows at a time).
local LOCATIONS = {
    { key = "rimmington", id = 1, portal = "poh_rimmington_portal", exit = { 2953, 3224 }, rows = { "Rimmington" } },
    { key = "taverley", id = 2, portal = "poh_taverly_portal", exit = { 2893, 3465 }, rows = { "Taverley" } },
    { key = "pollnivneach", id = 3, portal = "poh_pollnivneach_portal", exit = { 3340, 3003 }, rows = { "Pollnivneach" } },
    { key = "hosidius", id = 8, portal = "poh_kourend_portal", exit = { 1742, 3517 }, rows = { "Hosidius" } },
    { key = "rellekka", id = 4, portal = "poh_rellekka_portal", exit = { 2670, 3631 }, rows = { "More locations", "Rellekka" } },
    { key = "aldarin", id = 13, portal = "poh_aldarin_portal", exit = { 1422, 2964 }, rows = { "More locations", "Aldarin" } },
    { key = "brimhaven", id = 5, portal = "poh_brimhaven_portal", exit = { 2757, 3178 }, rows = { "More locations", "Brimhaven" } },
    { key = "yanille", id = 6, portal = "poh_yanille_portal", exit = { 2544, 3099 }, rows = { "More locations", "Yanille" } },
    { key = "prifddinas", id = 9, portal = "poh_prifddinas_portal", exit = { 3239, 6079 }, rows = { "More locations", "More locations", "Prifddinas" } },
}

-- Varrock's estate agent stands in the house-agency building east of the square.
local AGENT_TILE = "0_50_54_40_19" -- 3240,3475


return {
    id = "construction_tour",
    fixture = "fresh_lumbridge.ini",
    frames = 200000,
    setup = {
        "::clearinv",
        "::maxstats",
        "::give coins 5000000",
        "::give hammer 1",
        "::give poh_saw 1",
    },

    run = function(t)
        local H = {}

        function H.tile()
            local r, tl = t.world.tile()
            if r ~= "ok" or tl == nil then
                return { x = -1, z = -1, level = -1 }
            end
            return tl
        end
        function H.tile_str(tl)
            return tostring(tl.x) .. "," .. tostring(tl.z) .. " L" .. tostring(tl.level)
        end
        function H.inside()
            return H.tile().x >= 6400
        end
        function H.count(name)
            local _, n = t.inv.count(name)
            return n or 0
        end
        function H.server(name)
            local r, v = t.var.server(name)
            return r == "ok" and v or -1
        end
        function H.tele(coord)
            local r, d = t.cheat("::tele " .. coord, false)
            t.ticks(3)
            return r, d
        end
        function H.coord_of(x, z)
            return string.format("0_%d_%d_%d_%d", x // 64, z // 64, x % 64, z % 64)
        end
        -- Every copy of `sym` placed within `radius`.
        function H.copies(sym, radius)
            local r, _, rows = t.world.loc_copies(sym, radius or 64)
            if r ~= "ok" or rows == nil then
                return {}
            end
            return rows
        end
        -- The house's grid origin: the instance square the player stands in
        -- (map_instance_alloc hands out whole 64x64 squares). Not the exit
        -- portal -- Building Mode has none.
        function H.base()
            local tl = H.tile()
            if tl.x < 6400 then
                return nil
            end
            return { x = (tl.x // 64) * 64, z = (tl.z // 64) * 64, level = tl.level }
        end
        -- A grid room's 8x8 square, in world tiles.
        -- Answer a p_choice by the start of its row text.
        function H.choose(prefix)
            return t.chat.play({ "options", "choose:/^" .. prefix:gsub("%p", "%%%0") .. "/" })
        end
        function H.last_messages(n)
            local _, last = t.msg.last(n or 3)
            local text = {}
            for i = 1, #(last or {}) do
                text[#text + 1] = tostring(last[i].text)
            end
            return table.concat(text, " / ")
        end
        -- Wait for a p_choice page; on a miss, the row says what the game said.
        function H.await_choice(tag, ticks)
            for _ = 1, ticks or 4 do
                if t.chat.kind() == "options" then
                    return true
                end
                t.ticks(1)
            end
            t.check(tag, false, "no choice page; last messages: " .. H.last_messages(4))
            return false
        end
        function H.press(sym, sub)
            local r, w = t.ui.widget(sym, sub)
            if r ~= "ok" then
                return r, "ui.widget " .. tostring(sym) .. " " .. tostring(w)
            end
            return t.ui.invoke(w, 1)
        end

        -- House Options from the Settings side panel.
        function H.options_open(tag)
            t.exec(tag .. ".settings_tab", t.ui.tab, "settings")
            t.exec(tag .. ".options", H.press, "settings_side:houseoptions")
            return t.expect(tag .. ".options_panel", t.ui.await_open("poh_options", 5))
        end
        function H.options_leave(tag)
            if H.options_open(tag) == "ok" then
                t.exec(tag .. ".leave_house", H.press, "poh_options:leave_house")
            end
            t.ticks(3)
        end
        -- A step that left the player inside a house strands every later one:
        -- leave it by cheat and say so in the ledger.
        function H.recover(tag)
            if H.inside() then
                t.note(tag .. ": still inside a house -- ::pohleave to continue")
                t.cheat("::pohleave", false)
                t.ticks(3)
            end
        end

        -- ------------------------------------------------------------ 1. buy
        H.tele(AGENT_TILE)
        local agent_r, agent_d = t.npc.by_symbol("poh_estate_agent")
        t.check("buy.agent_present", agent_r == "ok", tostring(agent_d))
        t.exec("buy.talk", t.player.talk_to, "poh_estate_agent", 1)
        t.exec("buy.dialogue", t.chat.play, {
            "npc:Welcome to the Housing Agency",
            "choose:I'd like to buy a house.",
            "npc:starting house in Rimmington",
            "npc:redecorated in other styles",
            "npc:Do you want to buy a starter house?",
            "choose:Yes please!",
            "npc:Go through the Rimmington house portal",
        })
        t.check("buy.location", H.server("varb2187_poh_house_location") == 1,
            "house location varbit " .. tostring(H.server("varb2187_poh_house_location")))
        if H.server("varb2187_poh_house_location") ~= 1 then
            t.blocked("no house was bought; every later step needs one")
            return
        end

        -- -------------------------------------------------------- 2. portals
        local current = 1
        for li = 1, #LOCATIONS do
            local loc = LOCATIONS[li]
            local tag = "portal." .. loc.key
            if loc.id ~= current then
                H.tele(AGENT_TILE)
                local coins_before = H.count("coins")
                t.exec(tag .. ".agent", t.player.talk_to, "poh_estate_agent", 3) -- Relocate
                local script = { "npc:Where would you like your house moved?" }
                for ri = 1, #loc.rows do
                    script[#script + 1] = "choose:/^" .. loc.rows[ri] .. "/"
                end
                script[#script + 1] = "npc:That move will cost"
                script[#script + 1] = "choose:Yes, move my house."
                script[#script + 1] = "npc:Your house has been moved."
                t.exec(tag .. ".relocate", t.chat.play, script)
                local now = H.server("varb2187_poh_house_location")
                t.check(tag .. ".moved", now == loc.id, "location varbit " .. tostring(now) .. " want " .. loc.id
                    .. ", paid " .. tostring(coins_before - H.count("coins")))
                current = now
            end
            -- Enter through the portal's own menu (op 1), then leave by the exit portal.
            H.tele(H.coord_of(loc.exit[1], loc.exit[2]))
            local near_r, near_d = t.world.loc_near(loc.portal, 12)
            t.check(tag .. ".portal_present", near_r == "ok", tostring(near_d))
            t.exec(tag .. ".menu", t.player.click_loc, loc.portal, 1)
            t.exec(tag .. ".go_home", H.choose, "Go to your house")
            t.ticks(4)
            local inside_tile = H.tile()
            t.check(tag .. ".inside", inside_tile.x >= 6400, "at " .. H.tile_str(inside_tile))
            t.check(tag .. ".not_building", H.server("varb2176_poh_building_mode") == 0,
                "building mode " .. tostring(H.server("varb2176_poh_building_mode")))
            t.exec(tag .. ".leave", t.player.click_loc, "poh_exit_portal", 1)
            t.ticks(3)
            local out = H.tile()
            local dx, dz = math.abs(out.x - loc.exit[1]), math.abs(out.z - loc.exit[2])
            t.check(tag .. ".outside", out.x < 6400 and dx <= 6 and dz <= 6,
                "at " .. H.tile_str(out) .. ", portal side " .. loc.exit[1] .. "," .. loc.exit[2])
            H.recover(tag)
            -- The Build-mode op enters in Building Mode.
            t.exec(tag .. ".build_mode", t.player.click_loc, loc.portal, 3)
            t.ticks(4)
            t.check(tag .. ".build_inside", H.inside() and H.server("varb2176_poh_building_mode") == 1,
                "at " .. H.tile_str(H.tile()) .. " building " .. tostring(H.server("varb2176_poh_building_mode")))
            -- Building Mode has no exit portal (poh_construct.rs2 ~poh_place_exit_portal):
            -- the garden centrepiece is a hotspot, so the way out is House Options.
            H.options_leave(tag .. ".build_leave")
            t.check(tag .. ".build_outside", not H.inside(), "at " .. H.tile_str(H.tile()))
            H.recover(tag)
        end

        -- -------------------------------------------------------- 3. options
        -- The house is in Prifddinas now; enter it there in Building Mode.
        local home = LOCATIONS[#LOCATIONS]
        H.tele(H.coord_of(home.exit[1], home.exit[2]))
        t.exec("options.enter", t.player.click_loc, home.portal, 3)
        t.ticks(4)
        t.check("options.inside", H.inside(), "at " .. H.tile_str(H.tile()))
        H.options_open("options")
        t.exec("options.build_off", H.press, "poh_options:build_mode_off")
        t.ticks(4)
        t.check("options.off", H.server("varb2176_poh_building_mode") == 0,
            "building mode " .. tostring(H.server("varb2176_poh_building_mode")))
        t.exec("options.build_on", H.press, "poh_options:build_mode_on")
        t.ticks(4)
        t.check("options.on", H.server("varb2176_poh_building_mode") == 1,
            "building mode " .. tostring(H.server("varb2176_poh_building_mode")))

        H.options_leave("done.leave")
        t.check("done.outside", not H.inside(), "at " .. H.tile_str(H.tile()))
        t.finish(0)
    end,
}
