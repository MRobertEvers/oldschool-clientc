                local on = math.floor(st.var / (2 ^ vb[1])) % 2
                set("::setvar " .. vb[2] .. " " .. on)
            end
            set("::setvar varp176_dragonquest " .. st.stage)
            local r, j = t.ui.journal_open("Dragon Slayer I")
            if r == "ok" then
                t.ui.journal_close()
            end
            local lines = (r == "ok" and j and j.lines) or {}
            local diff = nil
            for i = 1, math.max(#st.rows, #lines) do
                if lines[i] ~= (st.rows[i] and plain_read(st.rows[i])) then
