#!/usr/bin/env python3
"""Generate 3rd/rsprot/packets/update_inv_full.{h,c}: every revision's layout.

UPDATE_INV_FULL is outside the main generators (HAND_WRITTEN_PROTS): the
Kotlin reads slots through accessors on a packed value and clamps the count
with an escape field. Those idioms are the same at every revision; what moves
is the per-slot ORDER (id first, or count first) and each field's transform,
which Jagex reshuffles every revision. This script reads exactly that from the
sources and writes one function per distinct layout:

    revisions 221-239  RSProt   UpdateInvFullEncoder.kt (the non-null path)
    revisions 240-241  RSProx   UpdateInvFullDecoder.kt

    python3 tools/rsprot_gen_inv_full.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rsprox_prot  # noqa: E402

REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "3rd", "rsprot", "packets")
RSPROT = os.path.expanduser("~/Documents/git_repos/rsprot")
RSPROT_REVS = range(221, 240)
RSPROX_REVS = range(240, 242)

MACRO = {"1": "U1", "2": "U2", "4": "U4"}


def macro(call):
    """p2Alt1 / g2Alt1 -> U2_ALT1."""
    m = re.fullmatch(r"[pg]([124])(Alt([123]))?", call)
    assert m, call
    return MACRO[m.group(1)] + ("_ALT" + m.group(3) if m.group(3) else "")


def find(root, rev, cls):
    for d, _dirs, files in os.walk(os.path.join(root, "protocol", "osrs-%d" % rev)):
        if cls + ".kt" in files:
            return os.path.join(d, cls + ".kt")
    raise SystemExit("rev %d: no %s under %s" % (rev, cls, root))


def body(path, fn):
    src = open(path).read()
    i = src.index("override fun " + fn)
    return src[i:src.index("\n    }\n", i)]


def rsprot_layout(rev):
    """The encoder's non-null slot: three writes, (count, long count, id) or
    (id, count, long count)."""
    text = body(find(RSPROT, rev, "UpdateInvFullEncoder"), "encode")
    loop = text[text.index("for ("):]
    loop = loop[loop.index("continue"):]
    calls = re.findall(r"buffer\.(p[124](?:Alt[123])?)\(", loop)
    assert len(calls) == 3, (rev, calls)
    if calls[0].startswith("p2"):
        return ("id", macro(calls[0]), macro(calls[1]), macro(calls[2]))
    return ("count", macro(calls[2]), macro(calls[0]), macro(calls[1]))


def rsprox_layout(rev):
    text = body(find(rsprox_prot.RSPROX, rev, "UpdateInvFullDecoder"), "decode")
    loop = text[text.index("for (i in 0..<capacity)"):]
    reads = re.findall(r"(id|count) = buffer\.(g[124](?:Alt[123])?)\(\)", loop)
    assert len(reads) == 3, (rev, reads)
    fields = {}
    for name, call in reads:
        fields.setdefault(name, []).append(macro(call))
    first = reads[0][0]
    return (first, fields["id"][0], fields["count"][0], fields["count"][1])


def slot_lines(layout):
    first, id_m, count_m, long_m = layout
    count = [
        "        /* One byte, saturating at 255; at 255 the real count follows. */",
        "        RSPROT_CLAMP(x, %s, slot->count_lo, slot->count, 255);" % count_m,
        "        if (RSPROT_BRANCH(x, slot->count_lo) == 255)",
        "            RSPROT_%s(x, slot->count);" % long_m,
    ]
    ident = [
        "        /* The wire carries id + 1: 0 is an empty slot, id -1 here. */",
        "        RSPROT_XFORM(x, %s, slot->id, 1);" % id_m,
    ]
    return ident + count if first == "id" else count + ident


def describe(layout):
    first, id_m, count_m, long_m = layout
    parts = ["id %s" % id_m, "count %s [%s]" % (count_m, long_m)]
    return ", ".join(parts if first == "id" else parts[::-1])


def ranges(revs):
    out = []
    for r in sorted(revs):
        if out and out[-1][1] == r - 1:
            out[-1][1] = r
        else:
            out.append([r, r])
    return ", ".join(str(a) if a == b else "%d-%d" % (a, b) for a, b in out)


HEADER = '''#ifndef RSPROT_PACKET_UPDATE_INV_FULL_H
#define RSPROT_PACKET_UPDATE_INV_FULL_H

/*
 * UPDATE_INV_FULL -- server -> client. A whole container, slot by slot.
 *
 * GENERATED by tools/rsprot_gen_inv_full.py -- do not edit. The main
 * generators refuse this prot (HAND_WRITTEN_PROTS in tools/rsprot_gen_codec.py):
 * the Kotlin reads slots through accessors on a packed value and clamps a
 * count with an escape field. Those idioms are the same at every revision; the
 * slot ORDER and each field's transform are not, and that is all the script
 * reads (RSProt's encoder for 221-239, RSProx's decoder for 240-241).
 *
 * ## The empty slot is not a special layout
 *
 * RSProt writes `if (obj == InventoryObject.NULL) { <count 0>; <id 0>; continue }`,
 * which reads like a second layout and is not one: the general path for
 * `count = 0, id = -1` emits exactly those bytes (the clamp of 0 is 0, no
 * escape follows, and the id + 1 offset turns -1 into 0). So each layout has
 * ONE path.
 *
 * The offset direction is the trap: get it backwards and every item in the
 * container shifts by one, which renders perfectly and is wrong everywhere.
 */

#include "../include/rsprot_exec.h"

/** One slot. `id` is -1 for an empty slot; `count_lo` is the derived one-byte
 *  count the wire carries, and is meaningful only next to `count`. */
typedef struct MsgUpdateInvFullSlot
{
    int32_t count_lo;
    int32_t count;
    int32_t id;
} MsgUpdateInvFullSlot;

typedef struct MsgUpdateInvFull
{
    int32_t combined_id;
    int32_t inventory_id;
    /** Slot count, ON the wire -- unlike UPDATE_INV_PARTIAL's, which is not. */
    int32_t capacity;
    MsgUpdateInvFullSlot *slots;
} MsgUpdateInvFull;

/** Caller-supplied `slots` capacity. The wire's own field is two bytes, so a
 *  malformed packet can ask for up to 65535; the codec fails past this. */
#define MSG_UPDATE_INV_FULL_MAX_SLOTS 4096

'''


def main():
    by_rev = {r: rsprot_layout(r) for r in RSPROT_REVS}
    by_rev.update({r: rsprox_layout(r) for r in RSPROX_REVS})
    versions = []
    for r in sorted(by_rev):
        if by_rev[r] not in versions:
            versions.append(by_rev[r])
    num = {v: i + 1 for i, v in enumerate(versions)}
    revs_of = {v: [r for r in by_rev if by_rev[r] == v] for v in versions}

    h = [HEADER]
    c = ["/* UPDATE_INV_FULL. GENERATED by tools/rsprot_gen_inv_full.py -- do not edit. */",
         '#include "update_inv_full.h"', ""]
    for v in versions:
        note = "/* v%d -- revs %s: %s. */" % (num[v], ranges(revs_of[v]), describe(v))
        h.append(note)
        h.append("void packet_update_inv_full_v%d_out(RsprotExec *x, MsgUpdateInvFull *m);" % num[v])
        c += [note, "void", "packet_update_inv_full_v%d_out(RsprotExec *x, MsgUpdateInvFull *m)" % num[v],
              "{", "    RSPROT_COM(x, m->combined_id);", "    RSPROT_U2(x, m->inventory_id);",
              "    RSPROT_COUNT2(x, m->capacity, MSG_UPDATE_INV_FULL_MAX_SLOTS);",
              "    for (int32_t i = 0; i < m->capacity; i++) {",
              "        MsgUpdateInvFullSlot *slot = &m->slots[i];"]
        c += slot_lines(v)
        c += ["    }", "}", ""]
    h.append("")
    for r in sorted(by_rev):
        h.append("#define packet_update_inv_full_osrs%d_out packet_update_inv_full_v%d_out"
                 % (r, num[by_rev[r]]))
    h += ["", "extern const RsprotVersionRange rsprot_update_inv_full_out[];",
          "extern const int rsprot_update_inv_full_out_count;", "", "#endif", ""]
    rows = []
    for r in sorted(by_rev):
        if rows and rows[-1][1] == r - 1 and rows[-1][2] == num[by_rev[r]]:
            rows[-1][1] = r
        else:
            rows.append([r, r, num[by_rev[r]]])
    c.append("const RsprotVersionRange rsprot_update_inv_full_out[] = {")
    c += ["    { %d, %d, (RsprotCodecFn)packet_update_inv_full_v%d_out }," % tuple(row) for row in rows]
    c += ["};", "",
          "const int rsprot_update_inv_full_out_count =",
          "    (int)(sizeof(rsprot_update_inv_full_out) / sizeof(rsprot_update_inv_full_out[0]));", ""]
    with open(os.path.join(OUT, "update_inv_full.h"), "w") as fh:
        fh.write("\n".join(h))
    with open(os.path.join(OUT, "update_inv_full.c"), "w") as fh:
        fh.write("\n".join(c))
    print("%d layouts over revisions %d-%d" % (len(versions), min(by_rev), max(by_rev)))


if __name__ == "__main__":
    main()
