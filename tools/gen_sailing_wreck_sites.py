#!/usr/bin/env python3
"""Generate the shipwreck site pools from the cache's own map placements.

Every salvageable wreck site is placed in the map files as its SUNKEN form
(`sailing_<kind>_shipwreck_stump`, configs/all.loc) at its real angle -- the
OSRS wiki "Small shipwreck" pins (3095,2928 .. 3132,2951; 1574,3326 ..) are
exactly the cache's stump tiles. Sites of one kind within CLUSTER tiles of
each other form one area: a shared pool (wiki "Salvaging": "Each area has a
shared spawn pool"). Writes
OSRS-Content/osrs-content/server/scripts/sailing/scripts/sailing_wreck_sites.rs2.

    python3 tools/gen_sailing_wreck_sites.py
"""

import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "OSRS-Content", "osrs-content")
OUT = os.path.join(CONTENT, "server", "scripts", "sailing", "scripts", "sailing_wreck_sites.rs2")
KINDS = ["small", "fisherman", "barracuda", "large", "pirate", "mercenary", "fremennik", "merchant"]
CLUSTER = 64


def loc_ids():
    """Loc symbol -> id: configs/all.loc.compack, the cache's own `id=name`
    member list (where every loc id in this tree comes from)."""
    path = os.path.join(CONTENT, "configs", "all.loc.compack")
    ids = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"^(\d+)=(\S+)$", line.strip())
            if m:
                ids[m.group(2)] = int(m.group(1))
    if not ids:
        sys.exit("no loc ids in " + path)
    return ids


def coord(level, x, z):
    return "%d_%d_%d_%d_%d" % (level, x // 64, z // 64, x % 64, z % 64)


def main():
    ids = loc_ids()
    stump_of = {}
    for kind in KINDS:
        sym = "sailing_%s_shipwreck_stump" % kind
        if sym not in ids:
            sys.exit("no loc id for " + sym)
        stump_of[ids[sym]] = kind
    sites = {k: [] for k in KINDS}
    for path in sorted(glob.glob(os.path.join(CONTENT, "maps", "m*.jl2"))):
        m = re.search(r"m(\d+)_(\d+)\.jl2$", path)
        mx, mz = int(m.group(1)), int(m.group(2))
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                mm = re.match(r"^(\d+) (\d+) (\d+): (\d+) ", line)
                if mm and int(mm.group(4)) in stump_of:
                    sites[stump_of[int(mm.group(4))]].append(
                        (int(mm.group(1)), mx * 64 + int(mm.group(2)), mz * 64 + int(mm.group(3))))
    areas = []
    for kind in KINDS:
        clusters = []
        for site in sorted(sites[kind]):
            home = None
            for c in clusters:
                if any(max(abs(site[1] - q[1]), abs(site[2] - q[2])) <= CLUSTER for q in c):
                    home = c
                    break
            if home is None:
                clusters.append([site])
            else:
                home.append(site)
        for c in clusters:
            areas.append((kind, c))

    out = [
        "// GENERATED by tools/gen_sailing_wreck_sites.py -- do not edit by hand.",
        "// Shipwreck site pools: every site the cache's maps place a sunken wreck",
        "// on, grouped by kind into areas (sailing_wrecks.rs2 raises and sinks them).",
        "",
        "[proc,sailing_wreck_area_count]()(int)",
        "return(%d);" % len(areas),
        "",
        "[proc,sailing_wreck_area_size](int $area)(int)",
        "switch_int ($area) {",
    ]
    for i, (kind, c) in enumerate(areas):
        out.append("    case %d : return(%d);" % (i, len(c)))
    out += ["}", "return(0);", "", "// The area's wreck (raised) and its sunken form.",
            "[proc,sailing_wreck_area_locs](int $area)(loc, loc)", "switch_int ($area) {"]
    for i, (kind, c) in enumerate(areas):
        out.append("    case %d : return(sailing_%s_shipwreck, sailing_%s_shipwreck_stump);" % (i, kind, kind))
    out += ["}", "return(null, null);", "", "[proc,sailing_wreck_site](int $area, int $index)(coord)",
            "switch_int (calc($area * 64 + $index)) {"]
    for i, (kind, c) in enumerate(areas):
        for j, (level, x, z) in enumerate(c):
            out.append("    case %d : return(%s);" % (i * 64 + j, coord(level, x, z)))
    out += ["}", "return(null);", "", "// The area a site belongs to, or -1.",
            "[proc,sailing_wreck_area_at](coord $at)(int)", "switch_coord ($at) {"]
    for i, (kind, c) in enumerate(areas):
        for level, x, z in c:
            out.append("    case %s : return(%d);" % (coord(level, x, z), i))
    out += ["}", "return(-1);", ""]
    # A pool is laid out from the squares AROUND its sites too: a hull bought or
    # recovered inside a site square never fires that square's trigger (its
    # latch advances with nobody aboard), and nothing should have to sail out
    # and back for wrecks the wiki says are simply there.
    squares = {}
    for i, (kind, c) in enumerate(areas):
        for level, x, z in c:
            for dx in (-1, 0, 1):
                for dz in (-1, 0, 1):
                    squares.setdefault((level, x // 64 + dx, z // 64 + dz), set()).add(i)
    # A square another file already binds keeps its trigger there: it calls
    # the square's proc below instead (a trigger is declared once).
    taken = {}
    for path in glob.glob(os.path.join(CONTENT, "server", "scripts", "**", "*.rs2"), recursive=True):
        if os.path.abspath(path) == os.path.abspath(OUT) or "/build" in path:
            continue
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = re.match(r"^\[mapzone,(\d+_\d+_\d+)\]", line)
                if m:
                    taken[m.group(1)] = os.path.relpath(path, ROOT)
    out.append("// Entering a square with sites lays out its areas' pools (idempotent).")
    for (level, mx, mz), area_ids in sorted(squares.items()):
        square = "%d_%d_%d" % (level, mx, mz)
        if square in taken:
            out.append("// [mapzone,%s] is %s's: it calls this." % (square, taken[square]))
            out.append("[proc,sailing_wrecks_ensure_%s]" % square)
            print("square %s is bound in %s: call ~sailing_wrecks_ensure_%s from it" % (square, taken[square], square))
        else:
            out.append("[mapzone,%s]" % square)
        for a in sorted(area_ids):
            out.append("~sailing_wrecks_ensure(%d);" % a)
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %d areas, %d sites, %d squares to %s" % (
        len(areas), sum(len(c) for _, c in areas), len(squares), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
