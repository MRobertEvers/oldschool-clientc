#!/usr/bin/env python3
"""Generate the walk set (bas params) a held cargo crate gives its carrier.

Every sailing cargo crate (configs/all.obj category=2294, and the quest
crate prying_times_cargo_crate) is worn in both hands (wearpos=3, wearpos2=5)
and drawn held in front of the body (manwear 59178). The server owns which
walk set a held obj gives (player/scripts/appearance.rs2 ~update_bas reads
the rhand obj's *_baseanim params); the crates stated the bare-handed
human_* set, so a carrier walked with empty arms.

The set given here is the cache's two-handed crate carry --
dttd_carrying_crate_ready / _walk (seq 4193 / 4194) and _walk_fast (10679)
-- the set the cache already gives other carried-in-front objs
(easter19_giant_egg, the league_3 trophies:
skill_combat/configs/bas/attack_anims_modern.obj, from rsmod's objs.toml).
No source names a sailing-only carry set: neither the wiki nor RuneLite's
gameval AnimationID (read 2026-10-16) has one.

Writes OSRS-Content/osrs-content/server/scripts/sailing/configs/
cargo_crates_bas.obj and deletes the *_baseanim lines those crates stated in
server_fields.generated.obj (its rule: a value stated in an authored block
wins, and the generated line is deleted).

    python3 tools/gen_sailing_cargo_bas.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "OSRS-Content", "osrs-content")
OUT = os.path.join(CONTENT, "server", "scripts", "sailing", "configs", "cargo_crates_bas.obj")
GENERATED = os.path.join(CONTENT, "server", "scripts", "_explicit", "configs", "server_fields.generated.obj")
CARGO_CATEGORY = "2294"
EXTRA = ["prying_times_cargo_crate"]
BAS = [
    ("ready_baseanim", "dttd_carrying_crate_ready"),
    ("turnonspot_baseanim", "dttd_carrying_crate_walk"),
    ("walk_f_baseanim", "dttd_carrying_crate_walk"),
    ("walk_b_baseanim", "dttd_carrying_crate_walk"),
    ("walk_l_baseanim", "dttd_carrying_crate_walk"),
    ("walk_r_baseanim", "dttd_carrying_crate_walk"),
    ("running_baseanim", "dttd_carrying_crate_walk_fast"),
]


def crates():
    names = []
    name = None
    with open(os.path.join(CONTENT, "configs", "all.obj"), encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"^\[(.+)\]$", line.rstrip("\n"))
            if m:
                name = m.group(1)
            elif name and line.strip() == "category=" + CARGO_CATEGORY:
                names.append(name)
    for extra in EXTRA:
        if extra not in names:
            names.append(extra)
    return names


def main():
    names = crates()
    if len(names) < 400:
        sys.exit("only %d cargo crates in configs/all.obj" % len(names))
    seqs = set()
    with open(os.path.join(CONTENT, "configs", "all.seq"), encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"^\[(.+)\]$", line.rstrip("\n"))
            if m:
                seqs.add(m.group(1))
    for _, seq in BAS:
        if seq not in seqs:
            sys.exit("no seq " + seq + " in configs/all.seq")
    out = ["// GENERATED by tools/gen_sailing_cargo_bas.py -- do not edit by hand.",
           "// The walk set a held cargo crate gives its carrier (see the tool).", ""]
    for name in names:
        out.append("[%s]" % name)
        for param, seq in BAS:
            out.append("param=%s,%s" % (param, seq))
        out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    # The generated layer's baseanim lines for these records are superseded.
    wanted = set(names)
    keys = set(p for p, _ in BAS)
    kept = []
    removed = 0
    block = None
    with open(GENERATED, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^\[(.+)\]$", line.rstrip("\n"))
            if m:
                block = m.group(1)
            elif block in wanted and line.startswith("param="):
                key = line[len("param="):].split(",", 1)[0]
                if key in keys:
                    removed += 1
                    continue
            kept.append(line)
    with open(GENERATED, "w", encoding="utf-8") as f:
        f.writelines(kept)
    print("wrote %d crates to %s; removed %d superseded lines from %s" % (
        len(names), os.path.relpath(OUT, ROOT), removed, os.path.relpath(GENERATED, ROOT)))


if __name__ == "__main__":
    main()
