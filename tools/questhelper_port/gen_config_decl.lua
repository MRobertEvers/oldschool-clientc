-- The Quest Helper plugin definition's `config = {...}` list, from
-- QuestHelperConfig's @ConfigItem metadata (gen/fw.lua, __def.config) and
-- the interface's default methods, through the SAME function the runtime's
-- ConfigManager uses to decide where each keyName is stored
-- (QH.core.config_decl in script/plugins/quest_helper/rt/rl_core.lua). Rerun
-- it after build.sh and paste (or splice) its output into the definition.
--
--   /opt/homebrew/bin/lua tools/questhelper_port/gen_config_decl.lua [out.lua]
--
-- Writes a Lua chunk `return { {key=..., type=..., ...}, ... }` to out.lua
-- or stdout; what is not declared (and why) goes to stderr. Within the
-- client's limits: at most 64 items, key / label / default / choices at most
-- 95 bytes, keys [a-z0-9_], types bool/int/color/string/enum.
local HERE = debug.getinfo(1, "S").source:sub(2):match("^(.*)/") or "."
local ROOT = HERE .. "/../../script/plugins/quest_helper"
local out_path = arg[1]

J = { protect = pcall }
for _, f in ipairs({ "j_core", "j_lang", "j_util", "j_stream", "j_regex", "j_misc" }) do dofile(ROOT .. "/rt/" .. f .. ".lua") end
QH = { api = { core = {
  log = function(s) io.stderr:write(tostring(s), "\n") end,
  frame_ms = function() return 0 end,
} } }

local awt = io.open(ROOT .. "/rt/awt.lua")
if awt then
  awt:close()
  dofile(ROOT .. "/rt/awt.lua")
else
  dofile(HERE .. "/harness/awt_standin.lua")
end

local index = dofile(ROOT .. "/gen/index.lua")
local loaded = {}
local function load_module(m)
  if loaded[m] then return end
  loaded[m] = true
  for _, d in ipairs(index.modules[m] or {}) do load_module(d) end
  dofile(ROOT .. "/gen/" .. m .. ".lua")
end
-- Enum static initialisers reach RuneLite-layer classes (QuestFilter calls
-- net.runelite.client.util.Text.titleCase): only the constant NAMES matter
-- here, so a class neither gen/ nor rt/ has loaded is a stub that absorbs
-- every call.
local STUB
local stub_mt = {}
stub_mt.__index = function(t, k)
  if k == "__key" then return "stub" end
  if k == "__supers" then return {} end
  return function() return STUB end
end
stub_mt.__call = function() return STUB end
stub_mt.__concat = function(a, b) return tostring(type(a) == "table" and "<stub>" or a) .. tostring(type(b) == "table" and "<stub>" or b) end
STUB = setmetatable({}, stub_mt)
J.on_missing(function(key)
  local m = index.classes[key]
  if m then load_module(m); return end
  J.def(key, { kind = "class", super = "java.lang.Object", ifaces = {}, body = function(cls)
    setmetatable(cls, { __index = function(_, k)
      if type(k) == "string" and k:sub(1, 2) == "__" then return C["java.lang.Object"][k] end
      return function() return STUB end
    end })
  end })
end)
function J.try_class(key)
  local m = index.classes[key]
  if m then load_module(m) end
  if J.defined(key) then return C[key] end
  return nil
end

dofile(ROOT .. "/gen/enums.lua")
-- framework modules only register their classes (J.def is lazy); quest
-- modules stay unread unless something names one of their classes
for _, m in ipairs(index.framework) do load_module(m) end
dofile(ROOT .. "/rt/rl_core.lua")

local decl = QH.core.config_decl("com.questhelper.QuestHelperConfig")

local FIELDS = { "key", "type", "label", "default", "min", "max", "choices" }
local lines = {
  "-- GENERATED by tools/questhelper_port/gen_config_decl.lua from QuestHelperConfig. Do not edit.",
  "return {",
}
for _, it in ipairs(decl.items) do
  local parts = {}
  for _, f in ipairs(FIELDS) do
    local v = it[f]
    if v ~= nil then
      local s
      if type(v) == "string" then s = string.format("%q", v) else s = tostring(v) end
      parts[#parts + 1] = f .. " = " .. s
    end
  end
  lines[#lines + 1] = "  { " .. table.concat(parts, ", ") .. " },"
end
lines[#lines + 1] = "}"
local text = table.concat(lines, "\n") .. "\n"

for _, s in ipairs(decl.skipped) do
  io.stderr:write(string.format("not declared (kept in the config file): %s -- %s\n", s.keyName, s.why))
end
io.stderr:write(string.format("%d items declared (group %s)\n", #decl.items, tostring(decl.group)))

if out_path then
  local f = assert(io.open(out_path, "w"))
  f:write(text)
  f:close()
else
  io.write(text)
end
