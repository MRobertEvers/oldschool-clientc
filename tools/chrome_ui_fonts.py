#!/usr/bin/env python3
"""Bake the editor's vendored UI faces into the client.

    FONTTOOLS_DIR=<dir with fontTools> python3 tools/chrome_ui_fonts.py [--check]

The faces under src/engine/fonts/vendor/ (Inter, JetBrains Mono, the Lucide
icon subset; see the README there) are what the chrome's UI font slots draw
in: TORIRS_CHROME_FONT_UI, _UI_SMALL, _UI_BOLD, _UI_MONO and _ICON
(src/ui/uitree_debug_overlay.h). This writes, from those TTFs and nothing
else:

    src/engine/torirs_chrome_ui_fonts_baked.{c,h}
        each face's TrueType bytes as a `static const unsigned char[]`, behind
        one accessor. src/ui/torirs_chrome_bake.c rasterises them with
        stb_truetype, once per (slot, scale).

    src/ui/uitree_ui_font_metrics.h
        per face: units per em, ascent, descent, cap height, x-height, and the
        advance of bytes 32..255 in font units. `static const` tables and
        defines only, no includes: the chrome measures text from it without
        linking a font implementation, the way it measures the game faces
        from uitree_debug_font_metrics.h.

A byte is its Latin-1 code point (128..255 included). A byte the face has no
glyph for carries the face's MISSING_ADVANCE (the space's advance; half an em
in a face with no space), so every entry is a real pen step and none is 0.

The pixel size each slot draws at is NOT here: it is the chrome's
(k_dbg_ui_faces in src/ui/uitree_debug_overlay.c), and a device advance is
that table's arithmetic over these units.

`--check` writes nothing and fails when a committed file differs from a
rerun (make -C src chrome-ui-fonts-check). To refresh after changing a
vendored face: run without --check and commit what it writes. Needs Python 3
and fontTools 4.59.2 (FONTTOOLS_DIR, or importable).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import sys
from pathlib import Path

if os.environ.get("FONTTOOLS_DIR"):
    sys.path.insert(0, os.environ["FONTTOOLS_DIR"])
try:
    from fontTools.ttLib import TTFont  # noqa: E402
except ImportError:
    sys.exit(
        "chrome_ui_fonts.py needs fontTools 4.59.2: install it (pip install fonttools==4.59.2), "
        "or set FONTTOOLS_DIR to the directory that holds the fontTools package"
    )

VENDOR_DIR = "src/engine/fonts/vendor"
C_PATH = "src/engine/torirs_chrome_ui_fonts_baked.c"
H_PATH = "src/engine/torirs_chrome_ui_fonts_baked.h"
METRICS_PATH = "src/ui/uitree_ui_font_metrics.h"

# (C symbol, enum name, file, what it is). The order is the enum's.
FACES = [
    ("InterRegular", "INTER_REGULAR", "Inter-Regular.ttf", "Inter Regular: interface text"),
    ("InterSemiBold", "INTER_SEMIBOLD", "Inter-SemiBold.ttf", "Inter SemiBold: titles"),
    ("JetBrainsMono", "JETBRAINS_MONO", "JetBrainsMono-Regular.ttf", "JetBrains Mono Regular: code"),
    ("Icons", "ICONS", "ToriRSIcons.ttf", "the Lucide icon subset: one icon per printable ASCII code"),
]

FIRST_BYTE = 32
BYTE_COUNT = 256 - FIRST_BYTE


class Face:
    def __init__(self, repo: Path, sym: str, enum: str, file: str, what: str):
        self.sym = sym
        self.enum = enum
        self.file = file
        self.what = what
        self.data = (repo / VENDOR_DIR / file).read_bytes()
        self.sha256 = hashlib.sha256(self.data).hexdigest()
        font = TTFont(repo / VENDOR_DIR / file)
        cmap = font.getBestCmap()
        hmtx = font["hmtx"]
        os2 = font["OS/2"]
        self.upem = font["head"].unitsPerEm
        self.ascent = font["hhea"].ascent
        self.descent = -font["hhea"].descent
        self.cap_height = getattr(os2, "sCapHeight", 0) or 0
        self.x_height = getattr(os2, "sxHeight", 0) or 0
        self.missing = hmtx[cmap[0x20]][0] if 0x20 in cmap else self.upem // 2
        self.has = [(FIRST_BYTE + i) in cmap for i in range(BYTE_COUNT)]
        self.advance = [
            hmtx[cmap[FIRST_BYTE + i]][0] if self.has[i] else self.missing for i in range(BYTE_COUNT)
        ]
        assert self.upem > 0 and self.ascent > 0 and self.descent >= 0, file
        assert all(0 < a < 65536 for a in self.advance), file


def metrics_header(faces: list[Face]) -> str:
    out = [
        "/*",
        " * GENERATED by tools/chrome_ui_fonts.py -- do not edit; regenerate with",
        " * `python3 tools/chrome_ui_fonts.py` (`make -C src chrome-ui-fonts-check`",
        " * fails when a rerun differs).",
        " *",
        " * The metrics of the vendored UI faces (src/engine/fonts/vendor/), in FONT",
        " * UNITS: no includes, no types, no linkage. The chrome measures its UI font",
        " * slots from these the way it measures the game faces from",
        " * uitree_debug_font_metrics.h, so it links no font implementation.",
        " *",
        " * <prefix>_advance_units[b - 32] is the advance of byte `b` (32..255; a",
        " * byte is its Latin-1 code point). A byte the face has no glyph for",
        " * carries <prefix>_MISSING_ADVANCE, so every entry is a pen step.",
        " * The device advance at a pixel size and a chrome scale is arithmetic",
        " * over these: ToriRSChrome_GlyphAdvanceQ (src/ui/uitree_debug_overlay.c).",
        " */",
        "#ifndef UITREE_UI_FONT_METRICS_H",
        "#define UITREE_UI_FONT_METRICS_H",
        "",
        f"/** The first byte the advance tables cover, and how many they hold. */",
        f"#define ToriRSChromeUiFont_FIRST_BYTE {FIRST_BYTE}",
        f"#define ToriRSChromeUiFont_BYTE_COUNT {BYTE_COUNT}",
        "",
    ]
    for f in faces:
        p = f"ToriRSChromeUiFont_{f.sym}"
        have = sum(1 for h in f.has if h)
        out += [
            f"/* {f.sym}: {f.what}.",
            f" * {VENDOR_DIR}/{f.file}, {len(f.data)} bytes, sha256 {f.sha256};",
            f" * {have} of the {BYTE_COUNT} bytes have a glyph. */",
            f"/** Font units per em. */",
            f"#define {p}_UPEM {f.upem}",
            f"/** The face's ascent and descent (hhea), units above and below the baseline. */",
            f"#define {p}_ASCENT {f.ascent}",
            f"#define {p}_DESCENT {f.descent}",
            f"/** Cap height and x-height (OS/2), 0 where the face states none. */",
            f"#define {p}_CAP_HEIGHT {f.cap_height}",
            f"#define {p}_X_HEIGHT {f.x_height}",
            f"/** The advance of a byte the face has no glyph for. */",
            f"#define {p}_MISSING_ADVANCE {f.missing}",
            "",
            f"static const unsigned short {p}_advance_units[{BYTE_COUNT}] = {{",
        ]
        for i in range(0, BYTE_COUNT, 16):
            out.append("    " + ", ".join(f"{a:4d}" for a in f.advance[i : i + 16]) + ",")
        out += ["};", ""]
    out += ["#endif /* UITREE_UI_FONT_METRICS_H */", ""]
    return "\n".join(out)


def c_header(faces: list[Face]) -> str:
    out = [
        "/*",
        " * GENERATED by tools/chrome_ui_fonts.py -- do not edit; regenerate with",
        " * `python3 tools/chrome_ui_fonts.py` (`make -C src chrome-ui-fonts-check`",
        " * fails when a rerun differs).",
        " *",
        " * The vendored UI faces (src/engine/fonts/vendor/: Inter and JetBrains",
        " * Mono, SIL OFL 1.1; the Lucide icon subset, ISC), each a whole TrueType",
        " * file as bytes. src/ui/torirs_chrome_bake.c rasterises them with",
        " * stb_truetype into the atlases the chrome's UI font slots draw from",
        " * (TORIRS_CHROME_FONT_UI and its siblings, src/ui/uitree_debug_overlay.h);",
        " * their metrics are src/ui/uitree_ui_font_metrics.h, written by the same",
        " * run from the same files.",
        " *",
        " * The arrays are `static const` and live for the life of the process.",
        " */",
        "#ifndef TORIRS_CHROME_UI_FONTS_BAKED_H",
        "#define TORIRS_CHROME_UI_FONTS_BAKED_H",
        "",
        "/** The vendored faces, in the order they are baked. */",
        "enum ToriRSChromeUiFace",
        "{",
    ]
    for i, f in enumerate(faces):
        out.append(f"    /** {f.file}: {f.what}. */")
        out.append(f"    TORIRS_CHROME_UI_FACE_{f.enum} = {i},")
    out += [
        f"    TORIRS_CHROME_UI_FACE_COUNT = {len(faces)}",
        "};",
        "",
        "struct ToriRSChromeUiFontFile",
        "{",
        "    /** The TrueType file. */",
        "    unsigned char const* ttf;",
        "    int ttf_size;",
        "    /** Font units per em (the file's head.unitsPerEm). */",
        "    int units_per_em;",
        "};",
        "",
        "/** The file of `face` (enum ToriRSChromeUiFace). Asserts on any other value. */",
        "struct ToriRSChromeUiFontFile const*",
        "ToriRSChromeUiFont_File(int face);",
        "",
        "#endif /* TORIRS_CHROME_UI_FONTS_BAKED_H */",
        "",
    ]
    return "\n".join(out)


def c_source(faces: list[Face]) -> str:
    out = [
        "/*",
        " * GENERATED by tools/chrome_ui_fonts.py -- do not edit. See",
        " * torirs_chrome_ui_fonts_baked.h.",
        " *",
    ]
    for f in faces:
        out.append(f" * {f.file}  {len(f.data)} bytes  sha256 {f.sha256}")
    out += [" */", '#include "torirs_chrome_ui_fonts_baked.h"', "", "#include <assert.h>", ""]
    for f in faces:
        out.append(f"static const unsigned char k_{f.enum.lower()}_ttf[{len(f.data)}] = {{")
        for i in range(0, len(f.data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in f.data[i : i + 16]) + ",")
        out += ["};", ""]
    out.append(f"static const struct ToriRSChromeUiFontFile k_files[TORIRS_CHROME_UI_FACE_COUNT] = {{")
    for f in faces:
        sym = f"k_{f.enum.lower()}_ttf"
        out.append(f"    [TORIRS_CHROME_UI_FACE_{f.enum}] = {{ {sym}, (int)sizeof({sym}), {f.upem} }},")
    out += [
        "};",
        "",
        "struct ToriRSChromeUiFontFile const*",
        "ToriRSChromeUiFont_File(int face)",
        "{",
        "    assert(face >= 0);",
        "    assert(face < TORIRS_CHROME_UI_FACE_COUNT);",
        "    return &k_files[face];",
        "}",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    repo = Path(__file__).resolve().parents[1]
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail when a committed file differs from a rerun",
    )
    args = ap.parse_args(argv)

    faces = [Face(repo, *row) for row in FACES]
    outputs = {
        METRICS_PATH: metrics_header(faces).encode("utf-8"),
        H_PATH: c_header(faces).encode("utf-8"),
        C_PATH: c_source(faces).encode("utf-8"),
    }
    for f in faces:
        print(
            f"{f.sym}: {f.file} {len(f.data)} B, upem {f.upem}, ascent {f.ascent}, descent {f.descent}, "
            f"{sum(1 for h in f.has if h)} glyphs of {BYTE_COUNT} bytes"
        )
    if args.check:
        # A checkout with core.autocrlf holds these as CRLF: the comparison is
        # of the text, whichever line ending the working tree gave it.
        def committed(rel: str) -> bytes:
            return (repo / rel).read_bytes().replace(b"\r\n", b"\n")

        stale = [rel for rel, data in sorted(outputs.items()) if not (repo / rel).is_file() or committed(rel) != data]
        for rel in stale:
            print(f"differs from a rerun: {rel}", file=sys.stderr)
        if stale:
            print("run python3 tools/chrome_ui_fonts.py and commit what it writes", file=sys.stderr)
            return 1
        print(f"chrome-ui-fonts: {len(outputs)} files reproduce byte for byte")
        return 0
    for rel, data in sorted(outputs.items()):
        dest = repo / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    print(f"wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
