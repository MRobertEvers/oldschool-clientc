#!/usr/bin/env python3
"""Generate server/scripts/quests/configs/quest_progress.enum.

Which var holds each quest's stage is the client's own table: clientscript
`quest_progress_get` (4024) is a switch on the quest's dbrow that returns one
varp or varbit per quest. The server needs the same fact the other way round
-- "this var is quest X's stage" -- so that a write to it can run
`[proc,quest_progress_changed]` (the recent-quest varbits, RSProx 4680/4682).

Two enums, keyed on the var's id: `quest_progress_varp` and
`quest_progress_varbit`, each -> the quest dbrow. Regenerate after a cache bump:

    python3 tools/quest_gate/gen_quest_progress_enum.py
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
CONTENT = os.path.join(ROOT, "OSRS-Content", "osrs-content")
CS2 = os.path.join(CONTENT, "scripts", "quest_progress_get.cs2")
DBROWS = os.path.join(CONTENT, "configs", "all.dbrow.compack")
OUT = os.path.join(CONTENT, "server", "scripts", "quests", "configs", "quest_progress.enum")


def main():
    names = {}
    with open(DBROWS) as f:
        for line in f:
            m = re.match(r"^(\d+)=(\S+)$", line.strip())
            if m:
                names[int(m.group(1))] = m.group(2)

    rows = {"varp": [], "varb": []}
    keys = None
    with open(CS2) as f:
        for line in f:
            line = line.strip()
            m = re.match(r"^case (.+) :$", line)
            if m:
                keys = [k.strip() for k in m.group(1).split(",")]
                continue
            m = re.match(r"^return\(%(varp|varb)(\d+)_\w+\);$", line)
            if m and keys:
                for k in keys:
                    if k == "default":
                        continue
                    row = int(k)
                    if row not in names:
                        sys.exit("quest_progress_get: dbrow %d has no name in all.dbrow.compack" % row)
                    rows[m.group(1)].append((int(m.group(2)), names[row], row))
                keys = None

    lines = [
        "// GENERATED by tools/quest_gate/gen_quest_progress_enum.py -- do not edit.",
        "//",
        "// Each quest's stage var, keyed on the var: the client's quest_progress_get",
        "// (clientscript 4024) read the other way round. The engine runs",
        "// [proc,quest_progress_changed] when a script writes one of these",
        "// (quests/scripts/recent_quests.rs2).",
        "",
    ]
    for kind, symbol in (("varp", "quest_progress_varp"), ("varb", "quest_progress_varbit")):
        seen = {}
        lines += ["[%s]" % symbol, "inputtype=int", "outputtype=dbrow", "default=null"]
        for var, name, row in sorted(rows[kind]):
            if var in seen:
                # One var, two quests: the client reads it for both, the
                # server can name one. Keep the first and say so.
                lines.append("// %s %d is also %s's stage (dbrow %d)" % (kind, var, name, row))
                continue
            seen[var] = name
            lines.append("val=%d,%s" % (var, name))
        lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("%s: %d varps, %d varbits" % (OUT, len(rows["varp"]), len(rows["varb"])))


if __name__ == "__main__":
    main()
