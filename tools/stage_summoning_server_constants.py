#!/usr/bin/env python3
"""Stage ServerScript constants with one explicit value per gated content lane.

Every lane's flag is written here rather than by a stager of its own. There is
one staged constants tree per build, so a second stager would not add a flag —
it would delete the first one's, because staging starts by clearing `--out`.
A lane that is off still needs its constant *defined*, at 0: shared files like
skill_combat/combat_stats.rs2 test `^curses_enabled` unconditionally, and an
undefined constant is a compile error, not a falsey value.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--enabled", type=int, choices=(0, 1), required=True,
                        help="^summoning_enabled")
    parser.add_argument("--curses", type=int, choices=(0, 1), default=0,
                        help="^curses_enabled (Ancient Curses lane)")
    args = parser.parse_args()

    src = args.src.resolve()
    out = args.out.resolve()
    if src == out or src in out.parents:
        raise SystemExit("output must not be the source tree or one of its parents")
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    constant_count = 0
    dbtable_count = 0
    paths = sorted(path for path in src.rglob("*") if path.suffix in (".constant", ".dbtable"))
    for path in paths:
        if any(part.startswith("build") for part in path.relative_to(src).parts):
            continue
        target = out / path.relative_to(src)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        if path.suffix == ".constant":
            constant_count += 1
        else:
            dbtable_count += 1
    if constant_count == 0 or dbtable_count == 0:
        raise SystemExit("refusing a vacuous constants stage")

    flags = (
        ("ported_scape2009_summoning/configs/summoning_feature.constant",
         "summoning_enabled", args.enabled),
        ("ported_rs558_ancient_curses/configs/curses_feature.constant",
         "curses_enabled", args.curses),
    )
    for relpath, name, value in flags:
        feature = out / relpath
        feature.parent.mkdir(parents=True, exist_ok=True)
        feature.write_text(
            "// Generated by tools/stage_summoning_server_constants.py.\n"
            f"^{name} = {value}\n",
            encoding="utf-8",
        )

    print(
        f"staged {constant_count + len(flags)} constants and {dbtable_count} dbtables; "
        f"summoning_enabled={args.enabled} curses_enabled={args.curses}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
