#!/usr/bin/env python3
"""
Generate 3rd/rsprot's per-revision prot tables from vendored RSProt Kotlin.

    tools/rsprot_gen_tables.py               # 221..239 from RSProt, 240..241 from RSProx
    tools/rsprot_gen_tables.py 239            # one revision

Revisions RSProt never vendored (RSPROX_REVISIONS) are read from RSProx's own
GameServerProt / GameClientProt enums (tools/rsprox_prot.py), with RSProx's
spellings folded back to RSProt's (rsprox_prot.RSPROT_ALIASES) so a prot keeps
one name across the whole table set. For the revisions both projects carry,
RSProx is the authority on what the wire holds: a prot RSProx defines and
RSProt omits (WORLDENTITY_INFO_V6 at 236) is appended to the RSProt table, so
a recording that carries it still frames.

Unlike tools/rsprot_gen_rev.py (which maps RSProt's prots onto THIS ENGINE's
canonical PKT_NAME_* names for src/net/rev/osrsNNN/), this generator is for the
standalone `3rd/rsprot` library and knows nothing about the engine's packet
enum. It emits RSProt's own prot names verbatim, as plain {name, code, size}
data tables — the library's job is to be a faithful, revision-agnostic wire
codec; naming a payload to an engine concept is 3rd/rsprot's caller's job (see
src/net/rev/osrsNNN/, which does that mapping for the revisions this project
actively speaks).

Data only: no encoder/decoder bodies. This is the part of the port that is
genuinely cheap across all 19 revisions — the opcode/size tables are a few
hundred rows each and RSProt's own JSON dump (rsprot_dump_prot.py) already
extracts them per revision. Message structs and codec bodies are the expensive
part and are handled by a separate, narrower generator scoped to the revisions
this project actually implements (see rsprot_gen_codec.py and 3rd/rsprot/README.md
"What's generated" for the current split).
"""

import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rsprox_prot  # noqa: E402
REPO_ROOT = os.path.dirname(HERE)
GEN_DIR = os.path.join(REPO_ROOT, "3rd", "rsprot", "gen")
RSPROT = os.path.expanduser("~/Documents/git_repos/rsprot")

RSPROT_REVISIONS = list(range(221, 240))
RSPROX_REVISIONS = [240, 241]
ALL_REVISIONS = RSPROT_REVISIONS + RSPROX_REVISIONS
# The first revision merged with RSProx. 223-226 name a few prots apart in a way
# that is not a simple suffix (MIDI_SONG_V1 is two different prots at 223), and
# nothing in this tree speaks them; 227 is where the two tables agree.
RSPROX_FIRST = 227

BANNER = """/*
 * GENERATED by tools/rsprot_gen_tables.py -- do not edit.
 * Source: RSProt {src}, revision {rev}.
 */"""


def size_literal(n):
    if n == -1:
        return "RSPROT_VARU8"
    if n == -2:
        return "RSPROT_VARU16"
    return str(n)


def c_ident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def read_zone_order(rev):
    """The enclosed sub-packet index is the ORDINAL of RSProt's
    IndexedZoneProtEncoder, not the prot id and not the top-level opcode."""
    path = os.path.join(
        RSPROT,
        f"protocol/osrs-{rev}/osrs-{rev}-desktop/src/main/kotlin/net/rsprot/"
        "protocol/game/outgoing/codec/zone/header/"
        "DesktopUpdateZonePartialEnclosedEncoder.kt",
    )
    if not os.path.exists(path):
        return []
    src = open(path).read()
    marker = "private enum class IndexedZoneProtEncoder"
    if marker not in src:
        return []
    body = src[src.index(marker):]
    body = body[: body.index("\n            ;")]
    # One line (`LOC_ADD_CHANGE(OldSchoolZoneProt.LOC_ADD_CHANGE, ...)`) or, at
    # 225, the arguments on lines of their own.
    return re.findall(r"^\s{12}(\w+)\(\s*OldSchoolZoneProt\.", body, re.M)


def rsprot_spelling(name):
    back = {v: k for k, v in rsprox_prot.RSPROT_ALIASES.items()}
    return back.get(name, name)


def rsprox_dump(rev):
    """{"server", "client", "zone"} for a revision, read from RSProx, in
    RSProt's spelling."""
    prots = rsprox_prot.load_prots(rev)
    out = {}
    for side in ("server", "client"):
        out[side] = [dict(r, name=rsprot_spelling(r["name"])) for r in prots[side]]
    out["zone"] = [rsprot_spelling(n) for n in rsprox_prot.zone_order(rev)]
    return out


def merge_rsprox(rev, dump):
    """Append the prots RSProx defines at `rev` that RSProt's table lacks.

    A name match ignores RSProx's retroactive `_V1` suffix (RSProx renames a prot
    `X` to `X_V1` once an `X_V2` exists; RSProt keeps `X`). A prot present in
    both with a different opcode or size is a disagreement this generator will
    not paper over."""
    if rev < RSPROX_FIRST:
        return dump
    rx = rsprox_dump(rev)
    for side in ("server", "client"):
        have = {r["name"]: r for r in dump[side]}
        for r in rx[side]:
            cands = [r["name"], re.sub(r"_V1$", "", r["name"])]
            hit = next((have[c] for c in cands if c in have), None)
            if hit is None:
                dump[side].append(dict(r, rsprox_only=True))
            elif (hit["code"], hit["size"]) != (r["code"], r["size"]):
                raise SystemExit(
                    f"rev {rev} {side} {r['name']}: RSProt {hit['code']}/{hit['size']} "
                    f"but RSProx {r['code']}/{r['size']}")
    return dump


def gen_rev_header(rev, dump, src_hash):
    guard = f"RSPROT_GEN_OSRS{rev}_PROT_H"
    lines = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        BANNER.format(rev=rev, src=src_hash),
        "",
        '#include "../src/rsprot_tables_def.h"',
        "",
        "/* clang-format off */",
        f"static const RsprotProtDef rsprot_osrs{rev}_server[] = {{",
    ]
    for r in dump["server"]:
        lines.append(
            '    { "%s", %d, %s },%s' % (r["name"], r["code"], size_literal(r["size"]),
                                     "  /* RSProx only */" if r.get("rsprox_only") else "")
        )
    lines += [
        "};",
        f"static const RsprotProtDef rsprot_osrs{rev}_client[] = {{",
    ]
    for r in dump["client"]:
        lines.append(
            '    { "%s", %d, %s },%s' % (r["name"], r["code"], size_literal(r["size"]),
                                     "  /* RSProx only */" if r.get("rsprox_only") else "")
        )
    lines += ["};", ""]

    zone = dump["zone"] if "zone" in dump else read_zone_order(rev)
    lines.append(f"static const char *const rsprot_osrs{rev}_zone_order[] = {{")
    for name in zone:
        lines.append(f'    "{name}",')
    lines += ["};", "/* clang-format on */", ""]

    lines += [
        f"#define RSPROT_OSRS{rev}_SERVER_COUNT "
        f"((int)(sizeof(rsprot_osrs{rev}_server) / sizeof(rsprot_osrs{rev}_server[0])))",
        f"#define RSPROT_OSRS{rev}_CLIENT_COUNT "
        f"((int)(sizeof(rsprot_osrs{rev}_client) / sizeof(rsprot_osrs{rev}_client[0])))",
        f"#define RSPROT_OSRS{rev}_ZONE_COUNT "
        f"((int)(sizeof(rsprot_osrs{rev}_zone_order) / sizeof(rsprot_osrs{rev}_zone_order[0])))",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def gen_tables_dispatch(revisions, src_hash):
    lines = [
        "#ifndef RSPROT_GEN_TABLES_H",
        "#define RSPROT_GEN_TABLES_H",
        "",
        BANNER.format(rev="all", src=src_hash),
        "",
        "/*",
        " * Umbrella table: every vendored revision's {name, code, size} rows, plus a",
        " * runtime lookup by revision number. This is the ONLY file that needs to",
        " * change to add a revision RSProt vendors -- re-run",
        " * tools/rsprot_gen_tables.py, which regenerates every osrs<N>_prot.h and",
        " * this dispatch together so they cannot drift.",
        " */",
        "",
        '#include "../src/rsprot_tables_def.h"',
        "",
    ]
    for r in revisions:
        lines.append(f'#include "osrs{r}_prot.h"')
    lines += ["", "/* clang-format off */"]
    lines.append("static const RsprotRevTable rsprot_all_revisions[] = {")
    for r in revisions:
        lines.append(
            "    { %d, rsprot_osrs%d_server, RSPROT_OSRS%d_SERVER_COUNT, "
            "rsprot_osrs%d_client, RSPROT_OSRS%d_CLIENT_COUNT, "
            "rsprot_osrs%d_zone_order, RSPROT_OSRS%d_ZONE_COUNT },"
            % (r, r, r, r, r, r, r)
        )
    lines += ["};", "/* clang-format on */", ""]
    lines += [
        "#define RSPROT_REVISION_COUNT "
        "((int)(sizeof(rsprot_all_revisions) / sizeof(rsprot_all_revisions[0])))",
        "",
        "/* Looks up a revision by its bare number (e.g. 239). Returns NULL if this",
        " * build was not generated with that revision vendored. */",
        "static inline const RsprotRevTable *",
        "rsprot_rev_table(int revision)",
        "{",
        "    for( int i = 0; i < RSPROT_REVISION_COUNT; i++ )",
        "        if( rsprot_all_revisions[i].revision == revision )",
        "            return &rsprot_all_revisions[i];",
        "    return 0;",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    revisions = [int(a) for a in sys.argv[1:]] or ALL_REVISIONS

    src_hash = (
        subprocess.check_output(["git", "-C", RSPROT, "rev-parse", "--short", "HEAD"])
        .decode()
        .strip()
    )

    os.makedirs(GEN_DIR, exist_ok=True)
    for rev in revisions:
        if rev in RSPROX_REVISIONS:
            dump = rsprox_dump(rev)
            text = gen_rev_header(rev, dump, "-").replace(
                "Source: RSProt -, revision", f"Source: RSProx {rsprox_prot.source_hash()}, revision")
        else:
            dump = json.loads(
                subprocess.check_output(
                    [sys.executable, os.path.join(HERE, "rsprot_dump_prot.py"), str(rev)]
                )
            )
            dump = merge_rsprox(rev, dump)
            text = gen_rev_header(rev, dump, src_hash)
        path = os.path.join(GEN_DIR, f"osrs{rev}_prot.h")
        with open(path, "w") as fh:
            fh.write(text)
        print(
            f"rev {rev}: {len(dump['server'])} server prots, "
            f"{len(dump['client'])} client prots -> {path}",
            file=sys.stderr,
        )

    all_revs = sorted(
        set(revisions)
        | {
            int(re.match(r"osrs(\d+)_prot\.h", f).group(1))
            for f in os.listdir(GEN_DIR)
            if re.match(r"osrs\d+_prot\.h", f)
        }
    )
    dispatch_path = os.path.join(GEN_DIR, "rsprot_tables.h")
    with open(dispatch_path, "w") as fh:
        fh.write(gen_tables_dispatch(all_revs, src_hash))
    print(f"wrote {dispatch_path} ({len(all_revs)} revisions)", file=sys.stderr)


if __name__ == "__main__":
    main()
