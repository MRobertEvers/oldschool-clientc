/*
 * Writing CS2 source.
 *
 * The output is source, not bytecode: cachepack compiles it at bake time with
 * RSCache_CS2_Compile, the same path every hand-written script in the content tree
 * takes. That is worth the extra step — a generated script can be read in a diff,
 * stepped through in the decompiler's own dialect, and patched by hand when the
 * generator has not learned some trick yet.
 *
 * The dialect is not a friendly one. cs2_compile.c accepts what cs2_gen.c emits and
 * refuses to guess at anything else, so three rules shape everything below:
 *
 *   - arithmetic lives inside `calc(...)` and nowhere else;
 *   - strings are built by interpolation — `"<$string0> left"` — never by `+`;
 *   - a conditional is a statement, so a value that depends on one is hoisted into
 *     a local before the call that needs it (`hoistSelects`).
 *
 * Every command emitted is checked against the real compiler by test/run_tests.js,
 * so an argument order that drifts fails there rather than in the client.
 */

import { OPS, VARIABLE_SYNTAX, STATE_READ } from './ops.js';
import { isExpr, INT, STRING, BOOL } from './expr.js';
import { Cs2domError } from './ir.js';

const TYPE_KEYWORD = { [INT]: 'def_int', [STRING]: 'def_string', [BOOL]: 'def_boolean' };
const TYPE_ZERO = { [INT]: '0', [STRING]: '""', [BOOL]: 'false' };

class Writer {
    constructor(script, interfaceId) {
        this.script = script;
        this.interfaceId = interfaceId;
        this.lines = [];
        this.indent = 1;
        this.locals = 0;
        this.warnings = [];
    }

    line(text) {
        this.lines.push('\t'.repeat(this.indent - 1) + text);
    }

    newLocal(type) {
        return `$${type}${this.locals++}`;
    }
}

/**
 * Render one script to CS2 source text.
 *
 * `[clientscript,<name>]` rather than `[proc,...]`: these are entry points a hook
 * calls, not procedures another script calls.
 */
export function emitScript(script, interfaceId) {
    const writer = new Writer(script, interfaceId);
    /* Parameter slots are taken before any hoisted local can claim a name. */
    writer.locals = script.params.length;

    const params = script.params.map((p) => `${p.type} ${p.local}`).join(', ');
    const header = params ? `[clientscript,${script.name}](${params})` : `[clientscript,${script.name}]`;

    for( const statement of script.statements )
        emitStatement(writer, statement);

    const body = writer.lines.length ? writer.lines.join('\n') + '\n' : '';
    const source =
        `// ${script.id}\n` +
        `// generated by cs2dom — edits are overwritten; change the .tsx instead\n` +
        `${header}\n${body}`;
    return { source, warnings: writer.warnings };
}

function emitStatement(writer, statement) {
    if( statement.op === 'assign' ) {
        const variable = stateTerm(statement.source);
        const value = term(writer, statement.value, statement.source.kind === 'varcstr' ? STRING : INT);
        writer.line(`${variable} = ${value};`);
        return;
    }

    if( statement.op === 'runscript' ) {
        const args = statement.args.map((a) => term(writer, a)).join(', ');
        writer.line(`~script${statement.scriptId}(${args});`);
        return;
    }

    if( statement.op === 'if_button' ) {
        writer.warnings.push(
            'actions.button() emits if_triggerop, which this client does not implement yet ' +
            '(IF_TRIGGEROP; only CC_TRIGGEROP is wired). The cache record is right, the ' +
            'click will not reach the server until the client catches up.');
        writer.line(`if_triggerop(${componentRef(writer, writer.script.component)}, -1, ${statement.args[0]});`);
        return;
    }

    const signature = OPS[statement.op];
    if( !signature )
        throw new Cs2domError(`no signature for ${statement.op}`);

    const args = signature.args.map((prop, i) => {
        const value = statement.args[i];
        const type = argType(statement.op, prop);
        return term(writer, value, type);
    });
    args.push(componentRef(writer, statement.target));
    writer.line(`${statement.op}(${args.join(', ')});`);
}

/**
 * The type an argument slot wants.
 *
 * Only the boolean slots matter — an int written where a boolean belongs compiles
 * to the wrong opcode operand rather than to an error — so they are named here and
 * everything else is inferred from the value.
 */
const BOOLEAN_ARGS = new Set([
    'hidden', 'shadow', 'tiled', 'hFlip', 'vFlip', 'fill', 'lineDirection',
    'noClickThrough', 'orthographic',
]);

function argType(op, prop) {
    if( op === 'if_setgraphicshadow' ) return INT;   /* a colour, despite the name */
    if( BOOLEAN_ARGS.has(prop) ) return BOOL;
    if( prop === 'text' || prop === 'targetVerb' ) return STRING;
    return INT;
}

/* ---- expressions --------------------------------------------------------- */

/**
 * Print an expression as a single CS2 term, emitting whatever statements it needs
 * first. A ternary is the only thing that needs statements — CS2 has no conditional
 * expression, so the value is computed into a local by an if/else and the local is
 * what the caller gets.
 */
function term(writer, value, expected) {
    if( !isExpr(value) )
        return literal(value, expected);

    /*
     * A condition is a statement in CS2, so one that reached an argument slot —
     * `hidden={mode === 1}` — becomes the boolean the branch would have produced.
     * Turning it into a select here means one lowering path handles both, rather
     * than a second one that would drift from it.
     */
    const asValue = isCondition(value)
        ? { __cs2dom: 'expr', kind: 'select', type: BOOL, test: value,
            whenTrue: { __cs2dom: 'expr', kind: 'const', type: BOOL, value: true },
            whenFalse: { __cs2dom: 'expr', kind: 'const', type: BOOL, value: false } }
        : value;

    const hoisted = hoistSelects(writer, asValue);
    return print(writer, hoisted, false);
}

function isCondition(e) {
    return isExpr(e) && (e.kind === 'compare' || e.kind === 'logic' || e.kind === 'not');
}

function literal(value, expected) {
    if( typeof value === 'boolean' ) return value ? 'true' : 'false';
    if( typeof value === 'number' ) {
        if( expected === BOOL ) return value ? 'true' : 'false';
        return String(value);
    }
    if( typeof value === 'string' ) return quote(value);
    throw new Cs2domError(`cannot write ${typeof value} into a script`);
}

function quote(text) {
    /*
     * `<` opens markup inside a CS2 string, so a literal one would change what the
     * text means. Refusing is better than emitting a string that renders as a tag.
     */
    if( text.includes('<') )
        throw new Cs2domError(`'<' cannot appear in component text ("${text}")`);
    return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** Replace every `select` with a local the caller can use, depth first. */
function hoistSelects(writer, expression) {
    if( !isExpr(expression) ) return expression;

    switch( expression.kind ) {
        case 'select': {
            const test = hoistSelects(writer, expression.test);
            const local = writer.newLocal(expression.type);
            writer.line(`${TYPE_KEYWORD[expression.type]} ${local} = ${TYPE_ZERO[expression.type]};`);
            writer.line(`if (${print(writer, test, true)}) {`);
            writer.indent++;
            writer.line(`${local} = ${print(writer, hoistSelects(writer, expression.whenTrue), false)};`);
            writer.indent--;
            writer.line('} else {');
            writer.indent++;
            writer.line(`${local} = ${print(writer, hoistSelects(writer, expression.whenFalse), false)};`);
            writer.indent--;
            writer.line('}');
            return { __cs2dom: 'expr', kind: 'local', type: expression.type, name: local };
        }
        case 'arith': case 'compare': case 'logic':
            return { ...expression,
                     left: hoistSelects(writer, expression.left),
                     right: hoistSelects(writer, expression.right) };
        case 'not':
            return { ...expression, value: hoistSelects(writer, expression.value) };
        case 'template':
            return { ...expression, values: expression.values.map((v) => hoistSelects(writer, v)) };
        case 'call':
            return { ...expression, args: expression.args.map((a) => hoistSelects(writer, a)) };
        default:
            return expression;
    }
}

/**
 * Print a hoisted expression.
 *
 * `inCalc` tracks whether arithmetic is already inside a `calc(...)`, because the
 * wrapper goes on the outermost arithmetic node and nowhere below it.
 */
function print(writer, e, inCondition, inCalc = false) {
    if( !isExpr(e) ) return literal(e);

    switch( e.kind ) {
        case 'const':
            return literal(e.value);
        case 'local':
            return e.name;
        case 'state':
            return stateTerm(e.source);
        case 'arith': {
            const body = `${print(writer, e.left, false, true)} ${e.op} ${print(writer, e.right, false, true)}`;
            return inCalc ? body : `calc(${body})`;
        }
        case 'compare': {
            if( !inCondition )
                throw new Cs2domError(
                    'a comparison can only be used as a condition — put it in a ternary ' +
                    'to turn it into a value');
            return `${print(writer, e.left, false)} ${e.op} ${print(writer, e.right, false)}`;
        }
        case 'logic':
            return `${print(writer, e.left, true)} ${e.op} ${print(writer, e.right, true)}`;
        case 'not': {
            /* CS2 has no `!`, so the sense is flipped onto the comparison itself. */
            const inner = e.value;
            if( inner.kind === 'compare' ) {
                const flipped = { '=': '!', '!': '=', '<': '>=', '>': '<=', '<=': '>', '>=': '<' }[inner.op];
                return print(writer, { ...inner, op: flipped }, true);
            }
            return `${print(writer, inner, true)} = false`;
        }
        case 'template':
            return templateTerm(writer, e);
        case 'call': {
            const args = e.args.map((a) => print(writer, a, false)).join(', ');
            return `${e.command}(${args})`;
        }
        default:
            throw new Cs2domError(`cannot write a '${e.kind}' expression`);
    }
}

function stateTerm(source) {
    const variable = VARIABLE_SYNTAX[source.kind];
    if( variable ) return variable(source.id);
    const read = STATE_READ[source.kind];
    if( read ) return read(source.id);
    throw new Cs2domError(`no way to read ${source.kind} state`);
}

/**
 * A template becomes one interpolated string. An int inside it goes through
 * `tostring` — the interpolation takes a string, and CS2 will not convert.
 */
function templateTerm(writer, e) {
    let out = '"';
    for( let i = 0; i < e.strings.length; i++ ) {
        const literalPart = e.strings[i];
        if( literalPart.includes('<') )
            throw new Cs2domError(`'<' cannot appear in component text ("${literalPart}")`);
        out += literalPart.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
        if( i < e.values.length ) {
            const value = e.values[i];
            const printed = print(writer, value, false);
            out += value.type === STRING ? `<${printed}>` : `<tostring(${printed})>`;
        }
    }
    return out + '"';
}

/**
 * How a script names a component.
 *
 * Always the absolute `interface_<id>:<file id>` form. It costs nothing, needs no
 * name table, and — the point — means a hook can be bound with no arguments at all,
 * which is the one shape that never meets the compiler's hook-argument type
 * inference (EXCEPTIONS.md G3).
 */
function componentRef(writer, component) {
    if( !component ) throw new Cs2domError('a command needs a target component');
    return `interface_${writer.interfaceId}:${component.fileId}`;
}
