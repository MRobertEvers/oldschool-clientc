#!/usr/bin/env python3
"""Generate the farming patches added after the four classic farming areas.

The allotment, flower and herb families keep their first patches (Falador,
Catherby, Ardougne, Port Phasmatys, the Troll Stronghold) in hand-unrolled
chains in skill_farming/scripts/: a varp's id is a compile-time operand, so a
patch's storage cannot come from a db row. Every one of those chains ends by
asking this file's procs, so a new patch is one row in PATCHES below instead
of an arm in twenty procs.

Writes, under OSRS-Content/osrs-content/server/scripts/skill_farming/:
    scripts/farming_patch_slots.rs2   the per-patch arms, mapzone syncs
    configs/farming_patch_slots.varp  five server varps per patch
    configs/farming_patch_slots.dbrow the farming_patches registry rows
and appends the varp ids to pack/varp.alloc (dbrow ids: tools/ss_allocate.py).

Each patch: wrapper loc, family, the map square it is placed in (measured off
maps/m*.jl2), the transmit varbit its wrapper draws from (its multivarbit in
configs/all.loc), the flower patch beside it (allotments), the enum_1233
farming-view id. View ids marked UNVERIFIED are guesses at which of an area's
enum_1233 rows is which patch.

Usage: python3 tools/gen_farming_patch_slots.py [--check]
"""

import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(REPO, "OSRS-Content", "osrs-content")
FARMING = os.path.join(CONTENT, "server", "scripts", "skill_farming")
OUT_RS2 = os.path.join(FARMING, "scripts", "farming_patch_slots.rs2")
OUT_VARP = os.path.join(FARMING, "configs", "farming_patch_slots.varp")
OUT_DBROW = os.path.join(FARMING, "configs", "farming_patch_slots.dbrow")
VARP_ALLOC = os.path.join(CONTENT, "pack", "varp.alloc")
FIRST_VARP = 9753

TRANSMIT = {
    "a": "varb4771_farming_transmit_a",
    "b": "varb4772_farming_transmit_b",
    "c": "varb4773_farming_transmit_c",
    "d": "varb4774_farming_transmit_d",
    "e": "varb4775_farming_transmit_e",
    "h": "varb7906_farming_transmit_h",
}

FAMILY = {"allot": "^farming_type_allotment", "flower": "^farming_type_flower",
          "herb": "^farming_type_herb"}
STAGE = {"allot": "^farming_stage_mins_allotment", "flower": "^farming_stage_mins_flower",
         "herb": "^farming_stage_mins_herb"}

# (key, wrapper, family, square, transmit, flower beside it, view id, view note)
PATCHES = [
    ("hosidius_allot_ne", "farming_veg_patch_10", "allot", "27_55", "a", "farming_flower_patch_5", 51, ""),
    ("hosidius_allot_sw", "farming_veg_patch_11", "allot", "27_55", "b", "farming_flower_patch_5", 52, ""),
    ("hosidius_flower", "farming_flower_patch_5", "flower", "27_55", "c", None, 53, ""),
    ("hosidius_herb", "farming_herb_patch_6", "herb", "27_55", "d", None, 54, ""),
    ("guild_allot_n", "farming_veg_patch_12", "allot", "19_58", "c", "farming_flower_patch_6", 156, ""),
    ("guild_allot_s", "farming_veg_patch_13", "allot", "19_58", "d", "farming_flower_patch_6", 157, ""),
    ("guild_flower", "farming_flower_patch_6", "flower", "19_58", "h", None, 158, "UNVERIFIED"),
    ("guild_herb", "farming_herb_patch_7", "herb", "19_58", "e", None, 159, "UNVERIFIED"),
    ("prif_allot_n", "farming_veg_patch_14", "allot", "51_95", "a", "farming_flower_patch_7", 166, ""),
    ("prif_allot_s", "farming_veg_patch_15", "allot", "51_95", "b", "farming_flower_patch_7", 167, ""),
    ("prif_flower", "farming_flower_patch_7", "flower", "51_95", "c", None, 168, "UNVERIFIED"),
    ("civitas_allot_nw", "farming_veg_patch_16", "allot", "24_48", "a", "farming_flower_patch_8", 172, ""),
    ("civitas_allot_se", "farming_veg_patch_17", "allot", "24_48", "b", "farming_flower_patch_8", 173, ""),
    ("civitas_flower", "farming_flower_patch_8", "flower", "24_48", "c", None, 174, "UNVERIFIED"),
    ("civitas_herb", "farming_herb_patch_8", "herb", "24_48", "d", None, 171, "UNVERIFIED"),
    ("harmony_herb", "farming_herb_patch_5", "herb", "59_44", "b", None, 143, ""),
]
FIELDS = ["state", "seed", "next", "lives", "flags"]

# Squares whose [mapzone] another script already owns: the generator writes the
# sync proc and that script calls it.
SHARED_SQUARES = {"19_58": "skill_farming/scripts/farming_tree.rs2",
                  "51_95": "sailing/scripts/sailing_wreck_sites.rs2"}


def varp_name(i, key, field):
    return "varp%d_farming_%s_%s" % (FIRST_VARP + i * len(FIELDS) + FIELDS.index(field), key, field)


def var(i, key, field):
    return "%" + varp_name(i, key, field)


def build_rs2():
    o = ["// GENERATED by tools/gen_farming_patch_slots.py. Do not edit: change its",
         "// PATCHES table and rerun. The allotment, flower and herb patches beyond the",
         "// four classic areas: each family's hand-written chain (farming_allot.rs2,",
         "// farming_herb.rs2, farming_transmit.rs2, farming_state.rs2, farming_patch.rs2)",
         "// ends by asking these.", ""]

    def chain(header, arms, default):
        o.append(header)
        o.extend(arms)
        o.append(default)
        o.append("")

    chain("[proc,farming_slot_family](loc $patch)(int $family)",
          ["if ($patch = %s) return(%s);" % (w, FAMILY[f]) for _, w, f, *_ in PATCHES], "return(-1);")
    for field, typ, dflt in (("state", "int", "-1"), ("seed", "namedobj", "null"),
                             ("next", "int", "0"), ("lives", "int", "0"), ("flags", "int", "-1")):
        getter = "get" if field != "state" else "get"
        name = "farming_slot_get" if field == "state" else "farming_slot_get_" + field
        chain("[proc,%s](loc $patch)(%s $value)" % (name, typ),
              ["if ($patch = %s) return(%s);" % (p[1], var(i, p[0], field)) for i, p in enumerate(PATCHES)],
              "return(%s);" % dflt)
        if field == "state":
            continue
        o.append("[proc,farming_slot_set_%s](loc $patch, %s $value)" % (field, typ))
        for i, p in enumerate(PATCHES):
            o.append("if ($patch = %s) {" % p[1])
            o.append("    %s = $value;" % var(i, p[0], field))
            o.append("    return;")
            o.append("}")
        o.append("")
    o.append("[proc,farming_slot_set](loc $patch, int $state)")
    for i, (key, w, f, sq, tx, *_rest) in enumerate(PATCHES):
        o.append("if ($patch = %s) {" % w)
        o.append("    %s = $state;" % var(i, key, "state"))
        o.append("    if (inzone(0_%s_0_0, 0_%s_63_63, coord) = true) {" % (sq, sq))
        o.append("        %%%s = ~farming_display_state($patch, $state);" % TRANSMIT[tx])
        o.append("    }")
        o.append("    return;")
        o.append("}")
    o.append("")
    chain("[proc,farming_slot_flower_of](loc $patch)(loc $flower)",
          ["if ($patch = %s) return(%s);" % (p[1], p[5]) for p in PATCHES if p[5]], "return(null);")
    o.append("[proc,farming_slot_any_armed]()(int $armed)")
    for i, p in enumerate(PATCHES):
        o.append("if (%s > 0) return(1);" % var(i, p[0], "next"))
    o.append("return(0);")
    o.append("")
    o.append("[proc,farming_slot_rush]")
    for i, p in enumerate(PATCHES):
        o.append("if (%s > 0) %s = 1;" % (var(i, p[0], "next"), var(i, p[0], "next")))
    o.append("")
    o.append("[proc,farming_slot_catchup]")
    for p in PATCHES:
        o.append("~farming_catchup_%s(%s);" % (p[2], p[1]))
    o.append("")
    squares = []
    for p in PATCHES:
        if p[3] not in squares:
            squares.append(p[3])
    # Jagex writes an area's transmits d, c, b, a -- one VARP packet each, in
    # that order (RSProx index 4422 with the varp roots shown: [174], [797]);
    # the ones on other carriers after them.
    order = "dcbaefghijklmnop"
    for sq in squares:
        o.append("[proc,farming_slot_sync_0_%s]" % sq)
        rows = [(i, p) for i, p in enumerate(PATCHES) if p[3] == sq]
        rows.sort(key=lambda r: order.index(r[1][4]))
        for i, (key, w, f, s, tx, *_rest) in rows:
            o.append("%%%s = ~farming_display_state(%s, %s);" % (TRANSMIT[tx], w, var(i, key, "state")))
        o.append("")
        if sq in SHARED_SQUARES:
            o.append("// [mapzone,0_%s] is %s's; it calls the sync above." % (sq, SHARED_SQUARES[sq]))
            o.append("")
        else:
            o.append("[mapzone,0_%s]" % sq)
            o.append("~farming_slot_sync_0_%s;" % sq)
            o.append("")
    return "\n".join(o).rstrip("\n") + "\n"


def build_varp():
    o = ["// GENERATED by tools/gen_farming_patch_slots.py: state, seed, growth clock,",
         "// harvest lives (a flower's amount) and the flags word of each patch in its",
         "// PATCHES table.", ""]
    for i, p in enumerate(PATCHES):
        for field in FIELDS:
            o += ["[%s]" % varp_name(i, p[0], field), "protect=no", "transmit=no", "scope=perm",
                  "clientcode=default", "wholewrite=deny", "wholeread=deny", ""]
    return "\n".join(o).rstrip("\n") + "\n"


def build_dbrow():
    o = ["// GENERATED by tools/gen_farming_patch_slots.py: the farming_patches rows of",
         "// its PATCHES table. view_id: the patch's row in cache enum_1233.", ""]
    for key, w, f, sq, tx, flower, view, note in PATCHES:
        if note:
            o.append("// view_id %s: %s" % (view, note))
        o += ["[farming_patch_%s]" % key, "table=farming_patches", "data=patch,%s" % w,
              "data=type,%s" % FAMILY[f], "data=view_id,%d" % view, "data=stage_mins,%s" % STAGE[f], ""]
    return "\n".join(o).rstrip("\n") + "\n"


def alloc_lines():
    return ["%d=%s" % (FIRST_VARP + i * len(FIELDS) + FIELDS.index(field), varp_name(i, p[0], field))
            for i, p in enumerate(PATCHES) for field in FIELDS]


def main():
    outs = {OUT_RS2: build_rs2(), OUT_VARP: build_varp(), OUT_DBROW: build_dbrow()}
    alloc = open(VARP_ALLOC, encoding="utf-8").read()
    missing = [l for l in alloc_lines() if l not in alloc.split("\n")]
    if "--check" in sys.argv:
        stale = [p for p, t in outs.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        for p in stale:
            print("stale:", p)
        if missing:
            print("varp.alloc lacks %d id(s)" % len(missing))
        return 1 if stale or missing else 0
    for p, t in outs.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(t)
        print("wrote", p)
    if missing:
        for l in missing:
            n = int(l.split("=")[0])
            taken = re.search(r"^%d=" % n, alloc, re.M)
            assert not taken, "varp %d is already allocated to something else" % n
        with open(VARP_ALLOC, "a", encoding="utf-8") as f:
            f.write("\n".join(missing) + "\n")
        print("appended %d varp id(s) to %s" % (len(missing), VARP_ALLOC))
    return 0


if __name__ == "__main__":
    sys.exit(main())
