#!/usr/bin/env python3
"""Generate the generic sea-charting loc bindings.

Every chartable loc (configs/all.loc sailing_charting_generic_*, op1 "Chart")
is bound to the sailing_charting_generic row of the same name; the one pair
whose names differ is mapped by hand below. Writes
OSRS-Content/osrs239-content/server/scripts/sailing/scripts/sailing_charting_generic.rs2.

    python3 tools/gen_sailing_charting_generic.py
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "OSRS-Content", "osrs239-content")
OUT = os.path.join(CONTENT, "server", "scripts", "sailing", "scripts", "sailing_charting_generic.rs2")

# loc symbol -> row symbol where the cache names them differently (same sea,
# same wreck: the Strait of Khazard's rowboat is the "port_khazard" row).
RENAMED = {
    "sailing_charting_generic_rowboat_strait_of_khazard": "sailing_charting_generic_rowboat_port_khazard",
}


def headers(path, table=None):
    out = []
    name = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"^\[(.+)\]$", line.rstrip("\n"))
            if m:
                name = m.group(1)
                if table is None:
                    out.append(name)
                continue
            if table is not None and name and line.strip() == "table=" + table:
                out.append(name)
    return out


def main():
    locs = [n for n in headers(os.path.join(CONTENT, "configs", "all.loc"))
            if n.startswith("sailing_charting_generic_")]
    rows = set(headers(os.path.join(CONTENT, "configs", "all.dbrow"), "sailing_charting_generic"))
    # Each task's own completion varbit, `varb<N>_<row>_complete`: the bit of
    # varp5016.. the Captain's Log reads (startbit = the core row's unique_id).
    done = {}
    for name in headers(os.path.join(CONTENT, "configs", "all.varbit")):
        m = re.match(r"^varb\d+_(sailing_charting_generic_.+)_complete$", name)
        if m:
            done[m.group(1)] = name
    lines = [
        "// GENERATED by tools/gen_sailing_charting_generic.py -- do not edit by hand.",
        "// Each chartable loc's Chart op, bound to its sailing_charting_generic row",
        "// (sailing_charting.rs2 [label,sailing_chart_generic]). Aboard, the loc is",
        "// reached at approach distance from the deck's projection; ashore, adjacent.",
        "",
    ]
    bound = []
    for loc in sorted(locs):
        row = RENAMED.get(loc, loc)
        if row not in rows:
            sys.exit("no sailing_charting_generic row for loc " + loc)
        if row not in done:
            sys.exit("no completion varbit for row " + row)
        bound.append(row)
        lines += [
            "[aploc1,%s]" % loc,
            "if (vessel_here = 0) { p_aprange(1); return; }",
            "@sailing_chart_generic(%s);" % row,
            "[oploc1,%s] @sailing_chart_generic(%s);" % (loc, row),
            "",
        ]
    lines += ["// The task's completion bit.", "[proc,sailing_chart_generic_done](dbrow $row)(boolean)",
              "switch_dbrow ($row) {"]
    for row in bound:
        lines.append("    case %s : if (%%%s = 1) return(true);" % (row, done[row]))
    lines += ["}", "return(false);", "", "[proc,sailing_chart_generic_mark](dbrow $row)",
              "switch_dbrow ($row) {"]
    for row in bound:
        lines.append("    case %s : %%%s = 1;" % (row, done[row]))
    lines += ["}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %d bindings to %s" % (len(locs), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
