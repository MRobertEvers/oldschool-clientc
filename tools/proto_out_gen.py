#!/usr/bin/env python3
"""Generate src/net/proto/proto_out_writers.h from RSProt's client codecs.

    tools/proto_out_gen.py            write it
    tools/proto_out_gen.py --check    exit 1 if it is stale

One writer per client -> server packet file in 3rd/rsprot/packets/ (the
message an `_in` codec takes): it fills that message from struct ProtoOutArgs
(src/net/proto/proto_out.h), whose fields are named after RSProt's, so each
writer is `m->f = a->f` for every field f. A message with a field the
arguments do not carry gets no writer and is listed; proto_encode asserts if a
revision ever needs one, rather than sending a field it never set.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKETS = os.path.join(ROOT, "3rd", "rsprot", "packets")
ARGS_H = os.path.join(ROOT, "src", "net", "proto", "proto_out.h")
OUT = os.path.join(ROOT, "src", "net", "proto", "proto_out_writers.h")

STRUCT_RE = re.compile(r"typedef struct (\w+) \{(.*?)\} (\w+);", re.S)
IN_FN_RE = re.compile(r"void packet_\w+_in\(RsprotExec \*x, (\w+) \*m\);")
BIND_RE = re.compile(r"^/\* rsprot-bind: (\w+) \*/$", re.M)
TABLE_RE = re.compile(r"extern const RsprotVersionRange rsprot_(\w+)_in\[\];")
FIELD_RE = re.compile(r"^\s*((?:const\s+)?[\w ]+?\s*\**)\s*(\w+)(\[\w+\])?;", re.M)


def args_fields():
    text = open(ARGS_H).read()
    body = text[text.index("struct ProtoOutArgs\n{"):text.index("};", text.index("struct ProtoOutArgs\n{"))]
    out = {}
    for m in FIELD_RE.finditer(body):
        out[m.group(2)] = (m.group(1).replace(" ", ""), m.group(3))
    return out


def generate():
    args = args_fields()
    writers = []
    rows = []
    skipped = []
    for name in sorted(os.listdir(PACKETS)):
        if not name.endswith(".h"):
            continue
        text = open(os.path.join(PACKETS, name)).read()
        tables = TABLE_RE.findall(text)
        if not tables:
            continue
        types = set(IN_FN_RE.findall(text))
        if len(types) != 1:
            skipped.append("%s: %d message types in its _in codecs" % (name, len(types)))
            continue
        msg = types.pop()
        struct = None
        for m in STRUCT_RE.finditer(text):
            if m.group(3) == msg:
                struct = m.group(2)
        if struct is None:
            skipped.append("%s: %s is declared elsewhere" % (name, msg))
            continue
        fields = [(f.group(1).replace(" ", ""), f.group(2), f.group(3)) for f in FIELD_RE.finditer(
            re.sub(r"/\*.*?\*/", "", struct, flags=re.S))]
        lines = []
        missing = []
        for ctype, fname, arr in fields:
            if fname.startswith("_unused") or fname == "padding":
                continue
            # A 64-bit field takes the argument's 64-bit form (count -> count_long).
            src = fname + "_long" if ctype == "int64_t" and fname + "_long" in args else fname
            if src not in args:
                missing.append(fname)
                continue
            atype, aarr = args[src]
            if (ctype == "int64_t") != (atype == "int64_t"):
                missing.append(fname + " (width)")
                continue
            if (arr is None) != (aarr is None):
                missing.append(fname + " (shape)")
                continue
            if arr:
                lines.append("    memcpy(m->%s, a->%s, sizeof(m->%s));" % (fname, fname, fname))
            else:
                lines.append("    m->%s = a->%s;" % (fname, src))
        if missing:
            skipped.append("%s (%s): no argument for %s" % (name, msg, ", ".join(missing)))
            continue
        fn = "w_" + name[:-2]
        writers += ["static void", "%s(void* msg, struct ProtoOutArgs const* a)" % fn, "{",
                    "    %s* m = (%s*)msg;" % (msg, msg), ""] + (lines or ["    (void)m;", "    (void)a;"]) + ["}", ""]
        includes = name
        for table in tables:
            for prot in BIND_RE.findall(text) or [table.upper()]:
                rows.append('    { "%s", %s },' % (prot, fn))
        writers.insert(0, '#include "packets/%s"' % includes)
    incs = sorted(l for l in writers if l.startswith("#include"))
    body = [l for l in writers if not l.startswith("#include")]
    out = ["/*",
           " * GENERATED by tools/proto_out_gen.py from 3rd/rsprot/packets/ -- do not edit.",
           " * One writer per client packet file: its `_in` codec's message, filled from",
           " * struct ProtoOutArgs field by field (src/net/proto/proto_out.h).",
           " *",
           " * Files with no writer (a field the arguments do not carry):"]
    out += [" *   " + s for s in skipped] + [" */", "", "#include <string.h>", ""]
    out += incs + ["", "/* clang-format off */"] + body
    out += ["struct ProtoOutWriter", "{", "    char const* prot;",
            "    void (*fill)(void* msg, struct ProtoOutArgs const* a);", "};", "",
            "static struct ProtoOutWriter const k_proto_out_writers[] = {"] + rows + ["};",
                                                                                "/* clang-format on */", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    old = open(OUT).read() if os.path.exists(OUT) else None
    if old == text:
        return
    if args.check:
        print("stale: " + os.path.relpath(OUT, ROOT))
        sys.exit(1)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote " + os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
