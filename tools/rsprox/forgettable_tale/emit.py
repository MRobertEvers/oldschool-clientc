#!/usr/bin/env python3
"""emit.py: write forget_tracks.rs2 from gen.py's validated graphs and the recorded loc builds."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen, walk, copymap
S = os.path.dirname(os.path.abspath(__file__)) + '/'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../../OSRS-Content/osrs-content/server/scripts/quests/quest_forgettabletale/scripts/forget_tracks.rs2')
# each platform's box (RSProx 4646 card_box locs on plane 3 per group)
BOX = {(1, 1): (1898, 4985), (1, 2): (1897, 4986), (1, 3): (1915, 4987),
       (2, 1): (1898, 4985), (2, 2): (1906, 4985), (2, 3): (1918, 4990),
       (3, 1): (1906, 4987), (3, 2): (1898, 4986)}
SHAPE = {22: 'grounddecor', 10: 'centrepiece_straight'}
KEEP = re.compile(r'keldagrim_track|keldagrim_trackstraight|keldagrim_trackbuffer|forget_train_return_cart')

def pieces(lo, hi):
    locs = {}
    for line in open(S + 'tun.txt'):
        t, rest = line.split('\t', 1)
        t = int(t)
        if t < lo or t > hi:
            continue
        m = re.search(r'loc_add_change_v\d\] id=(\w+) \(\d+\), coord=\((\d+), (\d+), (\d+)\), shape=(\d+), rotation=(\d)', rest)
        if not m:
            continue
        name, x, z, p, sh, rot = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4)), int(m.group(5)), int(m.group(6))
        if not KEEP.search(name) or x < 1856 or x > 1919 or z < 4928 or z > 4991:
            continue
        name = name.replace('_a_left', '_a').replace('_a_right', '_a').replace('card_box_open', 'card_box')
        locs[(x, z, p, sh)] = (name, rot)
    return locs

def lc(t):
    """A copy-local tile (lx, lz, plane) as RuneScript."""
    return f'~forget_t({t[0]}, {t[1]}, {t[2]})'

def c(x, z, p):
    """A plane-0/1 template tile, which is the same tile in the copy."""
    assert p <= 1, (x, z, p)
    return lc((x - 1856, z - 4928, p))

# The group being written, and the copy-local tile the last step left the
# player on (copymap.copy_tile places a platform tile next to it).
CUR = {'g': 0, 'prev': None}

def to_copy(t):
    m = copymap.copy_tile(CUR['g'], t[0], t[1], t[2], CUR['prev'] or (t[0] - 1856, t[1] - 4928))
    return m

def seg(sg, land_override=None, first=False):
    (x0, z0, p0), (x1, z1, p1), delay, ang, land, snd = sg[0], sg[1], sg[2], sg[3], sg[4], sg[5]
    if land_override is not None:
        land = land_override
    a = to_copy((x0, z0, p0))
    CUR['prev'] = a
    b = to_copy((x1, z1, p1))
    CUR['prev'] = b
    l = to_copy(land)
    CUR['prev'] = l
    # In the copy no step changes plane or jumps: ~forget_cart_seg always slides.
    assert a[2] == b[2] == l[2] and abs(l[0] - b[0]) + abs(l[1] - b[1]) <= 2, (sg, a, b, l)
    return f'~forget_cart_seg({lc(a)}, {lc(b)}, {delay}, {ang}, {lc(l)}, {snd});'

def main():
    lines = ['// GENERATED by docs/rsprox-analysis/quests/forgettable_tale.md "The rides"',
             '// (tools/rsprox/forgettable_tale, over RSProx index 4646). Do not edit by hand:',
             '// every track piece of the three junction groups, laid in the player\'s copy of',
             '// the tunnels, and every ride over them -- one proc per junction exit. All 20',
             '// recorded rides are reproduced tile for tile; every other exit follows the',
             '// same rules (the analysis doc).', '']
    builds = {}
    for g in (1, 2, 3):
        b = gen.Build(g); b.build(); builds[g] = b
        lo, hi = walk.GROUPS[g]
        P = pieces(lo, hi)
        if g == 1:
            # group one's third platform: no ride reached it, so no cart was ever
            # sent; every recorded platform has its return cart on the arrival tile
            P[(1916, 4990, 3, 10)] = ('forget_train_return_cart', 2)
        placed = []
        raw = copymap.raw_pieces(lo, hi)
        for (x, z, p, sh), (name, rot) in sorted(P.items(), key=lambda k: (k[0][2], k[0][1], k[0][0])):
            lx, lz = x - 1856, z - 4928
            if p >= 2 and (lx // 8, lz // 8) not in copymap.SUBS[g].values():
                continue
            for t in copymap.copies_of(g, x, z, p):
                # a platform piece where Jagex laid it: its zone is copied to two places
                # in group one, the piece only to its own platform's (--raw)
                unrecorded = (x, z, p) == (1916, 4990, 3)   # group one's third platform's cart
                if p >= 2 and (name, t[0], t[1], t[2]) not in raw and not unrecorded:
                    continue
                placed.append((t, name, rot, sh))
        lines.append(f'// Group {g}: {len(placed)} pieces.')
        lines.append(f'[proc,forget_build_g{g}]')
        for t, name, rot, sh in sorted(placed, key=lambda k: (k[0][2], k[0][1], k[0][0])):
            lines.append(f'loc_add({lc(t)}, {name}, {rot}, {SHAPE.get(sh, "grounddecor")}, ^forget_placed_loc_ticks);')
        lines.append('')
        # junction pieces shown as set (4646 [3021]): 0 plain, 1 left (green), 2 right (yellow)
        lines.append(f'[proc,forget_show_junctions_g{g}]')
        for i, (jx, jz) in enumerate(b.order):
            lines.append(f'~forget_show_junction({c(jx, jz, 1)}, ~forget_junction_get({i}));')
        lines.append('')
    for g, b in builds.items():
        CUR['g'] = g
        lines.append(f'// ---- group {g} rides: switch i is the i-th junction breadth-first ----')
        # the start: onto the cart, the run east to junction 0
        hx, hz = b.hub
        lines.append(f'[proc,forget_ride_g{g}]')
        lines += arrive_lines(b, 0, gen.HUB_START[0], gen.HUB_START[1], start=True)
        lines.append('')
        for i, n in enumerate(b.order):
            lines.append(f'[proc,forget_g{g}_j{i}]')
            lines.append(f'if (~forget_junction_get({i}) = 1) {{')
            lines.append(f'    ~forget_g{g}_j{i}_n;')
            lines.append('} else {')
            lines.append(f'    ~forget_g{g}_j{i}_s;')
            lines.append('}')
            lines.append('')
            for d in 'NS':
                lines.append(f'[proc,forget_g{g}_j{i}_{d.lower()}]')
                lines += edge_lines(b, n, d)
                lines.append('')
        for n, info in b.nodes.items():
            if info['type'] == 'B':
                lines.append(f'[proc,forget_g{g}_bend_{n[0]}_{n[1]}]')
                lines += edge_lines(b, n, info['dir'])
                lines.append('')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(lines), 'lines')

# ---- step timing (validated on all 20 recorded rides by delays.py) ----
# A three-tile step that runs into a turn, or into a slow mouth (delay 90 or
# more), goes at delay 90 and the next step waits a tick more; the start's
# second step is 90 only over three tiles; a stop (blocked, buffer) is 80 over
# one tile and 130 over more.
def _tiles(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])

def _is_turn(st):
    sg = st['seg']
    land = st.get('land', sg[4])
    if land is None or land == 'PORTAL' or land[2] != sg[1][2] or _tiles(sg[1], land) > 4:
        return False
    return tuple(sg[1][:2]) != tuple(land[:2])

def _slow_jump(st):
    return not _is_turn(st) and st['seg'][2] >= 90

def finalize(steps, then_turn):
    if len(steps) > 1 and steps[0]['kind'] == 'start0' and _tiles(steps[1]['seg'][0], steps[1]['seg'][1]) != 3:
        steps[1]['seg'][2] = 60
    for i, st in enumerate(steps):
        sg = st['seg']
        if st['kind'] in ('fixed', 'start0', 'start1'):
            continue
        if st['kind'] == 'stop':
            sg[2] = 80 if _tiles(sg[0], sg[1]) <= 1 else 130
            continue
        nxt_turn = then_turn if i + 1 == len(steps) else (_is_turn(steps[i + 1]) or _slow_jump(steps[i + 1]))
        if _tiles(sg[0], sg[1]) == 3 and nxt_turn:
            sg[2] = 90
    out = []
    CUR['prev'] = None
    for st in steps:
        out += st.get('pre', [])
        out.append(seg(st['seg'], land_override=st.get('land_override')))
        if st['kind'] == 'start0':
            out.append('p_delay(2);')
        elif st['seg'][2] == 90:
            out.append('p_delay(1);')
        else:
            out.append('p_delay(0);')
    return out

def arrive_steps(b, idx, x0, z0, blocked, start=False):
    jx, jz = b.order[idx]
    tx = jx - 1 if blocked else jx
    steps = []
    segs = gen.Build.runsegs(x0, z0, tx, jz, gen.E)
    for k, sg in enumerate(segs):
        sg = list(sg)
        kind = ''
        if start and k == 0:
            sg[2] = 135; kind = 'start0'
        elif start and k == 1:
            sg[2] = 90; kind = 'start1'
        if not blocked and k == len(segs) - 1:
            sg[5] += 1
        if blocked and k == len(segs) - 1:
            kind = 'stop'
        st = {'seg': sg, 'kind': kind}
        if start and k == 0:
            st['pre'] = ['sound_synth(cart_away, 1, 30);']
        steps.append(st)
    return steps

def arrive_lines(b, idx, x0, z0, start=False, before=None):
    """The run east from (x0,z0) to junction idx: stopped a tile short when it is empty."""
    out = []
    before = before or []
    for blocked in (True, False):
        own = arrive_steps(b, idx, x0, z0, blocked, start)
        steps = [dict(s, seg=list(s['seg'])) for s in before] + own
        if not own and not blocked and steps:
            # landed on the junction already: its sound goes on the step before
            steps[-1]['seg'][5] += 1
        body = finalize(steps, not blocked)
        if blocked:
            out.append(f'if (~forget_junction_get({idx}) = 0) {{')
            out += ['    ' + l for l in body]
            out.append('    ~forget_cart_blocked;')
            out.append('    return;')
            out.append('}')
        else:
            out += body
            out.append(f'~forget_g{b.g}_j{idx};')
    return out

def edge_lines(b, n, d):
    segs, term = b.edges[(n, d)]
    kind = term[0]
    steps = []
    for k, sg in enumerate(segs):
        sg = list(sg)
        last = k == len(segs) - 1
        if sg[4] == 'PORTAL':
            portal = term[1]
            entry = portal[2][0] if portal[2] else None
            sg[5] += gen.MOUTH_TURNS.get((term[1][0], b.g, term[1][1]), 0)
            steps.append({'seg': sg, 'kind': 'fixed', 'land_override': entry, 'land': entry})
            continue
        steps.append({'seg': sg, 'kind': 'stop' if (kind == 'X' and last) else ''})
    if kind == 'J':
        nxt = term[1]
        idx = b.idx[nxt]
        lx, lz = (segs[-1][4][0], segs[-1][4][1]) if segs else (n[0], n[1])
        # one run: the edge's steps and the arrival, timed together
        return arrive_lines(b, idx, lx, lz, before=steps)
    out = []
    if kind == 'NODE':
        out += finalize(steps, True)
        out.append(f'~forget_g{b.g}_bend_{term[1][0]}_{term[1][1]};')
    elif kind == 'X':
        out += finalize(steps, False)
        out.append('~forget_cart_deadend;')
    elif kind == 'MOUTH':
        pk, num, tail = term[1]
        turns = gen.TAIL_TURNS.get((pk, b.g, num), [])
        for k, t in enumerate(gen.TAILS.get((pk, b.g, num), [])):
            steps.append({'seg': [t[0], t[1], t[2], t[3], t[4], turns[k]], 'kind': 'fixed'})
        out += finalize(steps, False)
        if pk == 'P':
            tails = gen.TAILS.get((pk, b.g, num), [])
            ax, az, ap = tails[-1][4] if tails else tail[0]
            bx, bz = BOX[(b.g, num)]
            sz = 1 if bz > az else -1
            # [3046]: four ticks on, one step off the cart toward the box
            out.append(f'~forget_cart_platform({num}, {lc(to_copy((ax, az + sz, ap)))});')
        elif pk == 'PX':
            out.append('~forget_cart_deadend;')
        elif pk == 'ROOM':
            out.append(f'~forget_cart_room;')
        elif pk == 'BRIDGE':
            bx, bz = gen.BRIDGE_EXIT[b.g]
            # the jump off the bridge is a 90 step: finalize's p_delay(1) is
            # the recorded two ticks to the next step ([4066] -> [4068])
            idx = b.idx[(bx, bz)]
            out.append(f'if (~forget_junction_get({idx}) = 0) {{')
            out.append('    ~forget_cart_blocked;')
            out.append('    return;')
            out.append('}')
            out.append(f'~forget_g{b.g}_j{idx};')
    else:
        out += finalize(steps, False)
        out.append('// unreachable: no stop recorded or derived')
        out.append('~forget_cart_deadend;')
    return out

if __name__ == '__main__':
    main()
