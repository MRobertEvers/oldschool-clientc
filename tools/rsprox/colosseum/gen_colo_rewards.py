#!/usr/bin/env python3
"""Generate minigame_colosseum/scripts/colosseum_reward_tables.rs2 from the
pinned wiki chest page (tools/rsprox/colosseum/colo_wiki_rewards.py).

    python3 tools/rsprox/colosseum/gen_colo_rewards.py
"""
import math
import os
import sys
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from colo_wiki_rewards import tables, ROOT  # noqa: E402

OUT = os.path.join(ROOT, "OSRS-Content/osrs-content/server/scripts/minigames/minigame_colosseum/scripts/colosseum_reward_tables.rs2")
OBJ = {
    "Sunfire splinters": "sunfiresplinter", "Rune platebody": "rune_platebody", "Death rune": "deathrune",
    "Chaos rune": "chaosrune", "Steel cannonball": "mcannonball", "Rune kiteshield": "rune_kiteshield",
    "Rune chainbody": "rune_chainbody", "Onyx bolts": "xbows_crossbow_bolts_runite_tipped_onyx",
    "Snapdragon seed": "snapdragon_seed", "Dragon platelegs": "dragon_platelegs", "Earth orb": "earth_orb",
    "Rune 2h sword": "rune_2h_sword", "Gold ore": "gold_ore", "Dragon bolts (unf)": "dragon_bolts_unfeathered",
    "Ranarr seed": "ranarr_seed", "Dragon arrowtips": "dragon_arrowheads", "Adamantite ore": "adamantite_ore",
    "Runite ore": "runite_ore", "Rune warhammer": "rune_warhammer", "Dragon plateskirt": "dragon_plateskirt",
    "Uncut onyx": "uncut_onyx", "Echo crystal": "echo_crystal",
    "Tonalztics of Ralos (uncharged)": "tonalztics_of_ralos_uncharged",
}
ARMOUR = ("Sunfire fanatic helm", "Sunfire fanatic cuirass", "Sunfire fanatic chausses")
SKIP = ("Dizana's quiver", "Smol Heredit", "Token (Varlamore)")


def main():
    by = {}
    for w, name, lo, hi, fr in tables():
        if name in SKIP or fr is None:
            continue
        by.setdefault(w, []).append((name, lo, hi, fr))
    lines = [
        "// GENERATED by tools/rsprox/colosseum/gen_colo_rewards.py from the pinned wiki chest page",
        "// (docs/minigames/colosseum/sources/wiki/wiki_Rewards_Chest_Fortis_Colosseum.wikitext).",
        "// Do not edit: change the generator. Each wave's table is one roll out of its common",
        "// denominator; the three sunfire pieces are rolled as one outcome (^colo_reward_armour)",
        "// so ~colo_reward_roll can give a missing piece first, and the 2-3 echo crystals as",
        "// ^colo_reward_echo_multi. The recordings agree with these tables wave by wave",
        "// (docs/rsprox-analysis/colosseum/README.md, the rewards section).",
        "",
    ]
    for w in sorted(by):
        rows = []
        armour = Fraction(0)
        for name, lo, hi, fr in by[w]:
            if name in ARMOUR:
                armour += fr
            else:
                rows.append((name, lo, hi, fr))
        if armour:
            rows.append(("ARMOUR", 1, 1, armour))
        den = 1
        for r in rows:
            den = den * r[3].denominator // math.gcd(den, r[3].denominator)
        lines.append(f"// Wave {w}: one roll out of {den}.")
        lines.append(f"[proc,colo_reward_table_{w}](int $roll)(namedobj, int)")
        acc = 0
        for name, lo, hi, fr in rows:
            wt = int(fr * den)
            acc += wt
            if name == "ARMOUR":
                obj, cnt = "null", "^colo_reward_armour"
            elif name == "Echo crystal" and hi > lo:
                obj, cnt = "echo_crystal", "^colo_reward_echo_multi"
            else:
                obj, cnt = OBJ[name], str(lo)
            lines.append(f"if ($roll < {acc}) return({obj}, {cnt}); // {name} x{lo}{'-' + str(hi) if hi > lo else ''}: {fr}")
        assert acc == den, (w, acc, den)
        lines.append(f"return(null, 0);")
        lines.append("")
        lines.append(f"[proc,colo_reward_den_{w}]()(int)")
        lines.append(f"return({den});")
        lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
