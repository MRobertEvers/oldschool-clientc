#!/usr/bin/env python3
"""Write the level-up unlock table from the cache's skill guide.

Which jingle a level-up plays is decided by whether the levels it crossed unlock
anything: Woodcutting 13 from 2 plays `woodcutting_level_up_unlocks`, 14 from 13
plays `woodcutting_level_up` (RSProx index 4393 [652], 4394 [754]; 21 of 21
recorded rev-241 level-ups outside the fixed-jingle skills). "Unlocks anything"
is a `skill_features` row (the skill guide's, dbtable 213) whose `skill` field
names that skill at a level in (old, new].

`skill_features` has no index on `skill` and 3,447 rows, so the level-up script
cannot ask it directly; this writes the answer per stat as one row each.

    tools/gen_levelup_unlocks.py [--tree OSRS-Content/osrs-content] [--check]
"""
import argparse
import os
import sys

# The skill guide's own skill numbering (the first field of `skill_features:skill`,
# and the first argument of clientscript `levelup_chatbox_transmit` 7781: Attack
# 1, Magic 4, Prayer 7, Thieving 10, Woodcutting 18, Construction 22 in the
# recordings). It is the guide's order, not the protocol's stat index.
GUIDE_TO_STAT = {
    1: "attack", 2: "strength", 3: "ranged", 4: "magic", 5: "defence",
    6: "hitpoints", 7: "prayer", 8: "agility", 9: "herblore", 10: "thieving",
    11: "crafting", 12: "runecraft", 13: "mining", 14: "smithing", 15: "fishing",
    16: "cooking", 17: "firemaking", 18: "woodcutting", 19: "fletching",
    20: "slayer", 21: "farming", 22: "construction", 23: "hunter", 24: "sailing",
}

OUT = "server/scripts/levelup/configs/levelup_unlocks.generated.dbrow"


def unlock_levels(dbrow_path):
    levels = {stat: set() for stat in GUIDE_TO_STAT.values()}
    in_table = False
    with open(dbrow_path, encoding="latin-1") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("["):
                in_table = False
            elif line == "table=skill_features":
                in_table = True
            elif in_table and line.startswith("data=skill,"):
                fields = line[len("data=skill,"):].split(",")
                guide, level = int(fields[0]), int(fields[1])
                if guide in GUIDE_TO_STAT and 1 < level <= 99:
                    levels[GUIDE_TO_STAT[guide]].add(level)
    return levels


def render(levels):
    out = [
        "// GENERATED by tools/gen_levelup_unlocks.py from configs/all.dbrow",
        "// (`skill_features`). Do not edit; rerun the tool.",
        "//",
        "// The levels at which the skill guide lists something for each stat:",
        "// a level-up that crosses one plays the stat's `_unlocks` jingle.",
    ]
    for stat in GUIDE_TO_STAT.values():
        out.append("")
        out.append(f"[levelup_unlocks_{stat}]")
        out.append("table=levelup_unlock_table")
        out.append(f"data=stat,{stat}")
        for level in sorted(levels[stat]):
            out.append(f"data=level,{level}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", default="OSRS-Content/osrs-content")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text = render(unlock_levels(os.path.join(args.tree, "configs/all.dbrow")))
    path = os.path.join(args.tree, OUT)
    if args.check:
        with open(path) as f:
            if f.read() != text:
                print(f"{path} is stale: rerun tools/gen_levelup_unlocks.py", file=sys.stderr)
                return 1
        return 0
    with open(path, "w") as f:
        f.write(text)
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
