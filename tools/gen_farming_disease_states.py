#!/usr/bin/env python3
"""Generate skill_farming/configs/farming_disease.enum from the cache.

A farming patch draws whatever its wrapper loc's multiloc list holds at the
transmitted state. The diseased and dead art sit at different places in each
patch family's list (allotments and flowers +128 / +192, herbs one diseased
set per herb from 128 and one shared dead set from 170, hops +11 / +139 for
hammerstone, trees +64 / +128, fruit trees +12 / +18, ...), and in a few lists
not at a fixed offset at all (snape grass). So nothing is computed: each
healthy growth state is mapped to the state whose loc NAME is its diseased or
dead form, in the same list.

    <crop>_<n>                 -> <crop>_<n>_diseased  | <crop>_diseased_<n>
    <crop>_fullygrown(_k)      -> <crop>_fullygrown_diseased | <crop>_diseased_fullygrown
    dead likewise, and the herbs' shared herb_<n>_dead

Two enums per family, farming_<family>_diseased and farming_<family>_dead,
int -> int, default -1 (no such art: that state cannot show disease), and for
the three families a watering can reaches (allotments, flowers, hops)
farming_<family>_watered: hops lay their watered art out at +128, not the
allotments' +64. The scripts read them in ~farming_disease_display and
~farming_display_state.

Usage:
    python3 tools/gen_farming_disease_states.py [--check]
--check exits non-zero if the checked-in file differs.
"""

import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(REPO, "OSRS-Content", "osrs-content")
ALL_LOC = os.path.join(CONTENT, "configs", "all.loc")
OUT = os.path.join(CONTENT, "server", "scripts", "skill_farming", "configs",
                   "farming_disease.enum")

# family -> the wrapper whose list every patch of that family shares.
FAMILIES = [
    ("allot", "farming_veg_patch_1"),
    ("flower", "farming_flower_patch_1"),
    ("herb", "farming_herb_patch_1"),
    ("hops", "farming_hops_patch_1"),
    ("bush", "farming_bush_patch_1"),
    ("tree", "farming_tree_patch_1"),
    ("hardwood", "farming_hardwood_tree_patch_1"),
    ("fruit", "farming_fruit_tree_patch_1"),
    ("spirit", "farming_spirit_tree_patch_1"),
    ("calquat", "farming_calquat_tree_patch"),
    ("cactus", "farming_cactus_patch"),
    ("mushroom", "farming_mushroom_patch"),
    ("belladonna", "farming_belladonna_patch"),
    ("celastrus", "farming_celastrus_patch_1"),
    ("redwood", "farming_redwood_tree_patch_0_1"),
]


def tables(path, wanted):
    out = {w: {} for w in wanted}
    cur = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("["):
                name = line[1:-1]
                cur = name if name in out else None
                continue
            if cur is None:
                continue
            m = re.match(r"multiloc(\d+)=([^,\s]+)", line)
            if m:
                out[cur][int(m.group(1)) - 1] = m.group(2)
    return out


def variants(name, kind):
    """Candidate names for the <kind> ('diseased'|'dead') form of `name`."""
    c = [name + "_" + kind]
    m = re.match(r"(.*)_(\d+)$", name)
    if m:
        base, n = m.group(1), m.group(2)
        c.append(base + "_" + kind + "_" + n)
        if base.startswith("herb_") and kind == "dead":
            c.append("herb_" + n + "_dead")
        # oak_tree_fullygrown_1 -> oak_tree_diseased_fullygrown
        fm = re.match(r"(.*)_fullygrown$", base)
        if fm:
            c.append(fm.group(1) + "_" + kind + "_fullygrown")
            c.append(base + "_" + kind)
    m = re.match(r"(.*)_fullygrown$", name)
    if m:
        c.append(m.group(1) + "_" + kind + "_fullygrown")
    # The cache's own spellings: herb_marentill_diseased_1 (one r) beside
    # herb_marrentill_1, and celastrus_dead_1 beside celastrus_tree_1.
    # snapegrass_seedling waters to snapegrass_seed_watered.
    if name.endswith("_seedling"):
        c.append(name[:-len("_seedling")] + "_seed_" + kind)
    more = []
    for x in c:
        more.append(x.replace("marrentill", "marentill"))
        more.append(x.replace("_tree_" + kind, "_" + kind))
    return c + more


def is_healthy(name):
    # "weeds" / "_weeded", not "weed": goutweed, ranarr weed and dwarf weed
    # are crops.
    return not re.search(r"(diseased|dead|weeds|_weeded|stump|claim|_seed$|"
                         r"seedling|watered|placeholder)", name) and name != "null"


def build():
    wanted = [w for _, w in FAMILIES]
    t = tables(ALL_LOC, wanted)
    lines = [
        "// GENERATED by tools/gen_farming_disease_states.py from configs/all.loc.",
        "// Do not edit: rerun the tool. Each family's healthy growth state ->",
        "// the state of the same crop's diseased / dead art in that family's",
        "// wrapper multiloc list, matched by loc name; -1 where the cache has none.",
        "",
    ]
    for fam, wrapper in FAMILIES:
        ml = t[wrapper]
        assert ml, "no multiloc table for " + wrapper
        index = {}
        for s, n in sorted(ml.items()):
            index.setdefault(n, s)
        for kind in ("diseased", "dead", "watered"):
            if kind == "watered" and fam not in ("allot", "flower", "hops"):
                continue
            rows = []
            for s, n in sorted(ml.items()):
                # A seed can be watered, never diseased or dead.
                seed = kind == "watered" and re.search(r"(_seed|seedling)$", n)
                if not seed and not is_healthy(n):
                    continue
                for cand in variants(n, kind):
                    if cand in index:
                        rows.append((s, index[cand]))
                        break
            lines.append("[farming_%s_%s]" % (fam, kind))
            lines.append("inputtype=int")
            lines.append("outputtype=int")
            lines.append("default=-1")
            for s, d in rows:
                lines.append("val=%d,%d" % (s, d))
            lines.append("")
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("farming_disease.enum is stale; rerun the tool")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
