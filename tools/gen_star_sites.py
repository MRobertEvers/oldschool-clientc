#!/usr/bin/env python3
"""Generate the shooting-star landing sites from the pinned wiki page.

Reads   docs/shooting_stars/sources/Shooting_Stars.wiki
Writes  OSRS-Content/osrs239-content/server/scripts/minigames/game_shootingstars/configs/star_sites.enum

The wiki lists every landing site as a map pin —
`{{Map|mtype=pin|X,Y|...|title=<region>|desc=<place>}}` — which is a table, not
prose, so it is parsed rather than typed. Near-Reality carries the same list as
`ShootingStarLocation` entries in Java.

Coords are emitted as this tree's `<level>_<mx>_<mz>_<lx>_<lz>` literal, which
is what a `coord` column takes. Level is 0 for every site: the wiki's pins are
surface positions and there is no z in a pin.

  python3 tools/gen_star_sites.py [--check]
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "shooting_stars", "sources", "Shooting_Stars.wiki")
OUT = os.path.join(
    ROOT, "OSRS-Content", "osrs239-content", "server", "scripts", "minigames",
    "game_shootingstars", "configs", "star_sites.enum",
)

PIN = re.compile(
    r"\{\{Map\|mtype=pin\|(\d{3,5}),(\d{3,5})\|[^}]*?title=([^|}]*)[^}]*?desc=([^|}]*)"
)


def to_literal(x, z):
    return "%d_%d_%d_%d_%d" % (0, x // 64, z // 64, x % 64, z % 64)


def collect():
    text = open(SRC, encoding="utf-8", errors="replace").read()
    seen, sites = set(), []
    for x, z, region, desc in PIN.findall(text):
        x, z = int(x), int(z)
        if (x, z) in seen:
            continue
        seen.add((x, z))
        sites.append((x, z, region.strip(), desc.strip()))
    return sites


def render(sites):
    lines = [
        "// Shooting Stars — where a star can land.",
        "//",
        "// GENERATED by tools/gen_star_sites.py from the pinned wikitext in",
        "// docs/shooting_stars/sources/. Hand edits are lost.",
        "//",
        "//     python3 tools/gen_star_sites.py",
        "//",
        "// The wiki lists every site as a map pin, which is a table rather than",
        "// prose, so it is parsed. Near-Reality carries the same list as Java",
        "// `ShootingStarLocation` entries.",
        "//",
        "// Level 0 throughout: the wiki's pins are surface positions and a pin",
        "// carries no plane. A site that is genuinely underground would need the",
        "// page to say so, and none of them does.",
        "",
        "[star_sites]",
        "inputtype=int",
        "outputtype=coord",
        "default=null",
    ]
    for index, (x, z, region, desc) in enumerate(sites):
        lines.append("val=%d,%s  // %s — %s" % (index, to_literal(x, z), region, desc))
    lines.append("")
    lines.append("// How many sites the enum holds, so a caller's `random()` bound comes from")
    lines.append("// the same generated file as the table it indexes.")
    lines.append("[star_site_count]")
    lines.append("inputtype=int")
    lines.append("outputtype=int")
    lines.append("default=0")
    lines.append("val=0,%d" % len(sites))
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    sites = collect()
    rendered = render(sites)

    if args.check:
        try:
            have = open(OUT, encoding="utf-8").read()
        except FileNotFoundError:
            print("gen_star_sites: %s does not exist" % OUT, file=sys.stderr)
            return 1
        if have != rendered:
            print("gen_star_sites: %s is stale — rerun the generator" % OUT, file=sys.stderr)
            return 1
        print("gen_star_sites: up to date")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print("gen_star_sites: %d landing site(s) -> %s" % (len(sites), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
