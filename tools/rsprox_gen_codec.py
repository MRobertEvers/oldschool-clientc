# --- Kotlin -> codec ----------------------------------------------------------

READ_RE = re.compile(r"buffer\.(g\w+)\(\)")


def prim_for(fn):
    """(macro, ctype, signed) for a JagByteBuf read, or None."""
    m = re.match(r"^g([1-4])(s?)(Alt[123])?$", fn)
    if m:
        width, signed, alt = m.group(1), bool(m.group(2)), m.group(3)
        suffix = "_ALT" + alt[3] if alt else ""
        if signed and not alt and width in ("1", "2"):
            return (f"I{width}", "int32_t", True)
        if width == "4":
            return (f"U4{suffix}", "int32_t", signed)
        return (f"U{width}{suffix}", "int32_t", signed)
    m = re.match(r"^gCombinedId(Alt[123])?$", fn)
    if m:
        return ("COM" + ("_ALT" + m.group(1)[3] if m.group(1) else ""), "int32_t", False)
    simple = {
        "g8": ("U8", "int64_t", True),
        "gjstr": ("JSTR", "const char *", False),
        "gjstrnull": ("JSTRNULL", "const char *", False),
        "gjstr2": ("JSTR2", "const char *", False),
        "gboolean": ("BOOL", "int32_t", False),
        "gSmart1or2": ("SMART", "int32_t", False),
        "gSmart1or2null": ("SMARTNULL", "int32_t", False),
        "gSmart2or4null": ("SMART2OR4NULL", "int32_t", False),
        "gVarInt2": ("VARINT2", "int32_t", False),
        "gVarInt2s": ("VARINT2S", "int32_t", True),
    }
    return simple.get(fn)


def snake(name):
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", s)
    return s.lower()


def statements(body):
    """Split a decode body into top-level statements, joining continuation
    lines (a `val x =` whose value is on the next lines)."""
    out = []
    depth = 0
    cur = []
    for line in body.split("\n"):
        t = line.strip()
        if not t:
            continue
        cur.append(t)
        depth += t.count("(") + t.count("{") + t.count("[")
        depth -= t.count(")") + t.count("}") + t.count("]")
        if depth <= 0 and not t.endswith("=") and not t.endswith(","):
            out.append(" ".join(cur))
            cur = []
            depth = 0
    if cur:
        out.append(" ".join(cur))
    return out


def translate(body):
    """(lines, fields, derived) for a flat body, or (None, reason, None).

    lines   C statements in wire order
    fields  [(name, ctype, signed, note)] in first-transfer order
    derived Kotlin statements that read nothing, verbatim (for the comment)
    """
    lines, fields, derived = [], [], []
    seen = set()
    skips = 0
    for st in statements(body):
        if st.startswith("return"):
            if READ_RE.search(st) or "gdata" in st or "skipRead" in st:
                return None, "wire access inside the return expression", None
            continue
        if st.startswith("@Suppress"):
            continue
        if re.search(r"\b(if|for|while|when|repeat|buildList|buildMap|try)\b\s*[({]", st):
            if READ_RE.search(st) or "gdata" in st or "skipRead" in st:
                return None, f"read under a branch or loop: {st[:70]!r}", None
            derived.append(st)
            continue
        m = re.match(r"^buffer\.skipRead\((\d+)\)$", st)
        if m:
            name = f"skip{skips}"
            skips += 1
            lines.append(f"    RSPROT_DATA(x, m->{name}, {m.group(1)});")
            fields.append((name, "const uint8_t *", False, f"{m.group(1)} unused bytes"))
            continue
        m = re.match(r"^buffer\.gdata\((\w+)\)$", st)
        if m:
            arr = m.group(1)
            size = next((d for d in derived if re.match(rf"^val {arr} = ByteArray\((\d+)\)$", d)), None)
            if size is None:
                return None, f"gdata into an array of unknown size: {st!r}", None
            n = re.search(r"\((\d+)\)", size).group(1)
            derived.remove(size)
            fname = snake(arr)
            lines.append(f"    RSPROT_DATA(x, m->{fname}, {n});")
            fields.append((fname, "const uint8_t *", False, f"{n} bytes"))
            seen.add(fname)
            continue
        calls = READ_RE.findall(st)
        if not calls:
            if "buffer" in st and "ByteArray" not in st:
                return None, f"buffer use the generator does not model: {st[:70]!r}", None
            derived.append(st)
            continue
        if len(calls) > 1:
            return None, f"two reads in one statement: {st[:70]!r}", None
        m = re.match(r"^(?:val|var)\s+(\w+)(?:\s*:\s*[\w<>?]+)?\s*=\s*(.*)$", st)
        if not m:
            return None, f"wire read outside a val statement: {st[:70]!r}", None
        name, expr = m.group(1), m.group(2)
        p = prim_for(calls[0])
        if p is None:
            return None, f"unmodelled read {calls[0]}", None
        macro, ctype, signed = p
        fname = snake(name)
        if fname in seen:
            return None, f"{name} read twice", None
        seen.add(fname)
        note = ""
        wrapped = expr.strip() != f"buffer.{calls[0]}()"
        if wrapped:
            note = "RSProx: " + re.sub(r"buffer\.(\w+)\(\)", r"<\1>", expr.strip())
        lines.append(f"    RSPROT_{macro}(x, m->{fname});")
        fields.append((fname, ctype, signed, note))
    if not lines:
        return [], [], derived
    return lines, fields, derived


# --- the ledger (shared with the overlay) -------------------------------------


def ledger_class(decoder_path):
    return "RSProx." + os.path.basename(decoder_path)[:-3]


# --- emission -----------------------------------------------------------------

H_TEMPLATE = '''#ifndef RSPROT_PACKET_{guard}_H
#define RSPROT_PACKET_{guard}_H

/*
 * {prot} -- server -> client.
 *
 * GENERATED by tools/rsprox_gen_codec.py -- do not edit. Hand edits are lost on
 * the next run; change the generator, or the RSProx source it reads.
 *
 * RSProt has no codec for this prot, so the layouts come from RSProx's decoders
 * ({cls}); see the generator's docstring for why and how. Field names are
 * RSProx's variable names. v1..v{nver} are this packet's layouts in ledger
 * order; each names its row in gen/rsprox_versions.txt:
 *                    grep '^{cls}\\tout\\t' 3rd/rsprot/gen/rsprox_versions.txt
 *
 * Layouts      : {nver} distinct, over {nrun} contiguous revision run(s)
 */

#include "../include/rsprot_exec.h"{tails_include}

/** One struct for every version -- the union of all their fields. */
typedef struct {msg} {{
{fields}
}} {msg};

{decls}
{aliases}

/** Revision -> layout. See the .c for the rows. */
extern const RsprotVersionRange rsprot_{snake}_out[];
extern const int rsprot_{snake}_out_count;

#endif
'''

C_TEMPLATE = '''/* {prot}. GENERATED by tools/rsprox_gen_codec.py -- do not edit. */
#include "{snake}.h"

/*
 * Transcribed from RSProx:
 *   protocol/osrs-<N>/src/main/kotlin/net/rsprox/protocol/v<N>/game/outgoing/
 *       decoder/codec/{rel}
 */

{bodies}
/*
 * {nrun} row(s) for {nver} layout(s), over revisions {revs}. A revision not
 * listed has no {prot} and picks NULL.
 */
const RsprotVersionRange rsprot_{snake}_out[] = {{
{rows}
}};

const int rsprot_{snake}_out_count =
    (int)(sizeof(rsprot_{snake}_out) / sizeof(rsprot_{snake}_out[0]));
'''


def emit(prot, cls, rel, versions, rev_to_ver, fields, out_dir):
    sn = gen.prot_to_snake(prot)
    msg = "Msg" + gen.snake_to_pascal(sn)
    ftext = []
    for name, ctype, signed, note in fields:
        dims = ""
        if note.startswith("["):
            dims, note = note, ""
        notes = [n for n in (("signed" if signed and ctype == "int32_t" else ""), note) if n]
        tail = f" /* {'; '.join(notes)} */" if notes else ""
        ftext.append(f"\t{ctype}{'' if ctype.endswith('*') else ' '}{name}{dims};{tail}")
    tail = gen.TAILS.get(prot.upper(), {})
    assert "body" not in tail and "struct_replace" not in tail, prot
    ftext += tail.get("fields", [])
    if not ftext:
        ftext.append("\tint32_t unused; /* zero-payload packet */")
    for info in versions.values():
        info["body"] = "\n".join(tail.get("prefix", []) + ([info["body"]] if info["body"] else [])
                                 + tail.get("suffix", []))
    num = gen.layout_numbers(versions)
    decls, bodies = [], []
    for ver in sorted(versions, key=num.get):
        info = versions[ver]
        rngs = gen.fmt_ranges(gen.compress_ranges(info["revs"]))
        fn = f"packet_{sn}_v{num[ver]}_out"
        note = f"/* v{num[ver]} -- revs {rngs} ({gen.ledger_name(ver)}). */"
        decls.append(note)
        decls.append(f"void {fn}(RsprotExec *x, {msg} *m);")
        body = info["body"] or "    (void)x;\n    (void)m;"
        der = info.get("derived") or []
        dcomment = ""
        if der:
            dcomment = "    /* RSProx derives, after the reads:\n" + "".join(
                f"     *   {d.replace('*/', '* /')}\n" for d in der) + "     */\n"
        bodies.append(f"{note}\nvoid\n{fn}(RsprotExec *x, {msg} *m)\n{{\n{dcomment}{body}\n}}\n")
    aliases = [f"#define packet_{sn}_osrs{r}_out packet_{sn}_v{num[rev_to_ver[r]]}_out"
               for r in sorted(rev_to_ver)]
    rows = []
    for r in sorted(rev_to_ver):
        v = rev_to_ver[r]
        if rows and rows[-1][1] == r - 1 and rows[-1][2] == v:
            rows[-1][1] = r
        else:
            rows.append([r, r, v])
    row_text = "\n".join(f"    {{ {lo}, {hi}, (RsprotCodecFn)packet_{sn}_v{num[v]}_out }},"
                         for lo, hi, v in rows)
    h = H_TEMPLATE.format(tails_include='\n#include "../include/rsprot_tails.h"' if prot.upper() in gen.TAILS else "",
                          guard=sn.upper(), prot=prot, cls=cls, nver=len(versions), nrun=len(rows),
                          msg=msg, fields="\n".join(ftext), decls="\n".join(decls) + "\n",
                          aliases="\n".join(aliases), snake=sn)
    c = C_TEMPLATE.format(prot=prot, snake=sn, rel=rel, bodies="\n".join(bodies), nrun=len(rows),
                          nver=len(versions), revs=gen.fmt_ranges(gen.compress_ranges(rev_to_ver)),
                          rows=row_text)
    with open(os.path.join(out_dir, f"{sn}.h"), "w") as fh:
        fh.write(h)
    with open(os.path.join(out_dir, f"{sn}.c"), "w") as fh:
        fh.write(c)


def table_codec(rev, prot):
    """The RSProt registry name gen/osrs<rev>_prot.h files `prot`'s codec under:
    the row's codec field (223-225, where the tables take RSProx's name for a
    prot RSProt calls X / X_OLD), or None when the row resolves by its name."""
    path = os.path.join(os.path.dirname(PACKETS_DIR), "gen", f"osrs{rev}_prot.h")
    src = open(path).read()
    src = src[src.index(f"rsprot_osrs{rev}_server[]"):]
    src = src[:src.index("};")]
    m = re.search(r'\{ "' + re.escape(prot) + r'", -?\d+, \w+, "(\w+)" \}', src)
    return m.group(1) if m else None


def rsprot_covers(name, rev, out_dir):
    """RSProt's (not this generator's) codec file for `name` has a row for `rev`."""
    sn = gen.prot_to_snake(name)
    c = os.path.join(out_dir, f"{sn}.c")
    if not os.path.exists(c) or is_ours_or_absent(os.path.join(out_dir, f"{sn}.h")):
        return False
    rows = re.findall(r"\{ (\d+), (\d+), \(RsprotCodecFn\)", open(c).read())
    return any(int(lo) <= rev <= int(hi) for lo, hi in rows)


def is_ours_or_absent(path):
    if not os.path.exists(path):
        return True
    with open(path) as fh:
        return MARK in fh.read(400)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--out", default=PACKETS_DIR)
    args = ap.parse_args()

    ledger = overlay.load_overlay_ledger(LEDGER)
    new_rows = []
    by_prot = {}  # prot -> {rev: (path, body)}
    for rev in REVS:
        names = {r["name"] for r in rsprox_prot.load_prots(rev)["server"]}
        decs = rsprox_prot.decoder_files(rev)
        for prot in names:
            path = decs.get(("out", prot))
            if path:
                by_prot.setdefault(prot, {})[rev] = path

    report = []
    for prot in sorted(by_prot):
        sn = gen.prot_to_snake(prot)
        hpath = os.path.join(args.out, f"{sn}.h")
        if prot in SKIP:
            report.append(("SKIP", prot, SKIP[prot]))
            continue
        if prot in RAW:
            report.append(("RAW", prot, "raw payload to a store"))
            continue
        if prot in HAND:
            report.append(("HAND", prot, f"hand-written {sn}.c" if os.path.exists(hpath)
                           else f"HAND but {sn}.c MISSING"))
            continue
        # RSProt may carry this prot under its own spelling: RSPROT_ALIASES, or
        # without the `_V1` RSProx adds once a `_V2` exists. That file is
        # RSProt's, and the overlay's gap fill is what extends it.
        back = {v: k for k, v in rsprox_prot.RSPROT_ALIASES.items()}
        spellings = {back.get(prot, prot), re.sub(r"_V1$", "", prot)} - {prot}
        if not is_ours_or_absent(hpath):
            continue  # RSProt's file (or a hand one); the coverage check says if it falls short
        revs = by_prot[prot]
        if any(not is_ours_or_absent(os.path.join(args.out, gen.prot_to_snake(n) + ".h"))
               for n in spellings):
            # Before 226 the spelling can name a different prot: RSProt's X is
            # RSProx's X_V2, its X_OLD RSProx's X_V1. So there a revision is
            # RSProt's only where the codec the table row names covers it.
            revs = {r: p for r, p in revs.items() if r < 226 and not any(
                rsprot_covers(n, r, args.out) for n in ([table_codec(r, prot)] if table_codec(r, prot)
                                                        else spellings))}
            if not revs:
                continue
        versions, rev_to_ver, fields = {}, {}, []
        fnames = set()
        refused = None
        cls = None
        rel = None
        for rev in sorted(revs):
            path = revs[rev]
            cls = ledger_class(path)
            rel = path.split("/decoder/codec/")[1].replace(f"v{rev}", "v<N>")
            body = overlay.decode_body(path)
            if body is None:
                refused = f"{rev}: no decode body"
                break
            lines, flds, derived = SHAPES.get(prot, translate)(body)
            if lines is None:
                refused = f"{rev}: {flds}"
                break
            for f in flds:
                if f[0] not in fnames:
                    fnames.add(f[0])
                    fields.append(f)
            ctext = "\n".join(lines)
            ver = next((v for v, s in versions.items() if s["body"] == ctext), None)
            if ver is None:
                led = ledger.get((cls, "out", rev))
                if led is not None:
                    ver = led[0]
                    if overlay._ledger_body(ctext) != led[1]:
                        raise SystemExit(f"{cls} rev {rev}: v{ver} is frozen as\n  {led[1]}\n"
                                         f"but RSProx now gives\n  {overlay._ledger_body(ctext)}")
                else:
                    used = list(versions) + [v for (c, d, _r), (v, _b) in ledger.items()
                                             if c == cls and d == "out"]
                    ver = max(used + [VERSION_FLOOR - 1]) + 1
                    ledger[(cls, "out", rev)] = (ver, overlay._ledger_body(ctext))
                    new_rows.append((cls, "out", rev, ver, overlay._ledger_body(ctext)))
                versions[ver] = {"body": ctext, "revs": [], "derived": derived}
            versions[ver]["revs"].append(rev)
            rev_to_ver[rev] = ver
        if refused:
            report.append(("REFUSED", prot, refused))
            continue
        report.append(("OK", prot, f"{len(versions)} layout(s), revs "
                       f"{gen.fmt_ranges(gen.compress_ranges(rev_to_ver))}"))
        if not args.report:
            emit(prot, cls, rel, versions, rev_to_ver, fields, args.out)

    for row in report:
        print(f"{row[0]:<8} {row[1]:<40} {row[2]}")
    if not args.report:
        if new_rows and os.path.realpath(args.out) == os.path.realpath(PACKETS_DIR):
            overlay.append_overlay_ledger(new_rows, LEDGER)
        gen.write_packets_unity(args.out)


if __name__ == "__main__":
    main()
