# Bound for the XTEA key list REBUILD_NORMAL carries at 227-237: the scene is
# 13x13 zones, so at most 4 distinct mapsquares in practice and never more than
# the 169 zones' worth.
XTEA_MAX = 169


def rebuild_shape(body):
    """REBUILD_NORMAL / _V1 (227-237): RSProx's StaticRebuildDecoder.

    The payload is [player-info init block, login variant only] + a header that
    moves every revision + `g2 xteaCount` + xteaCount * 4 * g4. The init block is
    bit-packed and owned by the player-info reader, so the CALLER strips it (it
    is exactly 30 + 2046 * 18 bits = 4608 bytes); the codec covers the rest. The
    header is translated like any flat body; the key list is a fixed shape."""
    if "XteaKey(" not in body or "val xteaCount" not in body:
        return None, "not the StaticRebuild shape", None
    head = [st for st in statements(body.split("val xteaCount")[0])
            if not st.startswith("val playerInfoInitBlock")]
    if any("playerInfoInitBlock" in st or "bitBuf" in st for st in head):
        return None, "init block not in one leading statement", None
    lines, fields, derived = translate("\n".join(head))
    if lines is None:
        return None, fields, None
    m = re.search(r"val xteaCount = buffer\.(g\w+)\(\)", body)
    if not m or m.group(1) != "g2":
        return None, "xtea count is not g2", None
    keys = re.search(r"XteaKey\(\s*(buffer\.g4\(\),\s*){3}buffer\.g4\(\),?\s*\)", body)
    if not keys:
        return None, "xtea key is not four g4", None
    lines += [
        f"    RSPROT_COUNT2(x, m->xtea_count, {XTEA_MAX});",
        "    for (int32_t i = 0; i < m->xtea_count; i++) {",
        "        RSPROT_U4(x, m->keys[i][0]);",
        "        RSPROT_U4(x, m->keys[i][1]);",
        "        RSPROT_U4(x, m->keys[i][2]);",
        "        RSPROT_U4(x, m->keys[i][3]);",
        "    }",
    ]
    fields = fields + [("xtea_count", "int32_t", False, ""),
                       ("keys", "int32_t", False, f"[{XTEA_MAX}][4]")]
    return lines, fields, ["(caller) the login variant's player-info init block precedes this"]


