#!/usr/bin/env python3
"""
Generate 3rd/rsprot/packets/ codecs for the server prots RSProt has no codec for,
straight from RSProx's decoders.

    tools/rsprox_gen_codec.py              # write every packet that generates
    tools/rsprox_gen_codec.py --report     # say what it would do; write nothing

## Where this sits

tools/rsprot_gen_codec.py reads RSProt's ENCODERS and is the source of almost
every file in packets/. tools/rsprox_codec_overlay.py extends those files past
239 by respelling RSProx's decoders through RSProt's field names. Neither can
produce a packet RSProt itself could not express: a field the encoder computes
(`(height << 16) | delay`), a nullable string spelled as the literal "null",
a sealed type written with no discriminator. RSProx, which only has to READ,
has a plain decoder for every one of them, at every revision it supports.

So for a prot with no RSProt-generated file at all, this generator reads the
RSProx decoder of every revision in REVS and writes the file itself:

  * struct fields are RSProx's own variable names, snake-cased -- RSProt has no
    names for these packets, so there is nothing to agree with;
  * one codec per distinct decode body, numbered in gen/rsprox_versions.txt
    (append-only, from 100) under the class `RSProx.<DecoderClass>`;
  * a body is translated only when it is FLAT: a sequence of
    `val/var NAME = <one wire read>` statements, `buffer.skipRead(N)`, and
    statements that read nothing (derived values, which RSProx computes after
    its reads and so can the caller). Anything else -- a loop, a `when`, a read
    inside the return expression -- is REFUSED and named in the report.

A refused packet is written by hand in the same shape (HAND below lists the
files this generator must never overwrite), the way rsprox_codec_overlay.MANUAL
does for the 240/241 bodies the respelling cannot take.

## Signedness

The codec vocabulary has signed primitives only for the unaltered one- and
two-byte reads (I1, I2). A transformed signed read (`g1sAlt1`, `g2sAlt3`) is
carried in the matching unsigned primitive and the field is marked `signed` in
the struct: the bytes are identical, and the consumer sign-extends. That is the
convention RSProt-generated files already follow for `p1Alt1(signedValue)`.
"""

