#!/usr/bin/env python3
"""
Generate a revision's client -> server field layouts from RSProx's decoders.

    tools/rsprox_gen_clientprot.py 241           # writes src/net/rev/osrs241/clientprot.h
    tools/rsprox_gen_clientprot.py 241 --check   # exit 1 if the checked-in file is stale

## Why this exists

At 239 the client's writers (src/net/net_out.c) and the server's readers
(src/torirsserver/mock239_inbound.c) are two hand transcriptions of the same
RSProt decoders. They agree because someone checked them byte for byte, and
RSProt's generated codecs could not take most of them (every op packet reads a
`g1AltN() == 1` control-key boolean, which the codec generator refuses).

Revision 241 reshuffled every one of those packets again. Rather than write a
third and fourth hand transcription, this states each flat client prot ONCE, as
data -- an ordered list of (byte access, field role) read straight off RSProx's
241 decoder -- and both ends run the same table: the client's writers through
osrs241_cp_write(), the server's reader through osrs241_cp_read()
(src/net/rev/osrs241/osrs241_clientprot.c). A packet cannot be written one way
and read another.

Only FLAT decoders are emitted: every wire access a top-level `val`, fixed-width
integers and combined ids, no strings, no loops. That is all of the op, button,
movement-header and resume packets. Anything else is listed in the header's
trailing comment and is written by hand.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import rsprox_codec_overlay as overlay  # noqa: E402
import rsprox_prot  # noqa: E402

ACCESS_RE = re.compile(r"^g([1234])s?(Alt[123])?$|^gCombinedId(Alt[123])?$")


def access_name(fn):
    m = ACCESS_RE.match(fn)
    if not m:
        return None
    if m.group(1):
        return f"G{m.group(1)}" + (f"_ALT{m.group(2)[3]}" if m.group(2) else "")
    return "G4" + (f"_ALT{m.group(3)[3]}" if m.group(3) else "")


def role_name(var):
    var = var.split("#")[0]
    return re.sub(r"(?<!^)(?=[A-Z])", "_", var).upper()


def build(rev):
    decs = rsprox_prot.decoder_files(rev)
    sizes = {r["name"]: r["size"] for r in rsprox_prot.load_prots(rev)["client"]}
    layouts = []
    skipped = []
    for (direction, prot), path in sorted(decs.items()):
        if direction != "in":
            continue
        body = overlay.decode_body(path)
        acc, why = overlay.flat_accesses(body or "")
        if acc is None:
            skipped.append((prot, why))
            continue
        if not acc:
            skipped.append((prot, "no payload"))
            continue
        fields = []
        bad = None
        for var, fn in acc:
            a = access_name(fn)
            if a is None:
                bad = f"non-integer access {fn}"
                break
            fields.append((a, role_name(var), var, fn))
        if bad:
            skipped.append((prot, bad))
            continue
        layouts.append((prot, sizes.get(prot), os.path.relpath(path, rsprox_prot.RSPROX), fields))
    return layouts, skipped


def render(rev, layouts, skipped):
    roles = sorted({f[1] for _p, _s, _r, fs in layouts for f in fs})
    out = []
    g = f"SRC_NET_REV_OSRS{rev}_CLIENTPROT_H"
    out += [
        f"#ifndef {g}",
        f"#define {g}",
        "",
        "/*",
        f" * GENERATED by tools/rsprox_gen_clientprot.py {rev} -- do not edit.",
        f" * Source: RSProx {rsprox_prot.source_hash()}, protocol/osrs-{rev} client decoders.",
        " *",
        f" * Revision {rev}'s flat client -> server packets as data: each layout is the",
        " * decoder's wire accesses in order, with the field each one carries. The",
        " * client writes through osrs" + str(rev) + "_cp_write() and the server reads through",
        " * osrs" + str(rev) + "_cp_read() (osrs" + str(rev) + "_clientprot.c), so both ends run the",
        " * same row.",
        " *",
        " * Access names follow RSProt/RSProx: G2_ALT1 is g2Alt1 (little endian),",
        " * G2_ALT2 big endian with the low byte +128, G2_ALT3 little endian +128;",
        " * G1_ALT1 v+128, G1_ALT2 -v, G1_ALT3 128-v; G4 also carries combined ids.",
        " * Values are the raw unsigned field; a decoder's `g1() == 1` boolean is the",
        " * byte, and its `g2s()` is the 16 bits before sign extension.",
        " */",
        "",
        "#include <stdint.h>",
        "",
        f"enum Osrs{rev}CpAccess",
        "{",
    ]
    accs = [f"G{w}{s}" for w in (1, 2, 3, 4) for s in ("", "_ALT1", "_ALT2", "_ALT3")]
    for a in accs:
        out.append(f"    OSRS{rev}_CP_{a},")
    out += ["};", "", f"enum Osrs{rev}CpRole", "{"]
    for r in roles:
        out.append(f"    OSRS{rev}_CP_{r},")
    out += [f"    OSRS{rev}_CP_ROLE_COUNT", "};", ""]
    maxf = max(len(fs) for _p, _s, _r, fs in layouts)
    out += [
        f"#define OSRS{rev}_CP_MAX_FIELDS {maxf}",
        "",
        f"struct Osrs{rev}CpField",
        "{",
        "    uint8_t access;",
        "    uint8_t role;",
        "};",
        "",
        f"struct Osrs{rev}CpLayout",
        "{",
        "    char const* prot;  /* RSProx's prot name */",
        "    int size;          /* the prot table's size: -1 var-byte, -2 var-short */",
        "    int field_count;",
        f"    struct Osrs{rev}CpField fields[OSRS{rev}_CP_MAX_FIELDS];",
        "};",
        "",
    ]
    for prot, size, rel, fields in layouts:
        out.append(f"/* {rel}")
        out.append(" *   " + ", ".join(f"{fn} {var}" for _a, _r, var, fn in fields))
        out.append(" */")
        out.append(
            f"static const struct Osrs{rev}CpLayout g_osrs{rev}_cp_{prot.lower()} = {{")
        out.append(f'    "{prot}", {size if size is not None else 0}, {len(fields)},')
        out.append("    {")
        for a, r, _var, _fn in fields:
            out.append(f"        {{ OSRS{rev}_CP_{a}, OSRS{rev}_CP_{r} }},")
        out.append("    },")
        out.append("};")
        out.append("")
    out.append("/* Client prots NOT in this table (written by hand, see net_out.c):")
    for prot, why in skipped:
        out.append(f" *   {prot:<40} {why}")
    out += [" */", "", "#endif", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rev", type=int)
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    path = args.out or os.path.join(REPO_ROOT, "src", "net", "rev", f"osrs{args.rev}", "clientprot.h")
    layouts, skipped = build(args.rev)
    text = render(args.rev, layouts, skipped)
    if args.check:
        cur = open(path).read() if os.path.exists(path) else ""
        if cur != text:
            print(f"{path} is stale -- rerun tools/rsprox_gen_clientprot.py {args.rev}")
            return 1
        print(f"{path}: up to date ({len(layouts)} layouts)")
        return 0
    with open(path, "w") as fh:
        fh.write(text)
    print(f"wrote {path}: {len(layouts)} layouts, {len(skipped)} by hand", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
