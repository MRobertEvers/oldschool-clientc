#!/usr/bin/env python3
"""Generate the per-code layer of the fairy ring network.

Reads the cache, writes
    OSRS-Content/osrs-content/server/scripts/general/scripts/misc/fairy_rings_codes.rs2

    python3 tools/gen_fairy_rings.py [--check]

Every code-indexed fact comes from the cache, never from a list written here:

  * configs/all.dbrow, table `fairyring`: one row per code 0..63 in code order
    (`multiloc_state`), its `code` ("A I R") and `text_component`
    (fairyrings_log:air). The destination and description are read at run time
    with db_getfield, so they are not copied.
  * interfaces/fairyrings_log.if: the log's rows (op1 "Use code", op2 "Add
    Favourite"), their star (`<code>_fave`, op1 "Add Favourite"), the hideout
    row and fave_1..10 (op1 "Use code", op2 "Remove Favourite").
  * configs/all.varbit: the travel-log flag of each code
    (`varbN_fairyrings_log_<code>`); a code without one is never logged.

The log's text order is Jagex's (RSProx index 4653 [38], [297]; 4654 [1620]):
the order of LOG_ORDER below, then the hideout row, then the favourites.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT = os.path.join(ROOT, "OSRS-Content", "osrs-content")
OUT = os.path.join(CONTENT, "server", "scripts", "general", "scripts", "misc",
                   "fairy_rings_codes.rs2")

# The order Jagex sends the log's rows in (4653 [38]: 55 rows; the codes with
# no destination are never sent).
LOG_ORDER = ("aiq air ajq ajr ajs akq ajp aks akr alp alq akp alr als ais bip biq "
             "bis bjp bjr bjs bkp bkq bkr bks blp blr bls blq cip ciq cir cis cjr "
             "cjq ckp ckq ckr cks clp clr cls dip diq dlp dir dis djp djr dkp dkr "
             "dks dlq dlr dls").split()

FIRST = "adcb"
SECOND = "ilkj"
THIRD = "psrq"


def code_name(code):
    return FIRST[code // 16] + SECOND[(code // 4) % 4] + THIRD[code % 4]


def read_rows():
    rows = {}
    cur = None
    path = os.path.join(CONTENT, "configs", "all.dbrow")
    for line in open(path, encoding="latin-1"):
        line = line.rstrip("\n")
        if line.startswith("["):
            cur = {"name": line[1:-1], "data": {}}
            continue
        if cur is None or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if key == "table":
            cur["table"] = value
            if value == "fairyring":
                rows[cur["name"]] = cur
        elif key == "data":
            parts = value.split(",", 1)
            cur["data"][parts[0]] = parts[1] if len(parts) > 1 else ""
    by_code = {}
    for row in rows.values():
        code = int(row["data"]["multiloc_state"])
        by_code[code] = row
    assert sorted(by_code) == list(range(64)), "fairyring rows are not codes 0..63"
    for code, row in by_code.items():
        assert row["data"]["code"].replace(" ", "").lower() == code_name(code), (code, row["data"]["code"])
        assert row["data"]["text_component"] == "fairyrings_log:" + code_name(code)
    return by_code


def read_components():
    path = os.path.join(CONTENT, "interfaces", "fairyrings_log.if")
    comps = {}
    cur = None
    for line in open(path, encoding="latin-1"):
        line = line.strip()
        m = re.match(r"^\[(.+)\]$", line)
        if m:
            cur = m.group(1)
            comps[cur] = {}
            continue
        m = re.match(r"^op(\d)=(.*)$", line)
        if m and cur:
            comps[cur][int(m.group(1))] = m.group(2)
    return comps


def read_log_varbits():
    path = os.path.join(CONTENT, "configs", "all.varbit")
    found = {}
    for line in open(path, encoding="latin-1"):
        m = re.match(r"^\[(varb\d+_fairyrings_log_([a-z]{3}))\]$", line.strip())
        if m:
            found[m.group(2)] = m.group(1)
    return found


def generate():
    rows = read_rows()
    comps = read_components()
    varbits = read_log_varbits()
    names = [code_name(c) for c in range(64)]
    for n in names:
        assert comps.get(n, {}).get(1) == "Use code", n
        assert comps.get(n, {}).get(2) == "Add Favourite", n
        assert comps.get(n + "_fave", {}).get(1) == "Add Favourite", n
    for i in range(1, 11):
        assert comps["fave_%d" % i].get(1) == "Use code"
        assert comps["fave_%d" % i].get(2) == "Remove Favourite"
    assert comps["hideout"].get(1) == "Use code"
    for n in LOG_ORDER:
        assert n in names

    out = []
    w = out.append
    w("// GENERATED by tools/gen_fairy_rings.py from the cache's `fairyring` dbtable,")
    w("// interfaces/fairyrings_log.if and configs/all.varbit. Do not edit; rerun it.")
    w("// The network itself is fairy_rings.rs2.")
    w("")
    w("// The travel-log flag of a code (0 for a code the log has no row flag for).")
    w("[proc,fairy_ring_logged](int $code)(boolean)")
    w("switch_int ($code) {")
    for c in range(64):
        n = names[c]
        if n in varbits:
            w("    case %d : if (%%%s = 1) return(true); // %s" % (c, varbits[n], n.upper()))
    w("}")
    w("return(false);")
    w("")
    w("[proc,fairy_ring_log](int $code)")
    w("switch_int ($code) {")
    for c in range(64):
        n = names[c]
        if n in varbits:
            w("    case %d : %%%s = 1; // %s" % (c, varbits[n], n.upper()))
    w("}")
    w("")
    w("// The log's rows in Jagex's order: a logged code shows its table description,")
    w("// every other row is sent empty (4654 [1620]: 75 rows, all empty).")
    w("[proc,fairy_ring_log_rows]")
    for n in LOG_ORDER:
        c = names.index(n)
        w("~fairy_ring_log_row(%d, fairyrings_log:%s);" % (c, n))
    w("")
    w("// The log's buttons. A row's op1 \"Use code\" turns the dial to it, op2 and its")
    w("// star \"Add Favourite\".")
    for c in range(64):
        n = names[c]
        w("[if_button1,fairyrings_log:%s] ~fairy_ring_use_code(%d);" % (n, c))
        w("[if_button2,fairyrings_log:%s] ~fairy_ring_favourite_add(%d);" % (n, c))
        w("[if_button1,fairyrings_log:%s_fave] ~fairy_ring_favourite_add(%d);" % (n, c))
    w("")
    w("[if_button1,fairyrings_log:hideout] ~fairy_ring_use_code(~fairy_ring_hideout_next);")
    for i in range(1, 11):
        w("[if_button1,fairyrings_log:fave_%d] ~fairy_ring_favourite_use_code(%d);" % (i, i))
        w("[if_button2,fairyrings_log:fave_%d] ~fairy_ring_favourite_remove(%d);" % (i, i))
    w("")
    w("[proc,fairy_ring_favourite_rows]")
    for i in range(1, 11):
        w("~fairy_ring_favourite_row(%d, fairyrings_log:fave_%d, fairyrings_log:fave_code_%d);" % (i, i, i))
    w("")
    return "\n".join(out)


def main():
    text = generate()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("fairy_rings_codes.rs2 is stale: rerun tools/gen_fairy_rings.py")
            return 1
        print("fairy_rings_codes.rs2 up to date")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
