/*
 * NPC_INFO's typed customisation blocks (BodyCustomisationV1/V2 and the head
 * ones): their recolour and retexture lists carry no count, the npc TYPE's
 * lists decide it (deob Statics ~47320: field1237.field5139 / field5158
 * .length), so the reader asks the host (RsprotNpcTypeLengths).
 *
 * The two frames below are real wire bytes: NPC_INFO_LARGE packets from
 * RSProx recordings, rev 226 (rsprox.net 1703, frame 110105, tick 7205: four
 * Abyssal axons, type 12375, three recolours each) and rev 234 (rsprox.net
 * 3285, frame 289111, tick 21465: ten Lost Souls, type 12212, four each). The
 * expected colours are RSProx's own transcript of the same packets, which
 * read the lengths off the cache. Without the type answer those frames ended
 * at their first typed block and every npc record after it went unread (29
 * records in 1703, 66 in 3285 and 38 in 3299 over the whole recordings).
 */
