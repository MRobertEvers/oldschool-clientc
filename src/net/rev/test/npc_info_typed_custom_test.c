static RsprotInfoOp g_ops[4096];
static uint8_t g_bytes[1 << 16];

/* The two types the real frames name, as the cache has them; and for the
 * hand-built rev 222 packet, the kept npc's type (5) and the one its record
 * turns it into (900, 2). */
static int g_asked_old;
static int g_asked_type;

static int
lengths(
    void* ctx,
    int old,
    int npc_type,
    int head,
    int* recolours,
    int* retextures)
{
    (void)ctx;
    (void)head;
    g_asked_old = old;
    g_asked_type = npc_type;
    *retextures = 0;
    if( npc_type == 12375 )
        *recolours = 3;
    else if( npc_type == 12212 )
        *recolours = 4;
    else if( npc_type == 900 )
        *recolours = 2;
    else if( npc_type < 0 && old == 0 )
        *recolours = 5;
    else
        return 0;
    return 1;
}

static void
check_frame(
    char const* name,
    RsprotNpcInfoReadFn read,
    uint8_t const* frame,
    int len,
    struct TypedBlock const* blocks,
    int block_count)
{
    RsprotInfoList list;
    int n;
    int position = -1;
    int seen = 0;
    int wrong = 0;

    printf("%s: a real NPC_INFO_LARGE with typed recolours\n", name);
    rsprot_info_list_init(&list, g_ops, 4096, g_bytes, (int)sizeof(g_bytes));
    n = proto_info_npc_read(read, frame, len, lengths, NULL, &list);
    CHECK(rsprot_info_list_complete(&list), "the whole packet is read, to its last byte");
    for( int i = 0; i < n; i++ )
    {
        RsprotInfoOp const* op = &g_ops[i];

        if( op->kind == RSPROT_OP_SET_EXT )
            position = (int)op->value;
        if( op->kind != RSPROT_OP_BODY_CUSTOM || op->body.recolour_count == 0 )
            continue;
        if( seen >= block_count || blocks[seen].position != position ||
            blocks[seen].count != op->body.recolour_count )
            wrong++;
        else
            for( int k = 0; k < op->body.recolour_count; k++ )
                wrong += op->body.recolours[k] != blocks[seen].recolours[k];
        seen++;
    }
    CHECK(seen == block_count, "every typed block the transcript shows is read");
    CHECK(wrong == 0, "each at its npc, with the transcript's colours");
}

/* Rev 222 reads TRANSFORMATION before BODY_CUSTOMISATION: the body block of a
 * record that retyped its npc reads the NEW type's counts. A kept npc (list
 * position 0, old index 0, type with five) turns into type 900 (two). */
static void
check_retype_first(void)
{
    static uint8_t packet[32];
    RsprotInfoList list;
    RsprotBuf b;
    int n;
    int found = 0;

    printf("osrs222: a record that retypes its npc reads the new type's counts\n");
    rsprot_buf_wrap(&b, packet, (int)sizeof(packet));
    rsprot_p1(&b, 0x01); /* one npc in view */
    rsprot_p1(&b, 0x9F); /* kept, stood still with extended info; 0xFFFF... */
    rsprot_p1(&b, 0xFF);
    rsprot_p1(&b, 0xE0); /* ...the terminator, then the pad */
    rsprot_p1(&b, 0x08 | 0x01); /* TRANSFORMATION, and a second byte */
    rsprot_p1(&b, 0x02);        /* BODY_CUSTOMISATION (0x200) */
    rsprot_p2_21_add128(&b, 900);
    rsprot_p1(&b, 0x4);
    rsprot_p2_12_add128(&b, 7001);
    rsprot_p2_12_add128(&b, 7002);
    rsprot_info_list_init(&list, g_ops, 4096, g_bytes, (int)sizeof(g_bytes));
    g_asked_old = -2;
    g_asked_type = -2;
    n = proto_info_npc_read(npc_info_small_v4_osrs222, packet, b.wpos, lengths, NULL, &list);
    CHECK(rsprot_info_list_complete(&list), "the packet is read whole");
    CHECK(g_asked_old == -1 && g_asked_type == 900, "the question names the type the record turned it into");
    for( int i = 0; i < n; i++ )
        if( g_ops[i].kind == RSPROT_OP_BODY_CUSTOM && g_ops[i].body.recolour_count == 2 &&
            g_ops[i].body.recolours[0] == 7001 && g_ops[i].body.recolours[1] == 7002 )
            found = 1;
    CHECK(found, "and the block carries that type's two colours");

    /* The kept npc's own type, without the retype: asked by its old index. */
    rsprot_buf_wrap(&b, packet, (int)sizeof(packet));
    rsprot_p1(&b, 0x01);
    rsprot_p1(&b, 0x9F);
    rsprot_p1(&b, 0xFF);
    rsprot_p1(&b, 0xE0);
    rsprot_p1(&b, 0x01);
    rsprot_p1(&b, 0x02);
    rsprot_p1(&b, 0x4);
    for( int i = 0; i < 5; i++ )
        rsprot_p2_12_add128(&b, 8000 + i);
    rsprot_info_list_init(&list, g_ops, 4096, g_bytes, (int)sizeof(g_bytes));
    n = proto_info_npc_read(npc_info_small_v4_osrs222, packet, b.wpos, lengths, NULL, &list);
    CHECK(rsprot_info_list_complete(&list), "a kept npc's block reads whole");
    CHECK(g_asked_old == 0 && g_asked_type == -1, "asked by the npc's index in the host's list");
    found = 0;
    for( int i = 0; i < n; i++ )
        if( g_ops[i].kind == RSPROT_OP_BODY_CUSTOM && g_ops[i].body.recolour_count == 5 &&
            g_ops[i].body.recolours[4] == 8004 )
            found = 1;
    CHECK(found, "with its type's five colours");

    /* An answer the payload cannot hold ends the read at the block, before
     * any colour is taken from past the end. */
    rsprot_buf_wrap(&b, packet, (int)sizeof(packet));
    rsprot_p1(&b, 0x01);
    rsprot_p1(&b, 0x9F);
    rsprot_p1(&b, 0xFF);
    rsprot_p1(&b, 0xE0);
    rsprot_p1(&b, 0x01);
    rsprot_p1(&b, 0x02);
    rsprot_p1(&b, 0x4);
    rsprot_p2_12_add128(&b, 8000); /* one of the five */
    rsprot_info_list_init(&list, g_ops, 4096, g_bytes, (int)sizeof(g_bytes));
    n = proto_info_npc_read(npc_info_small_v4_osrs222, packet, b.wpos, lengths, NULL, &list);
    CHECK(list.stopped && n > 0 && g_ops[n - 1].kind == RSPROT_OP_STOP &&
              g_ops[n - 1].stop.kind == RSPROT_IK_CUSTOM_TYPED,
        "a count longer than the payload left stops the read at its block");
}

int
main(void)
{
    check_frame("osrs226", npc_info_large_v5_osrs226, k_osrs226_frame, (int)sizeof(k_osrs226_frame),
        k_osrs226_frame_blocks, (int)(sizeof(k_osrs226_frame_blocks) / sizeof(k_osrs226_frame_blocks[0])));
    check_frame("osrs234", npc_info_large_v5_osrs234, k_osrs234_frame, (int)sizeof(k_osrs234_frame),
        k_osrs234_frame_blocks, (int)(sizeof(k_osrs234_frame_blocks) / sizeof(k_osrs234_frame_blocks[0])));
    check_retype_first();
    if( g_failures )
    {
        printf("npc_info_typed_custom: %d failures\n", g_failures);
        return 1;
    }
    printf("npc_info_typed_custom: all passed\n");
    return 0;
}
