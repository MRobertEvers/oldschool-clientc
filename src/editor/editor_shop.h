#ifndef SRC_EDITOR_EDITOR_SHOP_H
#define SRC_EDITOR_EDITOR_SHOP_H

/**
 * A SHOP (workbench 6.7, design section 11 "Shop builder"): one npc-opened
 * coin shop as the tree already writes it -- one `.rs2` and one `.inv`, in
 * exactly the shape tools/gen_shop_scripts.py emits (docs/SHOPS_PLAN.md
 * section 4). No new format: the pair IS the model, and the parser reads
 * back what the emitter writes (and refuses everything else, so a
 * hand-damaged file is reported rather than half-read).
 *
 *   rs2   <mark>
 *         // <shop name>
 *         // https://oldschool.runescape.wiki/w/<page_title>     } a wiki shop
 *         // Wiki revision <revid>, scraped <fetch_date>.        }
 *         // Authored in ToriRSEd (the Shop panel); no wiki revision.  (else)
 *         // Owner: <npc>, <npc>. [Members. ]<special>.
 *         // <npc> already had an [opnpc3] trade stub -- ...      (or blank)
 *         (blank)
 *         [opnpc<op>,<npc>] @<key>_open;                         (each declared owner)
 *         (blank)
 *         [label,<key>_open]
 *         ~openshop(<inv>, <buy>, <sell>, <delta>, "<title>");
 *
 *   inv   <mark>, the same citation lines, then
 *         [<inv>]  scope=shared  restock=yes  stackall=yes  [allstock=yes]
 *         stock<N>=<obj>,<count>,<rate>
 *
 * The three multipliers are passed inline to ~openshop, as the generator
 * does (SHOPS_PLAN 4.1: "Multipliers and title are passed inline to
 * ~openshop rather than through npc params"): `sell` is what the player
 * pays, `buy` what the shop pays, both per mille of the obj's cost; `delta`
 * the per-mille move per unit away from baseline stock.
 *
 * WHERE THE EDITOR WRITES. Its own directory, never the generator's:
 *
 *   server/scripts/shop/edited/<key>/scripts/<key>.rs2
 *   server/scripts/shop/edited/<key>/configs/<key>.inv
 *
 * TEXT documents "rs2:shop/edited/<key>/..." edited through the authority,
 * opening with EDITOR_SHOP_MARK. A pair the generator wrote (its own mark,
 * under shop/<area>/) parses the same, but is generated output and is never
 * saved over (Editor_ShopSaveRefusal).
 *
 * PRICES: LostCity's [proc,calc_shop_value], SHOPS_PLAN section 2:
 *
 *   value = scale(max(100, multiplier - clamp(-5000, 1000, (stock - base) * delta)),
 *                 1000, oc_cost(obj))
 *
 * scale(a, b, c) is c * a / b, truncated; a floor of 1 on what the shop
 * SELLS for (it never sells for 0) and none on what it buys for (a general
 * store paying 0 for a pot is correct).
 *
 * Pure: no document, no host, no catalog. NULL arguments assert.
 */

#include <stddef.h>

/** Bytes of a shop key, the terminator included: [a-z0-9_], spelled twice in
 *  each document key ("rs2:shop/edited/<k>/scripts/<k>.rs2" fits 128). */
#define EDITOR_SHOP_KEY_MAX 48
/** An npc, obj or inv name (a gameval). */
#define EDITOR_SHOP_NAME_MAX 96
#define EDITOR_SHOP_TEXT_MAX 160
#define EDITOR_SHOP_OWNERS_MAX 8
/** The largest cache shop inv is 40 slots; aprilfoolshorseshop's wiki table
 *  is 227 lines and is refused by the generator for overflowing its 31. */
#define EDITOR_SHOP_STOCK_MAX 64
#define EDITOR_SHOP_ISSUES_MAX 32

/** Relative to server/scripts: the directory the shop builder owns. */
#define EDITOR_SHOP_DIR "shop/edited"

/** The first line of every file the shop builder writes. */
#define EDITOR_SHOP_MARK                                                                           \
    "// Generated by the ToriRSEd shop builder (src/editor/editor_shop.c) \xe2\x80\x94 see "       \
    "docs/SHOPS_PLAN.md \xc2\xa7"                                                                  \
    "4."
/** tools/gen_shop_scripts.py's GENERATED_MARK, byte for byte. */
#define EDITOR_SHOP_GENERATOR_MARK                                                                 \
    "// Generated by tools/gen_shop_scripts.py \xe2\x80\x94 see docs/SHOPS_PLAN.md \xc2\xa7"       \
    "4."
/** The citation line of a shop authored here (no wiki page). */
#define EDITOR_SHOP_AUTHORED_LINE "// Authored in ToriRSEd (the Shop panel); no wiki revision."

/** The wiki stock catalogue (tools/gen_shop_catalog.py), relative to the
 *  content dir: what "From wiki catalogue..." reads. */
#define EDITOR_SHOP_WIKI_STOCK "wiki/shop_stock.csv"

/** Who wrote a parsed pair. */
enum Editor_ShopOrigin
{
    /** EDITOR_SHOP_MARK: the shop builder's own; it may save over it. */
    EDITOR_SHOP_ORIGIN_EDITOR = 0,
    /** EDITOR_SHOP_GENERATOR_MARK: tools/gen_shop_scripts.py's output. */
    EDITOR_SHOP_ORIGIN_GENERATOR,
};

struct Editor_ShopStock
{
    char obj[EDITOR_SHOP_NAME_MAX];
    /** Baseline stock, and the starting count. */
    int count;
    /** Ticks between +-1 nudges toward baseline. */
    int rate;
};

struct Editor_ShopOwner
{
    char npc[EDITOR_SHOP_NAME_MAX];
    /** 1: this file declares its `[opnpc<op>,<npc>]`. 0: the generator
     *  rewrote an existing "nothing to trade" stub elsewhere to call the
     *  open label (the patched note names it). The editor declares all. */
    int declared;
};

struct Editor_Shop
{
    char key[EDITOR_SHOP_KEY_MAX];
    /** The shop's name: the citation's first line and ~openshop's title
     *  (with '"' written as '\''). */
    char name[EDITOR_SHOP_TEXT_MAX];
    /** The wiki citation of a generated shop; page_title "" for one
     *  authored here. */
    char page_title[EDITOR_SHOP_TEXT_MAX];
    char revid[24];
    char fetch_date[24];
    int members;
    /** The wiki's `special=` ("General store", "Weapon shop", ...) or "". A
     *  general store accepts every tradeable obj (`allstock=yes`). */
    char special[48];
    struct Editor_ShopOwner owners[EDITOR_SHOP_OWNERS_MAX];
    int owner_count;
    /** The npc op that opens it, 1..5; 3 (Trade) by default. */
    int op;
    /** The cache inv that backs it (SHOPS_PLAN 2.3: reuse the cache's). */
    char inv[EDITOR_SHOP_NAME_MAX];
    /** Per mille: what the player pays, what the shop pays, the move per
     *  unit away from baseline. */
    int sell;
    int buy;
    int delta;
    struct Editor_ShopStock stock[EDITOR_SHOP_STOCK_MAX];
    int stock_count;
    /** Set by the parser. */
    enum Editor_ShopOrigin origin;
};

/* ---- names and keys ---------------------------------------------------- */

/** 1..47 bytes of [a-z0-9_]. */
int
Editor_ShopKeyValid(const char* key);

/** A gameval as the triggers and the .inv spell it: 1..95 bytes of
 *  [A-Za-z0-9_]. */
int
Editor_ShopNameValid(const char* name);

/** The two TEXT document keys of shop `key` (which must be valid):
 *  "rs2:shop/edited/<key>/scripts/<key>.rs2" and ".../configs/<key>.inv". */
void
Editor_ShopDocKeys(
    const char* key,
    char* out_rs2,
    size_t rs2_size,
    char* out_inv,
    size_t inv_size);

/* ---- the model ---------------------------------------------------------- */

/** A new shop authored here: `key`, op 3, the general-store multipliers
 *  SHOPS_PLAN section 2 quotes (sell 1300, buy 400, delta 30), no owner, no
 *  stock, the inv named after the key. */
void
Editor_ShopInit(
    struct Editor_Shop* shop,
    const char* key);

/** `special` reads "general store" (any case): `allstock=yes`. */
int
Editor_ShopIsGeneral(const struct Editor_Shop* shop);

/** Append an owner (declared). 0 when full or already there. */
int
Editor_ShopOwnerAdd(
    struct Editor_Shop* shop,
    const char* npc);

/** Append a stock row. Returns its index, -1 when full. */
int
Editor_ShopStockAdd(
    struct Editor_Shop* shop,
    const char* obj,
    int count,
    int rate);

/** Remove stock row `index` (in range); the later rows move up. */
void
Editor_ShopStockRemove(
    struct Editor_Shop* shop,
    int index);

/* ---- prices ------------------------------------------------------------- */

/** calc_shop_value: `multiplier` per mille, `haggle` the per-mille delta,
 *  `stock` against baseline `base`, `cost` the obj's oc_cost. */
int
Editor_ShopValue(
    int multiplier,
    int haggle,
    int stock,
    int base,
    int cost);

/** What the shop sells row `index` for at its baseline stock (at least 1). */
int
Editor_ShopSellsAt(
    const struct Editor_Shop* shop,
    int index,
    int cost);

/** What the shop pays for row `index` at its baseline stock (may be 0). */
int
Editor_ShopBuysAt(
    const struct Editor_Shop* shop,
    int index,
    int cost);

/* ---- the files ---------------------------------------------------------- */

/** The `.rs2`, its first line `mark` (EDITOR_SHOP_MARK, or the generator's
 *  for a byte comparison). snprintf's contract; returns the length. */
size_t
Editor_ShopEmitRs2(
    const struct Editor_Shop* shop,
    const char* mark,
    char* out,
    size_t out_capacity);

/** The `.inv`, its first line `mark`. snprintf's contract. */
size_t
Editor_ShopEmitInv(
    const struct Editor_Shop* shop,
    const char* mark,
    char* out,
    size_t out_capacity);

/**
 * Read a pair the emitter (or tools/gen_shop_scripts.py) wrote into `shop`,
 * its key from the open label. Returns 1, or 0 with a sentence in `why`
 * ("line 7: not a [opnpc<N>,<npc>] @<key>_open; trigger") -- text that is
 * data, not a contract violation.
 */
int
Editor_ShopParse(
    struct Editor_Shop* shop,
    const char* rs2,
    size_t rs2_length,
    const char* inv,
    size_t inv_length,
    char* why,
    size_t why_size);

/** Why Save must not write this shop, or NULL: a generated pair is
 *  tools/gen_shop_scripts.py's output and is regenerated, never edited. */
const char*
Editor_ShopSaveRefusal(const struct Editor_Shop* shop);

/* ---- checking ----------------------------------------------------------- */

/**
 * What the model alone can say is wrong, one sentence each, into `out` (at
 * most `max`): the key, the owners, the op, the inv, the multipliers, each
 * stock row (an obj name, count >= 1, rate >= 1, no obj twice), an empty
 * stock. Returns the count; 0 is a shop that may be saved. What needs the
 * catalog (the owner and objs exist, the inv is the cache's and big enough,
 * no other op trigger) is the panel's (edpanel_shop.c).
 */
int
Editor_ShopCheck(
    const struct Editor_Shop* shop,
    char (*out)[EDITOR_SHOP_TEXT_MAX],
    int max);

/* ---- the wiki catalogue ------------------------------------------------- */

/**
 * The stock rows of `key` in wiki/shop_stock.csv's text (a header row naming
 * shop_key, obj_gameval, stock, restock and optionally review; RFC 4180
 * quoting), in file order, into `out` (at most `max`). A row with no
 * obj_gameval or a non-empty review is skipped and counted in *out_skipped
 * (the generator never writes one either). Returns the count, or -1 when
 * the text has no such header.
 */
int
Editor_ShopWikiStock(
    const char* csv,
    size_t length,
    const char* key,
    struct Editor_ShopStock* out,
    int max,
    int* out_skipped);

#endif
