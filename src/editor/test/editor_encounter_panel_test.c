/* ---- driving the panel -------------------------------------------------------------- */

static void
frame(void)
{
    Editor_PumpFacts(&g_editor);
    ToriRSChrome_Build(&g_chrome);
    Editor_UiTick(&g_ui);
    ToriRSChrome_Build(&g_chrome);
}

static void
activate(int widget)
{
    assert(widget >= 0);
    g_chrome.activated = widget;
    frame();
}

static const char*
vrow(
    int widget,
    int row)
{
    for( int i = 0; i < TORIRS_CHROME_VROW_POOL; i++ )
        if( g_chrome.vrows[i].owner == widget && g_chrome.vrows[i].index == row )
            return g_chrome.vrows[i].text;
    return "";
}

static const char*
text(int widget)
{
    const char* t = ToriRSChrome_Text(&g_chrome, widget);
    return t ? t : "";
}

static const char*
doc_text(
    enum Editor_DocKind kind,
    const char* key)
{
    struct Editor_DocHandle handle;
    if( !Editor_DocFind(&g_editor.doc, kind, key, &handle) || !handle.text || !handle.text->text )
        return "";
    return handle.text->text;
}

static void
tab(int index)
{
    ToriRSChrome_PanelSetActiveTab(&g_chrome, g_w.panel, index);
    frame();
    frame();
}

