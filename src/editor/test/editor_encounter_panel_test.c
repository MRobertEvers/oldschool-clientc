static void
test_set(const char* root)
{
    struct Editor_EncounterRing rings[16];
    char* on_disk;
    int n;

    CHECK(!g_chrome.panels[g_w.panel].visible, "the panel starts closed");
    CHECK(Editor_UiTogglePanel(&g_ui, "encounter") == 1, "View > Encounters opens the panel");
    frame();
    frame();
    CHECK(strcmp(text(g_w.row_title), "Encounter camp | 3 spawns | 2 records") == 0, "the title: %s",
        text(g_w.row_title));
    CHECK(g_chrome.widgets[g_w.list_spawns].imax == 3, "three rows (%d)", g_chrome.widgets[g_w.list_spawns].imax);
    CHECK(strcmp(vrow(g_w.list_spawns, 0), "goblin  3205,3205 L0  (1 of 2)") == 0, "row 0: %s",
        vrow(g_w.list_spawns, 0));
    CHECK(strcmp(vrow(g_w.list_spawns, 2), "guard  3206,3208 L0") == 0, "row 2: %s", vrow(g_w.list_spawns, 2));

    /* The selected row's npc. */
    ToriRSChrome_VListSetSelected(&g_chrome, g_w.list_spawns, 0);
    activate(g_w.list_spawns);
    frame();
    CHECK(strncmp(text(g_w.row_selected), "Selected goblin | 2 spawns | 3 layers", 37) == 0, "the npc row: %s",
        text(g_w.row_selected));
    CHECK(strcmp(text(g_w.input_fields[0]), "35") == 0, "respawnrate from the authored overlay (%s)",
        text(g_w.input_fields[0]));
    CHECK(strcmp(text(g_w.input_fields[1]), "3") == 0, "wanderrange (%s)", text(g_w.input_fields[1]));
    CHECK(strcmp(text(g_w.input_fields[2]), "") == 0, "maxrange stated nowhere (%s)", text(g_w.input_fields[2]));
    CHECK(strcmp(text(g_w.input_fields[3]), "4") == 0, "param huntrange (%s)", text(g_w.input_fields[3]));
    CHECK(strcmp(text(g_w.input_fields[4]), "4") == 0, "param attackrate from the generated layer (%s)",
        text(g_w.input_fields[4]));
    CHECK(strcmp(text(g_w.row_rings), "rings: hunt 4 | wander 3 | leash 7") == 0, "the rings row: %s",
        text(g_w.row_rings));

    /* The rings: wander and hunt about each goblin, in the set's colour. */
    n = Editor_Encounter_Rings(&g_ui, rings, 16);
    CHECK(n == 4, "two rings per goblin, none for the guard not looked at (%d)", n);
    CHECK(n >= 2 && rings[0].hunt == 0 && rings[0].x0 == 3202 && rings[0].x1 == 3208 && rings[0].z0 == 3202
              && rings[1].hunt == 1 && rings[1].x0 == 3201 && rings[1].z1 == 3209 && rings[0].current,
        "a wander ring of 3 and a hunt ring of 4 about 3205,3205");
    CHECK(n >= 1 && rings[0].rgb == 0xFFE040u, "colour 2 (%06x)", n >= 1 ? rings[0].rgb : 0);

    /* Apply fields: two edits in the authored overlay, an override of a
     * generated-only param there, one undo step, the generated file kept. */
    ToriRSChrome_SetText(&g_chrome, g_w.input_fields[0], "50");
    ToriRSChrome_SetText(&g_chrome, g_w.input_fields[3], "6");
    ToriRSChrome_SetText(&g_chrome, g_w.input_fields[4], "5");
    ToriRSChrome_DropdownSetSelected(&g_chrome, g_w.dropdown_huntmode, 1);
    activate(g_w.button_apply_fields);
    {
        const char* authored = doc_text(EDITOR_DOC_CFG, AUTHORED_KEY);
        CHECK(strstr(authored, "respawnrate=50\n") && strstr(authored, "param=huntrange,6\n")
                  && strstr(authored, "param=attackrate,5") && strstr(authored, "huntmode=aggressive"),
            "the authored overlay takes all four:\n%s", authored);
        CHECK(strstr(doc_text(EDITOR_DOC_CFG, GENERATED_KEY), "param=attackrate,4") != NULL,
            "the generated layer is not written");
    }
    CHECK(strstr(Editor_UiStatusText(&g_ui), "goblin: 4 fields set") != NULL, "the status: %s",
        Editor_UiStatusText(&g_ui));
    frame();
    CHECK(strcmp(text(g_w.row_rings), "rings: hunt 6 | wander 3 | leash 7") == 0, "the rings follow: %s",
        text(g_w.row_rings));
    Editor_Undo(&g_editor);
    frame();
    CHECK(strcmp(doc_text(EDITOR_DOC_CFG, AUTHORED_KEY), "[goblin]\nrespawnrate=35\nwanderrange=3\nparam=huntrange,4\n")
                  == 0
              || strstr(doc_text(EDITOR_DOC_CFG, AUTHORED_KEY), "respawnrate=35\nwanderrange=3\nparam=huntrange,4\n"),
        "one undo takes all four back:\n%s", doc_text(EDITOR_DOC_CFG, AUTHORED_KEY));
    CHECK(strcmp(text(g_w.input_fields[0]), "35") == 0, "and the inputs follow (%s)", text(g_w.input_fields[0]));

    /* A generated-only npc: refused with a sentence. */
    ToriRSChrome_VListSetSelected(&g_chrome, g_w.list_spawns, 2);
    activate(g_w.list_spawns);
    frame();
    CHECK(strcmp(text(g_w.input_fields[0]), "30") == 0, "guard's respawnrate from the generated layer (%s)",
        text(g_w.input_fields[0]));
    ToriRSChrome_SetText(&g_chrome, g_w.input_fields[0], "40");
    activate(g_w.button_apply_fields);
    CHECK(strstr(Editor_UiStatusText(&g_ui), "Apply fields refused: guard's respawnrate is stated only in a generated")
              != NULL,
        "refused, saying why: %s", Editor_UiStatusText(&g_ui));
    on_disk = read_text(root, GENERATED_PATH);
    CHECK(on_disk && strcmp(on_disk, k_generated) == 0, "the generated file is as it was");
    free(on_disk);

    /* Add at latched tile: a SPAWN and the set's line, one step. */
    g_ui.tools.tile_valid = 1;
    g_ui.tools.tile_x = 3210;
    g_ui.tools.tile_z = 3211;
    g_ui.tools.tile_level = 0;
    ToriRSChrome_SetText(&g_chrome, g_w.input_spawn, "guard");
    activate(g_w.button_add_name);
    frame();
    CHECK(strstr(doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY), "| spawn npc:guard 3210 3211 0 |") != NULL,
        "the set lists the new spawn:\n%s", doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY));
    CHECK(g_chrome.widgets[g_w.list_spawns].imax == 4, "four rows (%d)", g_chrome.widgets[g_w.list_spawns].imax);
    {
        struct Editor_DocHandle handle;
        int found = 0;
        char key[EDITOR_DOC_KEY_MAX];
        Editor_SpawnDocKeyAt(key, 3210, 3211);
        if( Editor_DocFind(&g_editor.doc, EDITOR_DOC_SPAWN, key, &handle) && handle.spawn )
            for( int i = 0; i < handle.spawn->file.line_count; i++ )
                found += handle.spawn->file.lines[i].kind == EDITOR_SPAWN_LINE_ROW
                         && strcmp(handle.spawn->file.lines[i].row.name, "guard") == 0
                         && handle.spawn->file.lines[i].row.abs_x == 3210;
        CHECK(found == 1, "and the spawn is placed in %s", key);
        Editor_Undo(&g_editor);
        frame();
        found = 0;
        if( Editor_DocFind(&g_editor.doc, EDITOR_DOC_SPAWN, key, &handle) && handle.spawn )
            for( int i = 0; i < handle.spawn->file.line_count; i++ )
                found += handle.spawn->file.lines[i].kind == EDITOR_SPAWN_LINE_ROW;
        CHECK(found == 0 && strcmp(doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY), k_encounters) == 0,
            "one undo takes both back, the document byte for byte");
    }
    g_ui.tools.tile_valid = 0;
    activate(g_w.button_add_name);
    CHECK(strstr(Editor_UiStatusText(&g_ui), "Add spawn refused: latch a tile") != NULL, "no tile: refused (%s)",
        Editor_UiStatusText(&g_ui));

    /* The Spawns panel's Group...: the selection joins the shown set. */
    {
        struct Editor_SpawnRow rows[2];
        memset(rows, 0, sizeof(rows));
        snprintf(rows[0].name, sizeof(rows[0].name), "goblin");
        rows[0].abs_x = 3212;
        rows[0].abs_z = 3212;
        rows[0].count = 1;
        rows[1] = rows[0];
        rows[1].abs_x = 3205;
        rows[1].abs_z = 3205;
        Editor_Spawns_Select(&g_ui, rows, 2);
        CHECK(Editor_Encounter_GroupSelection(&g_ui) == 1, "Group adds the one spawn the set lacks");
        frame();
        CHECK(strstr(doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY), "spawn npc:goblin 3212 3212 0") != NULL,
            "it is in the set");
        Editor_Undo(&g_editor);
        frame();
    }

    /* Colour: the set's line, one undo step. */
    ToriRSChrome_DropdownSetSelected(&g_chrome, g_w.dropdown_colour, 6);
    activate(g_w.dropdown_colour);
    CHECK(strstr(doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY), "encounter camp | colour 5 |") != NULL,
        "Colour rewrites the line");
    Editor_Undo(&g_editor);
    frame();
    CHECK(strcmp(doc_text(EDITOR_DOC_TEXT, EDITOR_ENCOUNTERS_DOC_KEY), k_encounters) == 0, "and its undo restores it");
}

