/*
 * Emit ToriDraw's lookup tables as a C translation unit of `const` arrays.
 *
 * ## Why
 *
 * ToriDraw builds its tables at ToriDraw_Init: the HSL16 palette, three
 * trigonometric tables, an arctangent table, two reciprocal tables. That is
 * 185 KB of writable storage at 16bpp and 313 KB at 32bpp, all of it in RAM,
 * all of it immutable after the first millisecond of the program.
 *
 * On a desktop that is free. On a client with a quarter-megabyte of RAM, the
 * palette alone is more than half the budget and the client cannot run at all.
 * Compiled as `const`, the same bytes sit in .rodata, which a linker script
 * puts in flash -- and the client's RAM cost for tables falls to the 16 KB
 * yaw-pair table, which is derived from whichever sine and cosine tables are
 * selected and therefore cannot be frozen.
 *
 * ## Use
 *
 *   cc -DTORIDRAW_PIXEL_FORMAT=TORIDRAW_PF_RGB565 -I<toridraw> \
 *      toridraw_tables_gen.c -lm -o tables_gen
 *   ./tables_gen > toridraw_tables_precomputed.c
 *
 *   cc -DTORIDRAW_PIXEL_FORMAT=TORIDRAW_PF_RGB565 -DTORIDRAW_TABLES_PRECOMPUTED \
 *      -I<toridraw> -c toridraw_unity.c toridraw_tables_precomputed.c
 *
 * Build the generator with the SAME -DTORIDRAW_PIXEL_FORMAT as the target: the
 * palette's element type is toripixel_t, and a unit generated for one format is
 * the wrong width for another. The emitted file names the format it was built
 * for and _Static_asserts that the build consuming it agrees, so getting this
 * wrong is a compile error rather than a screen of wrong colours.
 *
 * ## Why it includes shared_tables.c
 *
 * So there is ONE implementation of every table's math. A generator that
 * reimplemented the palette's HSL-to-RGB or the atan table's rounding would be
 * a second copy of the truth, and the copy is wrong within a month -- silently,
 * because a palette that is subtly off does not fail, it just looks slightly
 * wrong on the target and nowhere else. Including the source and calling its
 * own builders makes the emitted values the values, by construction.
 *
 * The include is deliberately of the NON-precomputed path (this file must not
 * be compiled with TORIDRAW_TABLES_PRECOMPUTED, and says so).
 */

#ifdef TORIDRAW_TABLES_PRECOMPUTED
#error "the generator builds the tables; it cannot be built against precomputed ones"
#endif

#include "graphics/shared_tables.c"

#include <stdio.h>

static void
emit_int_table(
    const char* type,
    const char* name,
    const int* values,
    int count)
{
    int i;

    printf("const %s %s[%d] = {\n", type, name, count);
    for( i = 0; i < count; i++ )
        printf("%s%d,%s", (i % 8) == 0 ? "    " : " ", values[i], (i % 8) == 7 ? "\n" : "");
    if( (count % 8) != 0 )
        printf("\n");
    printf("};\n\n");
}

static void
emit_palette(void)
{
    int i;

    /* Printed as unsigned hex rather than decimal because toripixel_t is
     * `int` on XRGB8888 and `uint16_t` on the 16-bit formats, and a hex
     * literal is the same value under both without a cast per entry. */
    printf("const toripixel_t g_hsl16_to_pixel_table[65536] = {\n");
    for( i = 0; i < 65536; i++ )
        printf(
            "%s0x%X,%s",
            (i % 8) == 0 ? "    " : " ",
            (unsigned)(uint32_t)g_hsl16_to_pixel_table[i],
            (i % 8) == 7 ? "\n" : "");
    printf("};\n\n");
}

int
main(void)
{
    init_hsl16_to_pixel_table();
    ToriDraw_InitSinTable();
    ToriDraw_InitCosTable();
    ToriDraw_InitTanTable();
    ToriDraw_InitAtanTable();
    init_reciprocal16();

    printf("/*\n");
    printf(" * GENERATED by 3rd/toridraw/tools/toridraw_tables_gen.c. Do not edit.\n");
    printf(" *\n");
    printf(" * Pixel format: %s (%d bytes per pixel).\n", TORIPIXEL_FORMAT_NAME, TORIPIXEL_BYTES);
    printf(" *\n");
    printf(" * Compile alongside toridraw_unity.c with -DTORIDRAW_TABLES_PRECOMPUTED\n");
    printf(" * and the same -DTORIDRAW_PIXEL_FORMAT this was generated for.\n");
    printf(" */\n\n");

    printf("#include \"graphics/shared_tables.h\"\n\n");

    printf("#ifndef TORIDRAW_TABLES_PRECOMPUTED\n");
    printf("#error \"precomputed tables built without -DTORIDRAW_TABLES_PRECOMPUTED\"\n");
    printf("#endif\n\n");

    /* The format is not a comment: a unit generated for RGB565 and linked into
     * an XRGB8888 build would define a 128 KB array where the consumer expects
     * 256 KB, and the palette lookups past halfway would read whatever follows
     * it. Two bytes are not four, and the linker will not say so. */
    printf("_Static_assert(\n");
    printf("    TORIDRAW_PIXEL_FORMAT == %d,\n", TORIDRAW_PIXEL_FORMAT);
    printf(
        "    \"precomputed tables were generated for %s and this build selected another "
        "format\");\n\n",
        TORIPIXEL_FORMAT_NAME);

    emit_palette();
    emit_int_table("int", "g_toridraw_sin_precomputed", g_sin_table, 2048);
    emit_int_table("int", "g_toridraw_cos_precomputed", g_cos_table, 2048);
    emit_int_table("int", "g_toridraw_tan_precomputed", g_tan_table, 2048);
    emit_int_table(
        "int", "g_atan_turns16_table", g_atan_turns16_table, TORIDRAW_ATAN_TABLE_LEN);
    emit_int_table("int", "g_reciprocal15", g_reciprocal15, 4096);
    emit_int_table("int", "g_reciprocal16", g_reciprocal16, 4096);

    return 0;
}
