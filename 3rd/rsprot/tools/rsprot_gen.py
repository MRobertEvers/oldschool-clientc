#!/usr/bin/env python3
"""Generate RSProt's C from its spec -- the only input is spec/.

    tools/rsprot_gen.py            write every generated file
    tools/rsprot_gen.py --check    exit 1 if any generated file differs from the spec

spec/ is the protocol as data, in INI files (tools/rsprot_spec.py reads them
and documents each family's sections):

    spec/packets/<file>.ini     a packet codec: its message structs and, per
                                version, the reads in wire order and the
                                revisions that version covers
    spec/tables/osrs<N>.ini     revision N's prot table: name, opcode, size and
                                the version each row calls
    spec/streams/<stream>.ini   the info streams' versions and per-revision
                                constants

and every file under packets/, gen/ and streams/ that says "GENERATED by
tools/rsprot_gen.py" is written from it, plus rsprot_packets_unity.c from the
contents of packets/ and streams/. Nothing else is read: no RSProt, no RSProx,
no Kotlin. To change a codec, change its spec and run this.
"""
import argparse
import os
import re
import sys

from rsprot_spec import load_packet, load_stream, load_table, parse_rev

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(HERE, "spec")
GENERATOR = "tools/rsprot_gen.py"

# Every revision with a prot table: what a `revs` run expands over.
REVISIONS = sorted(parse_rev(n[:-4]) for n in os.listdir(os.path.join(SPEC, "tables")) if n.endswith(".ini"))


def expand(lo, hi):
    """The tabled revisions in [lo, hi]; both ends must be tabled."""
    assert lo in REVISIONS, "no spec/tables file for %s" % lo.text
    assert hi in REVISIONS, "no spec/tables file for %s" % hi.text
    return [r for r in REVISIONS if r.family == lo.family and lo <= r <= hi]


def runs_text(runs):
    return ", ".join(lo.text if lo == hi else "%s-%s" % (lo.text, hi.text[len(hi.family):]) for lo, hi in runs)


def comment_block(lines, indent=""):
    """A /* ... */ block, one ` * ` line per entry ("" for a blank line)."""
    out = [indent + "/*"]
    for line in lines:
        out.append((indent + " * " + line).rstrip())
    out.append(indent + " */")
    return out


# --- packets/ ---------------------------------------------------------------

DIRECTION = {"out": "server -> client", "in": "client -> server"}


def packet_layout_rows(p):
    """The version table's rows: (lo, hi, version) sorted by revision."""
    rows = []
    for i, layout in enumerate(p["layouts"], 1):
        for lo, hi in layout["revs"]:
            rows.append((lo, hi, i))
    return sorted(rows)


def packet_h(p):
    f = p["file"]
    d = p["dir"]
    guard = "RSPROT_PACKET_%s_H" % f.upper()
    msg = p["structs"][-1]["name"]
    head = "%s -- %s." % (p["prot"], DIRECTION[d])
    if p.get("summary"):
        head += " " + p["summary"]
    banner = [head, "",
              "GENERATED by %s from spec/packets/%s.ini -- do not edit:" % (GENERATOR, f),
              "change the spec and regenerate."]
    if p.get("doc"):
        banner += [""] + p["doc"]
    if p.get("source"):
        banner += ["", "Ported from %s: %s" % (p["source"]["project"], p["source"]["path"])]
    out = ["#ifndef " + guard, "#define " + guard, ""]
    out += comment_block(banner)
    out += ["", '#include "../include/rsprot_exec.h"']
    for inc in p.get("includes", []):
        out.append('#include "%s"' % inc)
    out.append("")
    for s in p["structs"]:
        if s.get("doc"):
            out += s["doc"]
        elif s is p["structs"][-1]:
            out.append("/** One struct for every version: the union of their fields. */")
        out.append("typedef struct %s {" % s["name"])
        for field in s["fields"]:
            if isinstance(field, str):
                field = {"decl": field}
            for line in field.get("doc", []):
                out.append("\t" + line)
            note = " /* %s */" % field["note"] if field.get("note") else ""
            out.append("\t%s;%s" % (field["decl"], note))
        out.append("} %s;" % s["name"])
        out.append("")
    for define in p.get("defines", []):
        out += define.get("doc", [])
        out.append("#define %s %s" % (define["name"], define["value"]))
        out.append("")
    for i, layout in enumerate(p["layouts"], 1):
        out.append("/* v%d -- revs %s. */" % (i, runs_text(layout["revs"])))
        out.append("void packet_%s_v%d_%s(RsprotExec *x, %s *m);" % (f, i, d, msg))
    out += ["", "/* Per-revision entry points: what revision R calls is packet_%s_<R>_%s. */" % (f, d)]
    for lo, hi, i in packet_layout_rows(p):
        for rev in expand(lo, hi):
            out.append("#define packet_%s_%s_%s packet_%s_v%d_%s" % (f, rev.ident, d, f, i, d))
    out += ["",
            "/** Revision -> layout. See the .c for the rows. */",
            "extern const RsprotVersionRange rsprot_%s_%s[];" % (f, d),
            "extern const int rsprot_%s_%s_count;" % (f, d)]
    if p.get("binds"):
        out += ["", "/* One layout for every prot bound to it; the registry gives each a row onto",
                " * the table above. */"]
        out += ["/* rsprot-bind: %s */" % b for b in p["binds"]]
    out += ["", "#endif", ""]
    return "\n".join(out)


def packet_body_line(item):
    if isinstance(item, str):
        return item
    enc, field = item
    if "->" not in field:
        field = "m->" + field
    return "    RSPROT_%s(x, %s);" % (enc, field)


def packet_c(p):
    f = p["file"]
    d = p["dir"]
    msg = p["structs"][-1]["name"]
    out = ["/* %s. GENERATED by %s from spec/packets/%s.ini -- do not edit. */" % (p["prot"], GENERATOR, f),
           '#include "%s.h"' % f, ""]
    ported = ["Ported from %s:" % p["source"]["project"], "  " + p["source"]["path"], ""] if p.get("source") else []
    out += comment_block(ported + ["One function per layout, running in whichever direction the executor is",
                                   "in -- so a server's writer and a client's reader are the same",
                                   "transcription and cannot drift apart."])
    out.append("")
    for i, layout in enumerate(p["layouts"], 1):
        out += ["/* v%d -- revs %s. */" % (i, runs_text(layout["revs"])),
                "void",
                "packet_%s_v%d_%s(RsprotExec *x, %s *m)" % (f, i, d, msg),
                "{"]
        out += [packet_body_line(item) for item in layout["body"]]
        out += ["}", ""]
    rows = packet_layout_rows(p)
    out += comment_block(["%d row(s) for %d layout(s). A revision not listed has no %s and" % (
        len(rows), len(p["layouts"]), p["prot"]), "picks NULL."])
    out.append("const RsprotVersionRange rsprot_%s_%s[] = {" % (f, d))
    for lo, hi, i in rows:
        out.append("    { %s, %s, (RsprotCodecFn)packet_%s_v%d_%s }," % (lo.c_id, hi.c_id, f, i, d))
    out += ["};", "",
            "const int rsprot_%s_%s_count =" % (f, d),
            "    (int)(sizeof(rsprot_%s_%s) / sizeof(rsprot_%s_%s[0]));" % (f, d, f, d), ""]
    return "\n".join(out)


def packet_files():
    out = {}
    pdir = os.path.join(SPEC, "packets")
    for name in sorted(os.listdir(pdir)):
        if not name.endswith(".ini"):
            continue
        p = load_packet(os.path.join(pdir, name))
        out["packets/%s.h" % p["file"]] = packet_h(p)
        out["packets/%s.c" % p["file"]] = packet_c(p)
    return out


# --- gen/: the prot tables ---------------------------------------------------

SIZES = {"VARU8": "RSPROT_VARU8", "VARU16": "RSPROT_VARU16"}


def table_row(row):
    """[name, opcode, size(, the version it calls)]."""
    name, code, size = row[:3]
    codec = '"%s"' % row[3] if len(row) > 3 else "NULL"
    size = SIZES.get(size, size) if isinstance(size, str) else str(size)
    return '    { "%s", %d, %s, %s },' % (name, code, size, codec)


def table_h(t):
    rev = t["revision"]
    n = rev.ident
    N = n.upper()
    guard = "RSPROT_GEN_%s_PROT_H" % N
    out = ["#ifndef " + guard, "#define " + guard, ""]
    out += comment_block(["GENERATED by %s from spec/tables/%s.ini -- do not edit." % (GENERATOR, n),
                          "Revision %s's prots: name, opcode, size, and the version each calls" % rev.text,
                          "where that is not its name. Ported from %s." % t["source"]])
    out += ["", '#include "../src/rsprot_tables_def.h"', "", "/* clang-format off */",
            "static const RsprotProtDef rsprot_%s_server[] = {" % n]
    out += [table_row(r) for r in t["server"]]
    out += ["};", "static const RsprotProtDef rsprot_%s_client[] = {" % n]
    out += [table_row(r) for r in t["client"]]
    out += ["};", "", "static const char *const rsprot_%s_zone_order[] = {" % n]
    out += ['    "%s",' % z for z in t["zone_order"]]
    out += ["};", "/* clang-format on */", ""]
    for part, arr in (("SERVER", "server"), ("CLIENT", "client"), ("ZONE", "zone_order")):
        out.append("#define RSPROT_%s_%s_COUNT ((int)(sizeof(rsprot_%s_%s) / sizeof(rsprot_%s_%s[0])))"
                   % (N, part, n, arr, n, arr))
    out += ["", "#endif", ""]
    return "\n".join(out)


def tables_h(revisions):
    out = ["#ifndef RSPROT_GEN_TABLES_H", "#define RSPROT_GEN_TABLES_H", ""]
    out += comment_block(["GENERATED by %s from spec/tables/ -- do not edit." % GENERATOR, "",
                          "Every revision's table (<revision>_prot.h) and a lookup by revision. A",
                          "revision is added by adding its spec/tables/<revision>.ini."])
    out += ["", '#include "../src/rsprot_tables_def.h"', ""]
    out += ['#include "%s_prot.h"' % r.ident for r in revisions]
    out += ["", "/* clang-format off */", "static const RsprotRevTable rsprot_all_revisions[] = {"]
    for r in revisions:
        n, N = r.ident, r.ident.upper()
        out.append("    { { %s }, rsprot_%s_server, RSPROT_%s_SERVER_COUNT, rsprot_%s_client, "
                   "RSPROT_%s_CLIENT_COUNT, rsprot_%s_zone_order, RSPROT_%s_ZONE_COUNT },"
                   % (r.c_id, n, N, n, N, n, N))
    out += ["};", "/* clang-format on */", "",
            "#define RSPROT_REVISION_COUNT ((int)(sizeof(rsprot_all_revisions) / sizeof(rsprot_all_revisions[0])))",
            "",
            "/* The table for `rev`, or NULL if this build was not generated with that",
            " * revision vendored. */",
            "static inline const RsprotRevTable *",
            "rsprot_rev_table(RsprotRev rev)",
            "{",
            "    for( int i = 0; i < RSPROT_REVISION_COUNT; i++ )",
            "        if( rsprot_all_revisions[i].rev.id == rev.id )",
            "            return &rsprot_all_revisions[i];",
            "    return 0;",
            "}",
            "",
            "#endif",
            ""]
    return "\n".join(out)


def table_files():
    out = {}
    tdir = os.path.join(SPEC, "tables")
    revisions = []
    for name in sorted(os.listdir(tdir)):
        if name.endswith(".ini"):
            t = load_table(os.path.join(tdir, name))
            revisions.append(t["revision"])
            out["gen/%s_prot.h" % t["revision"].ident] = table_h(t)
    out["gen/rsprot_tables.h"] = tables_h(sorted(revisions))
    return out


# --- streams/: the info streams' versions and per-revision constants --------

STREAM_PROT = {"player_info": "PLAYER_INFO", "npc_info": "NPC_INFO", "worldentity_info": "WORLDENTITY_INFO"}
ENTRY_ARGS = {
    "player_info": "    RsprotPlayerInfo *pi, const uint8_t *data, int32_t len, RsprotInfoList *out)",
    "npc_info": "    const uint8_t *data, int32_t len, RsprotNpcTypeLengths lengths, void *ctx,\n"
                "    RsprotInfoList *out)",
    "worldentity_info": "    const uint8_t *data, int32_t len, RsprotInfoList *out)",
}
NPC_VARIANTS = ("small", "large")


def stream_banner(st, lines):
    return comment_block(lines + ["", "GENERATED by %s from spec/streams/%s.ini -- do not edit." % (GENERATOR, st)])


def stream_entries(spec):
    """(revision, version, entry point name) in the order the header declares them."""
    st = spec["stream"]
    out = []
    for r in spec["revisions"]:
        n = r["revision"]
        for c in r["carries"]:
            k = c["version"]
            if st == "player_info":
                out.append((n, k, "player_info_%s" % n.ident))
            elif st == "npc_info":
                out += [(n, k, "npc_info_%s_v%d_%s" % (v, k, n.ident)) for v in NPC_VARIANTS]
            else:
                out.append((n, k, "worldentity_info_v%d_%s" % (k, n.ident)))
    return out


def stream_lookups(spec):
    """{lookup function: [(revision, entry point)]}, in definition order."""
    st = spec["stream"]
    found = {}
    for n, k, entry in stream_entries(spec):
        name = entry[:entry.rindex("_" + n.ident)] + "_" + n.family
        found.setdefault(name, []).append((n, entry))
    return {name: found[name] for name in sorted(found)}


def stream_h(spec):
    st = spec["stream"]
    guard = "RSPROT_STREAM_%s_H" % st.upper()
    out = ["#ifndef " + guard, "#define " + guard, ""]
    out += stream_banner(st, ["%s: the entry points, <prot>_<revision> for each revision and version," % STREAM_PROT[st],
                              "and a lookup by revision for each."])
    out += ["", '#include "rsprot_info.h"', ""]
    for n, k, entry in stream_entries(spec):
        out += ["int %s(" % entry, ENTRY_ARGS[st] + ";"]
    out.append("")
    for name, rows in stream_lookups(spec).items():
        fn = {"player_info": "RsprotPlayerInfoReadFn", "npc_info": "RsprotNpcInfoReadFn",
              "worldentity_info": "RsprotWorldEntityInfoReadFn"}[st]
        out += ["/** %s<revision>, or NULL where the revision has no such prot. */" % name,
                "%s %s(RsprotRev rev);" % (fn, name)]
    out += ["", "#endif", ""]
    return "\n".join(out)


def stream_c(spec):
    st = spec["stream"]
    fn = {"player_info": "RsprotPlayerInfoReadFn", "npc_info": "RsprotNpcInfoReadFn",
          "worldentity_info": "RsprotWorldEntityInfoReadFn"}[st]
    out = stream_banner(st, ["The revision -> entry point lookups for %s." % STREAM_PROT[st]])
    out += ['#include "%s.h"' % st, "", "#include <stddef.h>", ""]
    for name, rows in stream_lookups(spec).items():
        out += [fn, "%s(RsprotRev rev)" % name, "{", "    switch (rev.id) {"]
        out += ["    case %s: return %s;" % (n.c_id, entry) for n, entry in rows]
        out += ["    default: return NULL;", "    }", "}", ""]
    return "\n".join(out)


def version_struct(spec, v):
    st = spec["stream"]
    name = {"player_info": "PlayerInfoV%d", "npc_info": "NpcInfoV%d", "worldentity_info": "WorldEntityInfoV%d"}[st] % v["version"]
    out = ["typedef struct %s" % name, "{"]
    if st == "worldentity_info":
        out += ["    /** The spawn record after its index. */", "    RsprotWeSpawnRead spawn;"]
        if v["extended"]:
            out += ["    /** An update entry's extended info: its flag byte, then the payload. */",
                    "    RsprotWeExtRead ext;"]
    else:
        out += ["    /** The flag word's continuation bits (0 ends them) and the flags no",
                "     *  layout exists for. */",
                "    uint32_t ext[3];",
                "    uint32_t illegal;"]
        if st == "npc_info":
            out += ["    /** The entering-view record, in this revision's field order. */",
                    "    RsprotNpcRecordRead record;"]
        out += ["    /** The blocks the flag word names, in this revision's wire order (the",
                "     *  revision's dispatch). */",
                "    int (*blocks)(RsprotInfoBlocks *t, const struct %s *k);" % name]
        out += ["    %s %s;" % (enc, field) for field, enc in v["fields"]]
    out.append("} %s;" % name)
    return name, out


def version_h(spec, v):
    st = spec["stream"]
    k = v["version"]
    guard = "RSPROT_STREAM_%s_V%d_H" % (st.upper(), k)
    name, struct = version_struct(spec, v)
    out = ["#ifndef " + guard, "#define " + guard, ""]
    out += stream_banner(st, ["%s v%d -- revs %s: the version, its constants' shape, and the reader" % (
        STREAM_PROT[st], k, runs_text(v["revs"])), "each revision's entry point calls."])
    if st == "worldentity_info":
        out += ["", '#include "rsprot_info.h"', '#include "rsprot_info_internal.h"', ""]
    else:
        out += ["", '#include "rsprot_info_blocks.h"', ""]
    out += struct + [""]
    if st == "player_info":
        out += ["int player_info_v%d(" % k,
                "    const %s *k, RsprotPlayerInfo *pi, const uint8_t *data, int32_t len," % name,
                "    RsprotInfoList *out);"]
    elif st == "npc_info":
        for variant in NPC_VARIANTS:
            out += ["int npc_info_%s_v%d(" % (variant, k),
                    "    const %s *k, const uint8_t *data, int32_t len, RsprotNpcTypeLengths lengths," % name,
                    "    void *ctx, RsprotInfoList *out);"]
    else:
        out += ["int worldentity_info_v%d(" % k,
                "    const %s *k, const uint8_t *data, int32_t len, RsprotInfoList *out);" % name]
    out += ["", "#endif", ""]
    return "\n".join(out)


def version_c(spec, v):
    st = spec["stream"]
    k = v["version"]
    name = version_struct(spec, v)[0]
    out = stream_banner(st, ["%s v%d -- revs %s. See %s_v%d.h." % (STREAM_PROT[st], k, runs_text(v["revs"]), st, k)])
    out += ['#include "%s_v%d.h"' % (st, k), "", "#include <assert.h>"]
    if st == "player_info":
        out += ["#include <string.h>", "", "int", "player_info_v%d(" % k,
                "    const %s *k, RsprotPlayerInfo *pi, const uint8_t *data, int32_t len," % name,
                "    RsprotInfoList *out)",
                "{",
                "    static _Thread_local int extended[RSPROT_INFO_PLAYER_SLOTS];",
                "    static _Thread_local RsprotPlayerPacket pp;",
                "    RsprotInfoBlocks t;",
                "    RsprotBuf b;",
                "    int count;",
                "",
                "    assert(k);",
                "    assert(pi);",
                "    assert(out);",
                "    rsprot_info_list_begin(out);",
                "    rsprot_buf_wrap_read(&b, data, len);",
                "    /* An unseeded table reads nothing: no GPI init has arrived. */",
                "    if (!pi->seeded) {",
                "        rsprot_info_stop(&b, out, RSPROT_STOP_ERROR, -1);",
                "        return out->count;",
                "    }",
                "    pp.pi = pi;",
                "    count = rsprot_info_player_sections(&pp, &b, out, extended);",
                "    memset(&t, 0, sizeof(t));",
                "    t.b = &b;",
                "    t.out = out;",
                "    t.player = &pp;",
                "    for (int i = 0; i < count && !b.err; i++) {",
                "        if (!rsprot_info_flags(&t, extended[i], k->ext, k->illegal))",
                "            break;",
                "        rsprot_info_player_target(out, pi, extended[i]);",
                "        if (!k->blocks(&t, k))",
                "            break;",
                "    }",
                "    return rsprot_info_finish(&b, out, len);",
                "}", ""]
    elif st == "npc_info":
        out += ["#include <string.h>", "", "static int", "npc_info_v%d_read(" % k,
                "    const %s *k, int delta_bits, const uint8_t *data, int32_t len," % name,
                "    RsprotNpcTypeLengths lengths, void *ctx, RsprotInfoList *out)",
                "{",
                "    static _Thread_local int extended[RSPROT_INFO_NPC_EXTENDED_MAX];",
                "    RsprotInfoBlocks t;",
                "    RsprotBuf b;",
                "    int count;",
                "",
                "    assert(k);",
                "    assert(out);",
                "    rsprot_info_list_begin(out);",
                "    rsprot_buf_wrap_read(&b, data, len);",
                "    count = rsprot_info_npc_sections(&b, delta_bits, k->record, out, extended);",
                "    memset(&t, 0, sizeof(t));",
                "    t.b = &b;",
                "    t.out = out;",
                "    t.lengths = lengths;",
                "    t.ctx = ctx;",
                "    for (int i = 0; i < count && !b.err; i++) {",
                "        if (!rsprot_info_flags(&t, extended[i], k->ext, k->illegal))",
                "            break;",
                "        rsprot_info_emit_value(out, RSPROT_OP_SET_EXT, (uint64_t)extended[i]);",
                "        if (!k->blocks(&t, k))",
                "            break;",
                "    }",
                "    return rsprot_info_finish(&b, out, len);",
                "}", ""]
        for variant, bits in (("small", v["small_delta_bits"]), ("large", 8)):
            out += ["int", "npc_info_%s_v%d(" % (variant, k),
                    "    const %s *k, const uint8_t *data, int32_t len, RsprotNpcTypeLengths lengths," % name,
                    "    void *ctx, RsprotInfoList *out)",
                    "{",
                    "    return npc_info_v%d_read(k, %d, data, len, lengths, ctx, out);" % (k, bits),
                    "}", ""]
    else:
        out += ["", "int", "worldentity_info_v%d(" % k,
                "    const %s *k, const uint8_t *data, int32_t len, RsprotInfoList *out)" % name,
                "{", "    assert(k);"]
        if v["extended"]:
            out += ["    return rsprot_info_worldentity_extended_read(",
                    "        k->spawn, k->ext, data, len, out);"]
        else:
            out.append("    return rsprot_info_worldentity_plain_read(k->spawn, data, len, out);")
        out += ["}", ""]
    return "\n".join(out)


def initializer(value, indent):
    """A designated initializer from an ordered {field: value or {...}}."""
    pad = "    " * indent
    out = []
    for key, v in value.items():
        if isinstance(v, dict):
            out.append("%s.%s = {" % (pad, key))
            out += initializer(v, indent + 1)
            out.append("%s}," % pad)
        else:
            out.append("%s.%s = %s," % (pad, key, v))
    return out


def dispatch(fn, k_type, blocks):
    out = ["static int", "%s(RsprotInfoBlocks *t, const %s *k)" % (fn, k_type), "{"]
    for bit, reader, field in blocks:
        args = "t, BIT_%s" % bit + (", &k->%s" % field if field else "")
        out += ["    if ((t->flag & BIT_%s) != 0 &&" % bit,
                "        !%s(%s))" % (reader, args),
                "        return 0;"]
    out += ["    return 1;", "}"]
    return out


def revision_c(spec, r):
    st = spec["stream"]
    n = r["revision"]
    versions = [c["version"] for c in r["carries"]]
    out = stream_banner(st, ["%s at revision %s: the constants of the version(s) it carries (%s)," % (
        STREAM_PROT[st], n.text, ", ".join("v%d" % k for k in versions)),
        "and their entry points. The flag bits, the dispatch's block order, each field's",
        "byte transform and each record's field order are this revision's; the shapes",
        "are rsprot_info_blocks.c and rsprot_info_worldentity.c."])
    out.append('#include "%s.h"' % st)
    out += ['#include "%s_v%d.h"' % (st, k) for k in versions]
    out.append("")
    if r.get("bits"):
        out.append("/* The flag word's flag bits. */")
        out += ["#define BIT_%s %s" % (name, value) for name, value in r["bits"]]
        out.append("")
    for c in r["carries"]:
        k = c["version"]
        k_type = {"player_info": "PlayerInfoV%d", "npc_info": "NpcInfoV%d",
                  "worldentity_info": "WorldEntityInfoV%d"}[st] % k
        const = "k_%s_%s" % (st, n.ident) if st == "player_info" else "k_%s_%s_v%d" % (st, n.ident, k)
        prefix = "%s_%s" % (st, n.ident) if st == "player_info" else "%s_%s_v%d" % (st, n.ident, k)
        if st == "worldentity_info":
            out.append("/* %s_V%d. */" % (STREAM_PROT[st], k))
        for f in c.get("functions", []):
            out += ["/* clang-format off */"] if f.get("clang_off") else []
            out += ["static void", "%s_%s(%s)" % (prefix, f["name"], f["params"]), "{"]
            out += f["body"]
            out += ["}", ""]
            out += ["/* clang-format on */"] if f.get("clang_off") else []
        if st != "worldentity_info":
            out += dispatch(prefix + "_blocks", k_type, c["blocks"]) + [""]
        out += ["/* clang-format off */"] if st != "worldentity_info" else []
        out.append("static const %s %s = {" % (k_type, const))
        out += initializer(c["constants"], 1)
        out.append("};")
        out += ["/* clang-format on */"] if st != "worldentity_info" else []
        out.append("")
        if st == "player_info":
            out += ["int", "player_info_%s(" % n.ident, ENTRY_ARGS[st], "{",
                    "    return player_info_v%d(&%s, pi, data, len, out);" % (k, const), "}", ""]
        elif st == "npc_info":
            for variant in NPC_VARIANTS:
                out += ["int", "npc_info_%s_v%d_%s(" % (variant, k, n.ident), ENTRY_ARGS[st], "{",
                        "    return npc_info_%s_v%d(" % (variant, k),
                        "        &%s, data, len, lengths, ctx, out);" % const, "}", ""]
        else:
            out += ["int", "worldentity_info_v%d_%s(" % (k, n.ident), ENTRY_ARGS[st], "{",
                    "    return worldentity_info_v%d(&%s, data, len, out);" % (k, const), "}", ""]
    for name, _ in r.get("bits", []):
        out.append("#undef BIT_%s" % name)
    if r.get("bits"):
        out.append("")
    return "\n".join(out)


def stream_files():
    out = {}
    sdir = os.path.join(SPEC, "streams")
    for name in sorted(os.listdir(sdir)):
        if not name.endswith(".ini"):
            continue
        spec = load_stream(os.path.join(sdir, name))
        st = spec["stream"]
        out["streams/%s.h" % st] = stream_h(spec)
        out["streams/%s.c" % st] = stream_c(spec)
        for v in spec["versions"]:
            out["streams/%s_v%d.h" % (st, v["version"])] = version_h(spec, v)
            out["streams/%s_v%d.c" % (st, v["version"])] = version_c(spec, v)
        for r in spec["revisions"]:
            out["streams/%s_%s.c" % (st, r["revision"].ident)] = revision_c(spec, r)
    return out


# --- rsprot_packets_unity.c: every codec and stream, one TU ------------------

BIND_RE = re.compile(r"^/\* rsprot-bind: (\w+) \*/$", re.M)


def on_disk_or(files, rel):
    if rel in files:
        return files[rel]
    with open(os.path.join(HERE, rel)) as f:
        return f.read()


def listing(files, sub, suffix):
    names = set(n for n in os.listdir(os.path.join(HERE, sub)) if n.endswith(suffix))
    names |= set(rel[len(sub) + 1:] for rel in files if rel.startswith(sub + "/") and rel.endswith(suffix))
    return sorted(names)


def unity_c(files):
    pkt_c = [n[:-2] for n in listing(files, "packets", ".c")]
    pkt_h = set(n[:-2] for n in listing(files, "packets", ".h"))
    packets = [n for n in pkt_c if n in pkt_h]
    out = comment_block([
        "rsprot packet-codec unity anchor -- every codec under packets/ and every",
        "info-stream reader under streams/, one TU, then the registry: one row per prot",
        "a codec's table answers for.",
        "",
        "GENERATED by %s from the contents of packets/ and streams/ -- do not" % GENERATOR,
        "edit: a packet is added by adding its spec (or its hand-written files).",
        "",
        "Separate from rsprot_unity.c, which is crypto and compression; the codecs",
        "run on the executor (src/rsprot_exec.c), which is its own object. One TU",
        "rather than one object per packet because there are hundreds of these and",
        "they are small; the compile is dominated by the headers, not the bodies."])
    out.append("")
    out.append("// clang-format off")
    out += ['#include "packets/%s.c"' % n for n in packets]
    out += ['#include "streams/%s"' % n for n in listing(files, "streams", ".c")]
    out += ["// clang-format on", ""]
    out += comment_block([
        "The registry: every codec table above, keyed by its prot's name -- the name a",
        "revision's prot table calls it (gen/osrs<N>_prot.h), or the version a row",
        "names. From the `extern const RsprotVersionRange rsprot_<file>_<dir>[]` each",
        "packet header declares, and its `rsprot-bind` lines where one layout serves",
        "several prots; see include/rsprot_registry.h."])
    out += ['#include "include/rsprot_registry.h"', '#include "src/rsprot_tables_def.h"', "",
            "#include <string.h>", "", "const RsprotRegistryEntry rsprot_registry[] = {"]
    for n in packets:
        hdr = on_disk_or(files, "packets/%s.h" % n)
        binds = BIND_RE.findall(hdr)
        for m in re.finditer(r"extern const RsprotVersionRange rsprot_(\w+)_(out|in)\[\];", hdr):
            snake, d = m.group(1), m.group(2)
            for prot in binds or [snake.upper()]:
                out.append('    { "%s", RSPROT_REG_%s, rsprot_%s_%s, &rsprot_%s_%s_count },'
                           % (prot, d.upper(), snake, d, snake, d))
    out += ["};", "",
            "const int rsprot_registry_count = (int)(sizeof(rsprot_registry) / sizeof(rsprot_registry[0]));",
            "", '#include "src/rsprot_registry.c"', ""]
    return "\n".join(out)


# --- entry points against range tables -------------------------------------

RANGE_ROW_RE = re.compile(r"\{ RSPROT_OSRS_ID\((\d+)\), RSPROT_OSRS_ID\((\d+)\), \(RsprotCodecFn\)(packet_\w+) \}")


def entry_point_problems(files):
    """Every packet header -- generated or hand-written -- must define
    packet_<f>_osrs<N>_<dir> for exactly the revisions its range table covers,
    as the version that table names: a revision's executor calls the entry
    point, and the registry reads the table, so the two may not disagree."""
    revs = sorted(int(m.group(1)) for m in (re.match(r"osrs(\d+)_prot\.h$", n)
                                           for n in listing(files, "gen", ".h")) if m)
    out = []
    for name in listing(files, "packets", ".c"):
        f = name[:-2]
        c = on_disk_or(files, "packets/%s.c" % f)
        h = on_disk_or(files, "packets/%s.h" % f)
        for m in re.finditer(r"const RsprotVersionRange rsprot_(\w+)_(out|in)\[\] = \{(.*?)\n\};", c, re.S):
            snake, d, body = m.groups()
            want = set()
            for lo, hi, fn in RANGE_ROW_RE.findall(body):
                want |= set((r, fn) for r in revs if int(lo) <= r <= int(hi))
            have = set((int(r), fn) for r, fn in re.findall(
                r"^#define packet_%s_osrs(\d+)_%s (\w+)$" % (snake, d), h, re.M))
            for r, fn in sorted(want - have):
                out.append("packets/%s.h: no packet_%s_osrs%d_%s (its range table calls %s)" % (f, snake, r, d, fn))
            for r, fn in sorted(have - want):
                out.append("packets/%s.h: packet_%s_osrs%d_%s -> %s, which its range table does not say" % (f, snake, r, d, fn))
    return out


# --- the driver -------------------------------------------------------------

FAMILIES = [packet_files, table_files, stream_files]


def generated():
    files = {}
    for family in FAMILIES:
        files.update(family())
    files["rsprot_packets_unity.c"] = unity_c(files)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare, write nothing")
    args = ap.parse_args()
    stale = 0
    for rel, text in sorted(generated().items()):
        path = os.path.join(HERE, rel)
        old = open(path).read() if os.path.exists(path) else None
        if old == text:
            continue
        stale += 1
        if args.check:
            print("stale: " + rel)
        else:
            with open(path, "w") as f:
                f.write(text)
            print("wrote " + rel)
    problems = entry_point_problems({})
    for p in problems:
        print("entry: " + p)
    if (args.check and stale) or problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
