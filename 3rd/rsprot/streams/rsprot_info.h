/** One block's scalars, by kind. Signed prims arrive sign-extended. */
typedef struct RsprotInfoBlockOp
{
    uint8_t kind; /* RsprotInfoKind */
    uint32_t flag; /* the block's bit in its revision's flag word */
    union
    {
        /* SAY, NAME_CHANGE */
        struct { const char *text; } say;
        /* MOVE_SPEED, TEMP_MOVE_SPEED, RESET, TRANSFORMATION (the type),
         * LEVEL_CHANGE, ENABLED_OPS (the op mask) */
        struct { int32_t value; } value;
        struct { int32_t id; int32_t delay; } sequence;
        /* 227-238: npc index, or 0x10000 + player index; 0xFFFFFF none. */
        struct { int32_t index; } face_pathing_entity;
        /* instant is 0 on the player form, which has none */
        struct { int32_t angle; int32_t instant; } face_angle;
        /* npc, 227-231: an absolute tile; 0xFFFF clears */
        struct { int32_t x; int32_t z; int32_t instant; } face_coord;
        /* 238+: `flag` = walk type (bits 0-2) | face kind (3-5) | instant (6);
         * kind 0 entity, 1 loc, 2 angle, 3 reset */
        struct
        {
            int32_t flag;
            int32_t entity_type;
            int32_t index;
            int32_t fallback_angle;
            int32_t x;
            int32_t z;
            int32_t size;
            int32_t angle;
        } facing;
        struct { const char *before; const char *after; const char *after_level; } name_extras;
        struct
        {
            int32_t colour_effects;
            int32_t mod_icon;
            int32_t autotyper;
            const uint8_t *data; /* huffman bytes, `data_order` */
            int32_t data_len;
            uint8_t data_order;  /* RsprotInfoPrim (DATA*) */
            uint8_t pattern_count;
            uint8_t pattern[8];
        } chat;
        struct
        {
            int32_t dx1;
            int32_t dz1;
            int32_t dx2;
            int32_t dz2;
            int32_t delay1;
            int32_t delay2;
            int32_t direction;
        } exact_move;
        struct
        {
            int32_t start;
            int32_t end;
            int32_t hue;
            int32_t saturation;
            int32_t lightness;
            int32_t weight;
        } tinting;
        struct
        {
            int32_t start;
            int32_t end;
            int32_t alpha_start;
            int32_t alpha_end;
            int32_t use_start;
        } transparency;
        struct { int32_t delay; int32_t duration; int32_t cancel; } freeze;
        struct
        {
            const uint8_t *data; /* `data_order` */
            int32_t data_len;
            uint8_t data_order;
        } appearance;
        /* `anims[n]` is bit n's animation, -1 where the bit is clear */
        struct { int32_t mask; int32_t anims[15]; } bas;
        /* SPOTANIM, HITMARKS, HEADBARS: how many entry ops follow. HITS: hits,
         * then `count2` bars. */
        struct { int32_t count; int32_t count2; } list;
        /*
         * CUSTOM_TYPED / HEAD_CUSTOM_TYPED / CUSTOM_V3 / V4. `flag` 0x1 resets
         * (nothing else then). Counts are -1 where the array is absent; the
         * entries follow as MODEL / RECOLOUR / RETEXTURE / IDENTKIT ops.
         */
        struct
        {
            int32_t flag;
            int32_t model_count;
            int32_t recolour_count;
            int32_t retexture_count;
            int32_t identkit_count;
            int32_t mirror;     /* -1 when absent */
            int32_t body_type;  /* -1 when absent */
            int32_t recol_all;  /* V4: -1 when absent */
        } custom;
        /* HEADICON_CUSTOM: the slot mask; one HEADICON op per set slot */
        struct { int32_t mask; } headicon;
    };
} RsprotInfoBlockOp;

