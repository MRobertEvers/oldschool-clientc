/** One stream layout's extended-info framing. */
typedef struct RsprotInfoSide
{
    /** The continuation bits: a flag byte carrying `ext[n]` is followed by
     *  byte n+1 (`<< 8 * (n + 1)`). 0 ends the list. */
    uint32_t ext[3];
    /** Every flag that names a block, an illegal one or a continuation; a
     *  flag outside it has no known layout and ends the tail. */
    uint32_t known;
    /** The flags RSProx throws on (CHAT_OLD, UNUSED_FLAGS): no layout. */
    uint32_t illegal;
    /** Blocks in WIRE order. */
    const RsprotInfoBlockDesc *blocks;
    int block_count;
    /** The appearance block's length read and its body's byte order
     *  (players; RSPROT_IP_NONE on the npc side). */
    uint8_t appearance_len_prim;
    uint8_t appearance_data_prim;
} RsprotInfoSide;

