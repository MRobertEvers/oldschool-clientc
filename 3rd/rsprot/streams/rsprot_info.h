#define RSPROT_INFO_PLAYER_SLOTS 2048

/** The player stream's table. Plain data: a host that decodes several
 *  sessions in one process may copy one in and out between them. */
typedef struct RsprotPlayerInfo
{
    int local_index;
    int seeded;
    uint8_t high_res[RSPROT_INFO_PLAYER_SLOTS];
    uint8_t flags[RSPROT_INFO_PLAYER_SLOTS];
    int32_t coord[RSPROT_INFO_PLAYER_SLOTS];
    int32_t low_res_pos[RSPROT_INFO_PLAYER_SLOTS];
} RsprotPlayerInfo;

/** A fresh table, owned by `local_index`. The table is the same at every
 *  revision; only the reader that walks it is per layout. */
void rsprot_player_info_reset(RsprotPlayerInfo *pi, int local_index);

/** Seed the table from the GPI init block (the front of the login REBUILD, or
 *  RECONNECT_OK's body). */
void rsprot_player_info_init(RsprotPlayerInfo *pi, const uint8_t *data, int32_t len);

/*
 * The readers are in the prot files. Every one returns the op count; its
 * `*complete` is 1 when every byte was consumed as the layout says and every op
 * fitted, 0 on a malformed or unknown block (the ops before it are written, the
 * block itself is not, and a player table is still advanced, as the
 * reference's is) or a full `ops`.
 * The npc and world-entity readers are stateless -- positions are the list both
 * sides rebuild during the packet; the npc ones take `lengths` / `ctx` to
 * answer CUSTOM_TYPED (NULL ends the tail there).
 */
typedef int (*RsprotPlayerInfoReadFn)(
    RsprotPlayerInfo *pi, const uint8_t *data, int32_t len, RsprotInfoOp *ops, int cap,
    int *complete);
typedef int (*RsprotNpcInfoReadFn)(
    const uint8_t *data, int32_t len, RsprotNpcTypeLengths lengths, void *ctx, RsprotInfoOp *ops,
    int cap, int *complete);

typedef int (*RsprotWorldEntityInfoReadFn)(
    const uint8_t *data, int32_t len, RsprotInfoOp *ops, int cap, int *complete);

/** A prot file's revision -> layout rows, as RsprotVersionRange is a codec's. */
typedef struct RsprotPlayerInfoRange
{
    int rev_lo;
    int rev_hi;
    RsprotPlayerInfoReadFn fn;
} RsprotPlayerInfoRange;

typedef struct RsprotNpcInfoRange
{
    int rev_lo;
    int rev_hi;
    RsprotNpcInfoReadFn fn;
} RsprotNpcInfoRange;

typedef struct RsprotWorldEntityInfoRange
{
    int rev_lo;
    int rev_hi;
    RsprotWorldEntityInfoReadFn fn;
} RsprotWorldEntityInfoRange;

