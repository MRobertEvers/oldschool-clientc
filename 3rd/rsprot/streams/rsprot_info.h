/*
 * A reader writes what it decoded as a flat list of ops, in wire order -- the
 * shape the client's own readers have always produced (pkt_player_info.h), in
 * this library's revision-independent vocabulary. A block's scalars are one
 * BLOCK op; a block's lists (spot anims, hits, headbars, models, ...) follow it
 * as one op per entry, so nothing here is sized for the worst case.
 *
 * Strings and blobs are BORROWED from the payload and valid while it is. A
 * blob that arrives obfuscated (the appearance block, chat's huffman bytes)
 * carries its byte order; rsprot_info_copy_data puts it in natural order.
 */

typedef enum RsprotInfoOpKind
{
    RSPROT_IO_NONE = 0,

    /* PLAYER_INFO's bit sections. `who` is the slot, 1..2047. */
    /** `move`: now at absolute CoordGrid `coord` ((level << 28) | (x << 14) |
     *  z); `how` 0 entered from low resolution, 1 walked, 2 ran, 3 teleported. */
    RSPROT_IO_PLAYER_MOVE,
    /** Stood still, with extended info this tick. */
    RSPROT_IO_PLAYER_STILL,
    /** Left high resolution. */
    RSPROT_IO_PLAYER_REMOVE,

    /* NPC_INFO's bit sections. */
    /** `count`: the first `count` previous-list entries are described next. */
    RSPROT_IO_NPC_COUNT,
    /** Previous-list entry `who` is kept; `moved` 0 unchanged, 1 described (a
     *  step or extended info follows). */
    RSPROT_IO_NPC_KEEP,
    /** Previous-list entry `who` is dropped. */
    RSPROT_IO_NPC_REMOVE,
    /** `step`, for the npc just kept: speed 0 crawl, 1 walk, 2 run. */
    RSPROT_IO_NPC_STEP,
    /** `add`: a new npc at list position `who`. */
    RSPROT_IO_NPC_ADD,

    /* WORLDENTITY_INFO_V3..V7. An update entry's `who` is its position in the
     * active world's entity list; a spawn's is the entity index. */
    RSPROT_IO_WE_COUNT,  /* `count`: the entries the update section walks */
    RSPROT_IO_WE_REMOVE, /* the entity at `who` leaves the list */
    RSPROT_IO_WE_IDLE,   /* `we_move`, no deltas: stays (extended info from V6) */
    RSPROT_IO_WE_MOVE,   /* `we_move` */
    RSPROT_IO_WE_ADD,    /* `we_add`: an entity enters, at the end of the list */

    /* Extended info, both streams. `who` is the player slot or npc list
     * position. */
    /** The ops up to the next EXT_BEGIN belong to `who`. */
    RSPROT_IO_EXT_BEGIN,
    /** `block`: one block's scalar fields; its list entries follow. */
    RSPROT_IO_BLOCK,
    RSPROT_IO_SPOT,      /* `spot` (SPOTANIM) */
    RSPROT_IO_HIT,       /* `hit` (HITS, HITMARKS) */
    RSPROT_IO_BAR,       /* `bar` (HITS, HEADBARS) */
    RSPROT_IO_MODEL,     /* `item` (CUSTOM_*) */
    RSPROT_IO_RECOLOUR,  /* `item` (CUSTOM_*) */
    RSPROT_IO_RETEXTURE, /* `item` (CUSTOM_*) */
    RSPROT_IO_IDENTKIT,  /* `item` (CUSTOM_V3 / V4) */
    RSPROT_IO_HEADICON,  /* `headicon` (HEADICON_CUSTOM: the slots that are set) */
} RsprotInfoOpKind;

