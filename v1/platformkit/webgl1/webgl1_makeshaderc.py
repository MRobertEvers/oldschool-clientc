#!/usr/bin/env python3
"""Generate webgl1_shaders.h from GLSL sources in shaders/."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_SHADER_DIR = SCRIPT_DIR / "shaders"
DEFAULT_OUTPUT = SCRIPT_DIR / "webgl1_shaders.h"

HEADER_GUARD = "TORIRS_PLATFORM_KIT_WEBGL1_SHADERS_H"

SHADERS = (
    ("vertex.glsl", "trspk_webgl1_vertex_shader"),
    ("fragment.glsl", "trspk_webgl1_fragment_shader"),
)


def c_string_literal_lines(source: str) -> list[str]:
    """Format shader source as C string literal fragments (one per line)."""
    if not source.endswith("\n"):
        source += "\n"
    lines = source.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    parts: list[str] = []
    for line in lines:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        parts.append(f'"{escaped}\\n"')
    return parts


def emit_shader(symbol: str, source: str) -> list[str]:
    """Emit a static const char* initialized from concatenated string literals."""
    parts = c_string_literal_lines(source)
    if len(parts) == 1:
        return [f"static const char* {symbol} = {parts[0]};"]
    lines = [f"static const char* {symbol} ="]
    lines.extend(f"    {part}" for part in parts[:-1])
    lines.append(f"    {parts[-1]};")
    return lines


def emit_header(shaders: list[tuple[str, str]]) -> str:
    lines = [
        f"/* Generated by webgl1_makeshaderc.py — do not edit. */",
        f"#ifndef {HEADER_GUARD}",
        f"#define {HEADER_GUARD}",
        "",
        "// clang-format off",
    ]
    for symbol, source in shaders:
        lines.extend(emit_shader(symbol, source))
        lines.append("")
    lines.append("// clang-format on")
    lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def read_shader(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(path)
    return path.read_text(encoding="utf-8")


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--shader-dir",
        type=Path,
        default=DEFAULT_SHADER_DIR,
        help=f"directory containing vertex.glsl and fragment.glsl (default: {DEFAULT_SHADER_DIR})",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"output header path (default: {DEFAULT_OUTPUT})",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    shader_dir = args.shader_dir.resolve()
    output = args.output.resolve()

    pairs: list[tuple[str, str]] = []
    for filename, symbol in SHADERS:
        pairs.append((symbol, read_shader(shader_dir / filename)))

    output.write_text(emit_header(pairs), encoding="utf-8", newline="\n")
    print(f"wrote {output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
